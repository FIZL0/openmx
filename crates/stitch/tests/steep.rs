//! C9: a tile whose cut runs through a steep hill (a 3:1 edge) joins a flat one at the default
//! max_slope 0.5. Its seam gate on that edge is set by the edge's own extension, so the rideable gate
//! asks for 0.5 where the ground can be held to it, and the widening is left to the blend.

use std::path::{Path, PathBuf};
use stitch::build::{Params, build};

fn scratch(name: &str) -> PathBuf {
    let d = Path::new(env!("CARGO_TARGET_TMPDIR")).join("stitch-steep").join(name);
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    d
}

/// The mesa's height, and its flanks' softness: `H/2 (1 + tanh(u / K))` is steepest at `u = 0`, `H / 2K` ≈ 3.1.
const MESA: f64 = 300.0;
const SOFT: f64 = 48.0;

/// A mesa `MESA` ft high and 600 ft across z, from the x = 0 side to 300 ft inside the cut, its flanks
/// 3:1 at their steepest: the interior's x0 edge (153 ft in) runs up one flank, across the top and
/// down the other: a steep edge with relief (mc09's steepest edge cell is 3.1 over 125 ft of relief;
/// mxu_nat17's 22.5 over 1,113 ft).
fn mesa(x: f64, z: f64, mid: f64) -> f64 {
    let rise = |u: f64| 0.5 * (1.0 + (u / SOFT).tanh());
    MESA * rise(z - (mid - 300.0)) * rise((mid + 300.0) - z) * rise(453.0 - x)
}

/// A generated track mod `elev_steep_<name>`: `n + 1` samples a side at 4.5 ft, flat-ish ground at `base`,
/// no berm (so only the 150 ft shootoff band is cut), and with `hill` the [`mesa`] on its x = 0 side.
fn tile(root: &Path, name: &str, n: u32, base: f64, surface: u8, hill: bool) -> PathBuf {
    let id = format!("elev_steep_{name}");
    let dir = root.join(&id);
    std::fs::create_dir_all(&dir).unwrap();
    let s = 4.5f32;
    let w = n + 1;
    let mid = f64::from(n) * f64::from(s) / 2.0;
    let feet: Vec<f32> = (0..w * w)
        .map(|i| {
            let (x, z) = (f64::from(i % w) * f64::from(s), f64::from(i / w) * f64::from(s));
            let bump = if hill { mesa(x, z, mid) } else { 0.0 };
            (base + 2.0 * (x / 210.0).sin() * (z / 250.0).cos() + bump) as f32
        })
        .collect();
    let (mut g, hs) = trnwrite::Grid::from_feet(w, w, &feet, s).unwrap();
    g.surfaces = vec![surface; (w * w) as usize];
    let trn = trnwrite::build(&g, &trnwrite::Options::new(s, hs)).unwrap();
    let (bytes, _) = trnwrite::write(&trn).unwrap();
    std::fs::write(dir.join(format!("{id}.ps2.trn")), bytes).unwrap();
    let m = mid as f32;
    let scene = trnwrite::scene::SceneText::for_terrain(&trn, &id, [m, base as f32, m], [0.0, 0.0, 1.0]).to_text();
    std::fs::write(dir.join(format!("{id}.scn")), scene).unwrap();
    std::fs::write(
        dir.join("mod.json"),
        format!(
            r#"{{"standard": 1, "kind": "track", "id": "{id}", "name": "Test {name}",
 "source": {{"game": "Real elevation", "data": "generated by stitch's tests", "date": "2026-10-22"}},
 "version": "1.0.0", "author": "stitch tests", "permission": "public-domain",
 "todo": ["generated test map"]}}"#
        ),
    )
    .unwrap();
    dir
}

#[test]
fn a_steep_edge_beside_a_flat_one_builds_at_half() {
    let root = scratch("two");
    let mods = root.join("mods");
    let flat = tile(&mods, "flat", 512, 100.0, 1, false);
    let hill = tile(&mods, "hill", 512, 100.0, 3, true);

    // The hill really is cut at 3:1: its interior's x0 edge has cells that steep.
    let t = stitch::Tile::load(&hill).unwrap();
    let keep = t.find_keep();
    assert_eq!(keep[0], 34, "only the shootoff band is cut on the hill's side: {keep:?}");
    let ring = t.ring(keep);
    let steepest = ring.edges[0].iter().map(|e| e.gx.hypot(e.gz)).fold(0.0, f64::max);
    assert!(steepest >= 3.0, "the edge's steepest cell is {steepest:.2}, not 3:1");
    let flat_steepest = ring.edges[2].iter().map(|e| e.gx.hypot(e.gz)).fold(0.0, f64::max);
    assert!(flat_steepest < 0.1, "the far edge is {flat_steepest:.2}");

    let mut p = Params::new("world_steep", "Test world steep");
    p.threads = 8;
    p.chunk = 128;
    assert_eq!(p.max_slope, 0.5);
    let b = build(&[flat.clone(), hill.clone()], &root.join("out"), &p).unwrap();
    assert!(b.far_slope <= 0.5, "far slope {}", b.far_slope);

    // The hill's x0 edge has its own gate, past C1's 2 lattice + 3 fade; its other edges and the flat
    // tile keep C1's.
    let base = 2.0 * 4.5 + 3.0 * p.fade;
    let src = &b.plan.sources[1];
    assert!(src.gates[0] > base + 50.0, "the steep edge's gate {:?}", src.gates);
    for e in 1..4 {
        assert_eq!(src.gates[e], base, "edge {e}: {:?}", src.gates);
    }
    assert_eq!(b.plan.sources[0].gates, [base; 4]);

    // Next to the hill, inside its gate, the ground really is steeper than 0.5 (the gate is not slack);
    // and the flat tile faces it across the gap.
    assert!(b.near_slope > 1.0, "near slope {}", b.near_slope);
    assert!(b.plan.sources[0].rect[2] < src.rect[0], "the flat tile is not west of the hill");

    // mod.json says so, and stitch check reads the gate back and passes.
    let meta = std::fs::read_to_string(b.dir.join("mod.json")).unwrap();
    assert!(meta.contains("\"gates\""), "no stitch.gates");
    assert!(meta.contains("elev_steep_hill: its edges' own relief"), "no todo for the hill");
    let r = stitch::check::check(&b.dir, Some(&mods));
    assert!(r.ok(), "check failed:\n{}", r.fail.join("\n"));
    assert!(r.far_slope <= 0.5, "check's far slope {}", r.far_slope);
}
