//! openmx MD53: a map with a rock face at its edge (MX Unleashed's nat17 stands a mountain about 900 ft
//! square in its x1/z1 corner) is cut past the rock, so no seam of the world runs through it: the seam
//! walk openmx's `--seams` prints finds no step over 0.75 ft between rays a quarter of a foot apart.
//! The join meets the tile's edge either way; through the rock, the tile's own last cell was 16 ft a
//! foot and the step was the slope. A map with no rock is cut where it was.

use ps2_float::F;
use std::path::{Path, PathBuf};
use stitch::build::{Params, build};
use stitch::openmx;

fn scratch(name: &str) -> PathBuf {
    let d = Path::new(env!("CARGO_TARGET_TMPDIR")).join("stitch-rock").join(name);
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    d
}

/// Samples a side, at [`S`] ft: two root cells.
const N: u32 = 512;
const S: f32 = 9.0;
/// How far the mountain reaches in from the x1 and z1 edges, in samples.
const ROCK: u32 = 120;

/// Gentle hills, with no berm (the cut is the 150 ft shootoff band, 17 samples).
fn hills(x: f64, z: f64) -> f64 {
    130.0 + 4.0 * (x / 190.0).sin() * (z / 230.0).cos()
}

/// The hills, and in the x1/z1 corner a mountain of rock: 300 ft over them, each sample up to 150 ft
/// more by a hash of its place (no period a line across it could fall in step with).
fn mountain(x: f64, z: f64) -> f64 {
    let (r, edge) = (f64::from(ROCK) * f64::from(S), f64::from(N) * f64::from(S));
    let rock = edge - x < r && edge - z < r;
    let hash = ((x as u64).wrapping_mul(0x9e37_79b9_7f4a_7c15) ^ (z as u64).wrapping_mul(0xc2b2_ae3d_27d4_eb4f)).wrapping_mul(0x1656_67b1_9e37_79f9);
    hills(x, z) + if rock { 300.0 + 150.0 * (hash >> 40) as f64 / (1u64 << 24) as f64 } else { 0.0 }
}

/// A generated track mod `elev_rock_<name>` with `height(x, z)`.
fn tile(root: &Path, name: &str, height: fn(f64, f64) -> f64) -> PathBuf {
    let id = format!("elev_rock_{name}");
    let dir = root.join(&id);
    std::fs::create_dir_all(&dir).unwrap();
    let w = N + 1;
    let feet: Vec<f32> =
        (0..w * w).map(|i| height(f64::from(i % w) * f64::from(S), f64::from(i / w) * f64::from(S)) as f32).collect();
    let (mut g, hs) = trnwrite::Grid::from_feet(w, w, &feet, S).unwrap();
    g.surfaces = vec![1; (w * w) as usize];
    let trn = trnwrite::build(&g, &trnwrite::Options::new(S, hs)).unwrap();
    let (bytes, _) = trnwrite::write(&trn).unwrap();
    std::fs::write(dir.join(format!("{id}.ps2.trn")), bytes).unwrap();
    let mid = (f64::from(N) * f64::from(S) / 2.0) as f32;
    let scene = trnwrite::scene::SceneText::for_terrain(&trn, &id, [mid, 130.0, mid], [0.0, 0.0, 1.0]).to_text();
    std::fs::write(dir.join(format!("{id}.scn")), scene).unwrap();
    std::fs::write(
        dir.join("mod.json"),
        format!(
            r#"{{"standard": 1, "kind": "track", "id": "{id}", "name": "Test {name}",
 "source": {{"game": "Real elevation", "data": "generated by stitch's tests", "date": "2026-10-29"}},
 "version": "1.0.0", "author": "stitch tests", "permission": "public-domain",
 "todo": ["generated test map"]}}"#
        ),
    )
    .unwrap();
    dir
}

#[test]
fn a_map_with_rock_at_its_edge_is_cut_past_it_and_its_seams_have_no_step() {
    let root = scratch("world");
    let mods = root.join("mods");
    let a = tile(&mods, "a", mountain);
    let b = tile(&mods, "b", hills);

    // One side moves past the rock, the cheaper of the two it stands on (x1 on a tie); then the other
    // side's line no longer reaches the mountain and stays at the shootoff band.
    let ta = stitch::Tile::load(&a).unwrap();
    assert_eq!(ta.find_cut(), ([17, 17, N - ROCK, N - 17], [false; 4]));
    assert_eq!(ta.rock_cut(), [0, 0, ROCK - 17, 0]);
    let tb = stitch::Tile::load(&b).unwrap();
    assert_eq!(tb.find_cut(), ([17, 17, N - 17, N - 17], [false; 4]));
    assert_eq!(tb.rock_cut(), [0; 4]);

    let mut p = Params::new("world_rock", "Test world rock");
    p.threads = 8;
    let built = build(&[a, b], &root.join("out"), &p).unwrap();
    let meta = std::fs::read_to_string(built.dir.join("mod.json")).unwrap();
    assert!(meta.contains("cut past a rock face"), "the cut is in the todo: {meta}");
    let world = openmx::load(&built.dir).unwrap();
    let mut tiled = world.tiled().unwrap();
    let w = tiled.seam_walk(F(1.0), F(0.125));
    assert_eq!(w.gaps, 0, "{w:?}");
    assert!(w.met > 0, "{w:?}");
    assert!(w.steepest < F(0.75), "a step of {} ft at {:?} ({:?})", w.steepest.0, w.steepest_at, w.steepest_between);
}
