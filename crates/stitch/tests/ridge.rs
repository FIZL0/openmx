//! M23: a map ringed by a ridge behind a flat shootoff plateau (MX Unleashed's freeride maps) is cut at
//! the ridge's peak, so the world's maps meet ridge to ridge over a narrow join, not across two plateaus.
//! A map whose ground only climbs inward of its edge is cut at its berm as before. The world built of
//! two ringed maps has every tile's origin at or past 0 (openmx refuses a negative `at`), no ground left
//! to no one, and one ridge across its join.

use stitch::json::Json;
use ps2_float::F;
use std::path::{Path, PathBuf};
use stitch::build::{Params, build};
use stitch::openmx;

fn scratch(name: &str) -> PathBuf {
    let d = Path::new(env!("CARGO_TARGET_TMPDIR")).join("stitch-ridge").join(name);
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    d
}

/// Samples a side, at [`S`] ft: two root cells.
const N: u32 = 512;
const S: f32 = 9.0;
/// Where the ridge's peak stands, in samples from each edge (MX Unleashed's: 87 and 88 at 9 ft).
const PEAK: u32 = 88;

/// The freeride ring by distance `d` (feet) from the nearest edge: a 189.9 ft plateau out to 630 ft,
/// a ridge rising to 250 ft at its peak and falling to a 115 ft valley floor 208 ft inward, then the
/// map's own gentle hills.
fn ringed(d: f64, x: f64, z: f64) -> f64 {
    let ease = |t: f64| {
        let t = t.clamp(0.0, 1.0);
        t * t * (3.0 - 2.0 * t)
    };
    let peak = f64::from(PEAK) * f64::from(S);
    if d < 630.0 {
        189.9
    } else if d < peak {
        189.9 + 60.1 * ease((d - 630.0) / (peak - 630.0))
    } else if d < peak + 208.0 {
        250.0 - 135.0 * ease((d - peak) / 208.0)
    } else {
        115.0 + 4.0 * (x / 190.0).sin() * (z / 230.0).cos()
    }
}

/// Ground that climbs inward from the edge to a hill 700 ft in and falls again, with no plateau.
fn rising(d: f64, x: f64, z: f64) -> f64 {
    130.0 + 60.0 * (-((d - 700.0) / 250.0).powi(2)).exp() + 3.0 * (x / 170.0).sin() * (z / 210.0).cos()
}

/// A generated track mod `elev_ridge_<name>` with `height(d, x, z)`.
fn tile(root: &Path, name: &str, height: fn(f64, f64, f64) -> f64) -> PathBuf {
    let id = format!("elev_ridge_{name}");
    let dir = root.join(&id);
    std::fs::create_dir_all(&dir).unwrap();
    let w = N + 1;
    let edge = f64::from(N) * f64::from(S);
    let feet: Vec<f32> = (0..w * w)
        .map(|i| {
            let (x, z) = (f64::from(i % w) * f64::from(S), f64::from(i / w) * f64::from(S));
            height(x.min(z).min(edge - x).min(edge - z), x, z) as f32
        })
        .collect();
    let (mut g, hs) = trnwrite::Grid::from_feet(w, w, &feet, S).unwrap();
    g.surfaces = vec![1; (w * w) as usize];
    let trn = trnwrite::build(&g, &trnwrite::Options::new(S, hs)).unwrap();
    let (bytes, _) = trnwrite::write(&trn).unwrap();
    std::fs::write(dir.join(format!("{id}.ps2.trn")), bytes).unwrap();
    let mid = (edge / 2.0) as f32;
    let scene = trnwrite::scene::SceneText::for_terrain(&trn, &id, [mid, 120.0, mid], [0.0, 0.0, 1.0]).to_text();
    std::fs::write(dir.join(format!("{id}.scn")), scene).unwrap();
    std::fs::write(
        dir.join("mod.json"),
        format!(
            r#"{{"standard": 1, "kind": "track", "id": "{id}", "name": "Test {name}",
 "source": {{"game": "Real elevation", "data": "generated by stitch's tests", "date": "2026-10-23"}},
 "version": "1.0.0", "author": "stitch tests", "permission": "public-domain",
 "todo": ["generated test map"]}}"#
        ),
    )
    .unwrap();
    dir
}

#[test]
fn a_ringed_map_is_cut_at_its_ridge_and_two_meet_ridge_to_ridge() {
    let root = scratch("world");
    let mods = root.join("mods");
    let a = tile(&mods, "a", ringed);
    let b = tile(&mods, "b", ringed);
    let c = tile(&mods, "c", rising);

    let ta = stitch::Tile::load(&a).unwrap();
    assert_eq!(ta.find_cut(), ([PEAK, PEAK, N - PEAK, N - PEAK], [true; 4]));
    // No plateau, no ridge cut: the shootoff band alone (17 samples at 9 ft), as before M23.
    let tc = stitch::Tile::load(&c).unwrap();
    assert_eq!(tc.find_cut(), ([17, 17, N - 17, N - 17], [false; 4]));

    let mut p = Params::new("world_ridge", "Test world ridge");
    p.threads = 8;
    p.chunk = 64;
    p.min_gap = 120.0;
    let built = build(&[a, b], &root.join("out"), &p).unwrap();
    let plan = &built.plan;
    for pl in &plan.placed {
        assert!(pl.at[0] >= 0.0 && pl.at[1] >= 0.0, "a tile at {:?}", pl.at);
        assert_eq!(pl.keep, [PEAK, PEAK, N - PEAK, N - PEAK]);
    }
    // The two interiors side by side along x, the join between them no wider than the blend's rooms
    // and a leaf of rounding.
    let r: Vec<[f64; 4]> = plan.sources.iter().map(|s| s.rect).collect();
    let (lo, hi) = if r[0][0] < r[1][0] { (r[0], r[1]) } else { (r[1], r[0]) };
    let gap = hi[0] - lo[2];
    assert!((p.min_gap..p.min_gap + 16.0 * f64::from(S)).contains(&gap), "gap {gap} ft between {lo:?} and {hi:?}");

    let meta = Json::parse(&std::fs::read_to_string(built.dir.join("mod.json")).unwrap()).unwrap();
    let todo: Vec<&str> = meta.get("todo").and_then(Json::arr).unwrap().iter().filter_map(Json::str).collect();
    for id in ["elev_ridge_a", "elev_ridge_b"] {
        assert!(todo.iter().any(|t| t.starts_with(&format!("{id}: cut at its ring's ridge on x0 z0 x1 z1"))), "{id}: {todo:?}");
    }
    let r2 = stitch::check::check(&built.dir, Some(&mods));
    assert!(r2.ok(), "check failed:\n{}", r2.fail.join("\n"));

    // As openmx loads it: no ground left to no one, and across the join one ridge, the join no lower
    // than the lower of the two peaks it joins less a few feet (the plateau between was 60 ft lower).
    let w = openmx::load(&built.dir).unwrap();
    let tiled = w.tiled().unwrap();
    let (asked, none, first) = openmx::holes(&tiled, 3.0);
    assert_eq!(none, 0, "{none} of {asked} points own nothing, first {first:?}");
    let (asked, none, first) = openmx::strips(&w, &tiled, 1.0);
    assert_eq!(none, 0, "{none} of {asked} edge points own nothing: {first:?}");
    let z = ((lo[1].max(hi[1]) + lo[3].min(hi[3])) / 2.0) as f32;
    let y = |x: f64| tiled.at(F(x as f32), F(z)).unwrap().y.0;
    let floor = y(lo[2]).min(y(hi[0])) - 5.0;
    let mut x = lo[2];
    while x <= hi[0] {
        assert!(y(x) >= floor, "the join dips to {} ft at x {x} between peaks of {} and {}", y(x), y(lo[2]), y(hi[0]));
        x += 1.0;
    }
}
