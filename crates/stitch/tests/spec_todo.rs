//! C10: a world spec's `todo` lines (a gap the spec chose, such as a raised `max_slope`) are in the
//! world's mod.json todo, after stitch's own.

use stitch::json::Json;
use std::path::{Path, PathBuf};
use stitch::build::{Params, build};

fn scratch(name: &str) -> PathBuf {
    let d = Path::new(env!("CARGO_TARGET_TMPDIR")).join("stitch-spec-todo").join(name);
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    d
}

/// A generated track mod `elev_spec_<name>`: `n + 1` samples a side at 4.5 ft, gentle hills on `base`.
fn tile(root: &Path, name: &str, n: u32, base: f64) -> PathBuf {
    let id = format!("elev_spec_{name}");
    let dir = root.join(&id);
    std::fs::create_dir_all(&dir).unwrap();
    let s = 4.5f32;
    let w = n + 1;
    let feet: Vec<f32> = (0..w * w)
        .map(|i| {
            let (x, z) = (f64::from(i % w) * f64::from(s), f64::from(i / w) * f64::from(s));
            (base + 5.0 * (x / 190.0).sin() * (z / 230.0).cos() + 0.003 * z) as f32
        })
        .collect();
    let (mut g, hs) = trnwrite::Grid::from_feet(w, w, &feet, s).unwrap();
    g.surfaces = vec![1; (w * w) as usize];
    let trn = trnwrite::build(&g, &trnwrite::Options::new(s, hs)).unwrap();
    let (bytes, _) = trnwrite::write(&trn).unwrap();
    std::fs::write(dir.join(format!("{id}.ps2.trn")), bytes).unwrap();
    let mid = (f64::from(n) * f64::from(s) / 2.0) as f32;
    let scene = trnwrite::scene::SceneText::for_terrain(&trn, &id, [mid, base as f32, mid], [0.0, 0.0, 1.0]).to_text();
    std::fs::write(dir.join(format!("{id}.scn")), scene).unwrap();
    std::fs::write(
        dir.join("mod.json"),
        format!(
            r#"{{"standard": 1, "kind": "track", "id": "{id}", "name": "Test {name}",
 "source": {{"game": "Real elevation", "data": "generated by stitch's tests", "date": "2026-10-22"}},
 "version": "1.0.0", "author": "stitch tests", "permission": "public-domain",
 "todo": ["generated test map"]}}"#
        ),
    )
    .unwrap();
    dir
}

#[test]
fn a_spec_carries_its_todo_lines_into_the_world() {
    let root = scratch("two");
    let mods = root.join("mods");
    let a = tile(&mods, "a", 256, 100.0);
    let b = tile(&mods, "b", 256, 110.0);
    let why = "max_slope 2: the join beside elev_spec_a is not rideable at 0.5 (test)";
    let mut p = Params::new("world_spec", "Test world spec todo");
    p.threads = 8;
    p.chunk = 64;
    p.max_slope = 2.0;
    p.todo = vec![why.to_owned()];
    let built = build(&[a, b], &root.join("out"), &p).unwrap();
    let meta = Json::parse(&std::fs::read_to_string(built.dir.join("mod.json")).unwrap()).unwrap();
    let todo: Vec<&str> = meta.get("todo").and_then(Json::arr).unwrap().iter().filter_map(Json::str).collect();
    assert_eq!(todo.iter().filter(|t| **t == why).count(), 1, "todo: {todo:?}");
    assert!(todo[0].starts_with("joins/*: generated ground"), "stitch's own lines first: {todo:?}");
    let r = stitch::check::check(&built.dir, Some(&mods));
    assert!(r.ok(), "check failed:\n{}", r.fail.join("\n"));
}
