//! C11: the combined and ultra maps as openmx loads them (`stitch::openmx`, openmx's `worlds::find`
//! over game-sim's `Tiled`).
//!
//! On generated worlds: every tile's ground in the world is its own track mod's alone, to the bit,
//! every join's is its file's and stitch's field at its samples, and an ultra map of two such worlds
//! answers the same under every piece. The ignored test builds world_mxu, world_mxvatv, world_untamed
//! and world_ultra from their specs off the three discs and holds each to the same.

use std::path::{Path, PathBuf};
use stitch::build::{Params, build};
use stitch::openmx::{self, Summary};

fn scratch(name: &str) -> PathBuf {
    let d = Path::new(env!("CARGO_TARGET_TMPDIR")).join("stitch-openmx").join(name);
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    d
}

/// A generated track mod `elev_c11_<name>`: `n + 1` samples a side at `s` ft, hills on `base`.
fn tile(root: &Path, name: &str, n: u32, s: f32, base: f64, surface: u8) -> PathBuf {
    let id = format!("elev_c11_{name}");
    let dir = root.join(&id);
    std::fs::create_dir_all(&dir).unwrap();
    let w = n + 1;
    let feet: Vec<f32> = (0..w * w)
        .map(|i| {
            let (x, z) = (f64::from(i % w) * f64::from(s), f64::from(i / w) * f64::from(s));
            (base + 8.0 * (x / 190.0).sin() * (z / 230.0).cos() + 0.3 * (x / 7.0).sin() + 0.005 * z) as f32
        })
        .collect();
    let (mut g, hs) = trnwrite::Grid::from_feet(w, w, &feet, s).unwrap();
    g.surfaces = (0..w * w).map(|i| surface + (i % 3) as u8).collect();
    let trn = trnwrite::build(&g, &trnwrite::Options::new(s, hs)).unwrap();
    let (bytes, _) = trnwrite::write(&trn).unwrap();
    std::fs::write(dir.join(format!("{id}.ps2.trn")), bytes).unwrap();
    let mid = (f64::from(n) * f64::from(s) / 2.0) as f32;
    let scene = trnwrite::scene::SceneText::for_terrain(&trn, &id, [mid, base as f32, mid], [0.0, 0.0, 1.0]).to_text();
    std::fs::write(dir.join(format!("{id}.scn")), scene).unwrap();
    std::fs::write(
        dir.join("mod.json"),
        format!(
            r#"{{"standard": 1, "kind": "track", "id": "{id}", "name": "Test {name}",
 "source": {{"game": "Real elevation", "data": "generated by stitch's tests", "date": "2026-10-23"}},
 "version": "1.0.0", "author": "stitch tests", "permission": "public-domain",
 "todo": ["generated test map",
          "{id}.scn: TerrainWidthScale and TerrainBreadthScale print the scale in fewer digits than the terrain's"]}}"#
        ),
    )
    .unwrap();
    dir
}

/// Every count of a world's summary that must be 0 is, and enough points were asked.
fn assert_clean(what: &str, s: &Summary, joins_fielded: bool) {
    for (part, c) in [("tiles", &s.tiles), ("joins", &s.joins)] {
        assert!(c.differ == 0 && c.field_over == 0, "{what} {part}: {} differ, {} off stitch's field\n{}", c.differ, c.field_over, c.first.join("\n"));
        assert!(c.points > 1000, "{what} {part}: {} points", c.points);
    }
    if joins_fielded {
        assert!(s.joins.field_points > 1000, "{what}: {} join samples against the field", s.joins.field_points);
    }
    assert_eq!(s.holes, 0, "{what}: no ground at {:?}", s.first_holes);
}

/// Every foot of the world's rectangle is some piece's: no strip between two joins that openmx leaves
/// to no one (its last row and column of a terrain), which throws a rider back 150 ft before it.
fn assert_no_strips(w: &openmx::World) {
    let (asked, none, first) = openmx::holes(&w.tiled().unwrap(), 1.0);
    assert_eq!(none, 0, "{}: {none} of {asked} points a foot apart have no ground, first {first:?}", w.id);
}

/// A world of three generated maps, two at 4.5 ft and one at 3.5 (so it has a collar), loaded as
/// openmx loads it: each tile's ground is its mod's alone, each join's is its file's, and at every
/// fourth join sample the height stitch solved.
#[test]
fn a_world_in_openmx_is_its_maps_and_stitchs_ground() {
    let root = scratch("world");
    let mods = root.join("mods");
    let dirs = vec![tile(&mods, "a", 512, 4.5, 100.0, 1), tile(&mods, "b", 512, 4.5, 130.0, 4), tile(&mods, "c", 512, 3.5, 115.0, 7)];
    let mut p = Params::new("world_c11", "Test world C11");
    p.threads = 4;
    let built = build(&dirs, &root.join("out"), &p).unwrap();
    assert!(!built.plan.collars.is_empty(), "no collar");
    let tiles: Vec<stitch::Tile> = dirs.iter().map(|d| stitch::Tile::load(d).unwrap()).collect();
    let terrains: Vec<_> = tiles.iter().map(stitch::Tile::terrain).collect();
    let plan = &built.plan;
    let field = |x: f64, z: f64| plan.at(&tiles, &terrains, &plan.candidates([x, z, x, z]), x, z).h;
    let w = openmx::load(&built.dir).unwrap();
    assert_eq!((w.tile_count, w.pieces.len() - w.tile_count), (3, plan.pieces(p.chunk).len()));
    let s = openmx::check_world(&w, &|t: &str| mods.join(t), Some(&field), 24, 4, 4).unwrap();
    println!("tiles {:?}\njoins {:?}", s.tiles, s.joins);
    assert_clean("world_c11", &s, true);
    assert_no_strips(&w);
}
