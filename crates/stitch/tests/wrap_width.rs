//! openmx MD61: a wrapped world's joins across the wrap are as narrow as its stitched ones, however deep
//! its first line's tiles are cut.
//!
//! A freeride map is cut at its ridge, 792 ft in (M23), and openmx used to refuse a tile origin below 0,
//! so the first line stood that far in and every join across the wrap was that much wider than the
//! joins between lines: world_mxu_free's Norfolk→Dallas join over the x seam was 927 ft against 135 ft
//! stitched (after openmx-mods 3c2c2fd). game-sim now lets a tile stand at a negative `at` while its kept
//! cells start at or past 0, and on a wrapped axis the first line starts two lattice cells in, its cut
//! ridge past the near seam. Four ringed maps in a 2×2 grid, cut at their ridges on every side.

use ps2_float::F;
use std::path::{Path, PathBuf};
use stitch::build::{Params, build, gap_for};
use stitch::openmx;

fn scratch(name: &str) -> PathBuf {
    let d = Path::new(env!("CARGO_TARGET_TMPDIR")).join("stitch-wrap-width").join(name);
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    d
}

/// Samples a side, at [`S`] ft: two root cells.
const N: u32 = 512;
const S: f32 = 9.0;
/// Where the ridge's peak stands, in samples from each edge (MX Unleashed's: 87 and 88 at 9 ft).
const PEAK: u32 = 88;

/// The freeride ring by distance `d` (feet) from the nearest edge: a 189.9 ft plateau out to 630 ft,
/// a ridge rising to 250 ft at its peak and falling to a 115 ft valley floor 208 ft inward, then the
/// map's own gentle hills.
fn ringed(d: f64, x: f64, z: f64) -> f64 {
    let ease = |t: f64| {
        let t = t.clamp(0.0, 1.0);
        t * t * (3.0 - 2.0 * t)
    };
    let peak = f64::from(PEAK) * f64::from(S);
    if d < 630.0 {
        189.9
    } else if d < peak {
        189.9 + 60.1 * ease((d - 630.0) / (peak - 630.0))
    } else if d < peak + 208.0 {
        250.0 - 135.0 * ease((d - peak) / 208.0)
    } else {
        115.0 + 4.0 * (x / 190.0).sin() * (z / 230.0).cos()
    }
}

/// A generated track mod `elev_md61_<name>` with `height(d, x, z)`.
fn tile(root: &Path, name: &str, height: fn(f64, f64, f64) -> f64) -> PathBuf {
    let id = format!("elev_md61_{name}");
    let dir = root.join(&id);
    std::fs::create_dir_all(&dir).unwrap();
    let w = N + 1;
    let edge = f64::from(N) * f64::from(S);
    let feet: Vec<f32> = (0..w * w)
        .map(|i| {
            let (x, z) = (f64::from(i % w) * f64::from(S), f64::from(i / w) * f64::from(S));
            height(x.min(z).min(edge - x).min(edge - z), x, z) as f32
        })
        .collect();
    let (mut g, hs) = trnwrite::Grid::from_feet(w, w, &feet, S).unwrap();
    g.surfaces = vec![1; (w * w) as usize];
    let trn = trnwrite::build(&g, &trnwrite::Options::new(S, hs)).unwrap();
    let (bytes, _) = trnwrite::write(&trn).unwrap();
    std::fs::write(dir.join(format!("{id}.ps2.trn")), bytes).unwrap();
    let mid = (edge / 2.0) as f32;
    let scene = trnwrite::scene::SceneText::for_terrain(&trn, &id, [mid, 120.0, mid], [0.0, 0.0, 1.0]).to_text();
    std::fs::write(dir.join(format!("{id}.scn")), scene).unwrap();
    std::fs::write(
        dir.join("mod.json"),
        format!(
            r#"{{"standard": 1, "kind": "track", "id": "{id}", "name": "Test {name}",
 "source": {{"game": "Real elevation", "data": "generated by stitch's tests", "date": "2026-11-04"}},
 "version": "1.0.0", "author": "stitch tests", "permission": "public-domain",
 "todo": ["generated test map"]}}"#
        ),
    )
    .unwrap();
    dir
}

/// Each row's (column's) gap across the wrap, `period − last.x1 + first.x0`, is at least the gap its
/// pair needs ([`gap_for`], as between any two lines) and no wider than a stitched gap on that axis
/// plus a leaf (each line's origin is rounded up to one); the first line's tiles stand short of 0; and
/// openmx's closed world has ground at every point of its seams.
#[test]
fn the_joins_across_the_wrap_are_as_narrow_as_the_stitched_ones() {
    let root = scratch("world");
    let mods = root.join("mods");
    let dirs: Vec<PathBuf> = ["a", "b", "c", "d"].iter().map(|n| tile(&mods, n, ringed)).collect();
    let mut p = Params::new("world_md61", "Test world MD61");
    p.threads = 8;
    p.chunk = 64;
    p.min_gap = 120.0;
    p.wrap = Some("xz".into());
    let built = build(&dirs, &root.join("out"), &p).unwrap();
    let plan = &built.plan;
    let leaf = 16.0 * f64::from(S);
    let ridge = f64::from(PEAK) * f64::from(S);
    for pl in &plan.placed {
        assert_eq!(pl.keep, [PEAK, PEAK, N - PEAK, N - PEAK]);
    }
    for axis in 0..2 {
        let lines: std::collections::BTreeSet<usize> = plan.placed.iter().map(|pl| if axis == 0 { pl.cell.1 } else { pl.cell.0 }).collect();
        let mut stitched = p.min_gap;
        let mut wrap = Vec::new();
        for line in lines {
            let mut run: Vec<usize> = (0..plan.placed.len()).filter(|&t| (if axis == 0 { plan.placed[t].cell.1 } else { plan.placed[t].cell.0 }) == line).collect();
            run.sort_by(|&a, &b| plan.sources[a].rect[axis].total_cmp(&plan.sources[b].rect[axis]));
            for w in run.windows(2) {
                stitched = stitched.max(plan.sources[w[1]].rect[axis] - plan.sources[w[0]].rect[axis + 2]);
            }
            let (first, last) = (&plan.sources[run[0]], &plan.sources[*run.last().unwrap()]);
            let c = plan.placed[run[0]].cell;
            if (if axis == 0 { c.0 } else { c.1 }) == 0 {
                assert!(plan.placed[run[0]].at[axis] < 0.0, "axis {axis}: the first tile at {:?}", plan.placed[run[0]].at);
                assert!(first.rect[axis] < ridge, "axis {axis}: the first line's kept edge {} ft in", first.rect[axis]);
            }
            let room = |src: &stitch::Source, e: usize| src.gates[e] - (plan.spacing + 2.0 * p.fade);
            let dh = last.ring.edge_mean(axis + 2) - first.ring.edge_mean(axis);
            let need = gap_for(dh, &p, room(last, axis + 2) + room(first, axis), plan.widen);
            wrap.push((plan.period[axis] - last.rect[axis + 2] + first.rect[axis], need));
        }
        println!("axis {axis}: period {} ft, stitched joins up to {stitched} ft, across the wrap (gap, need) {wrap:?} ft", plan.period[axis]);
        for (g, need) in wrap {
            assert!(g >= need - 1e-9, "axis {axis}: {g} ft across the wrap, its pair needs {need} ft");
            assert!(g <= stitched + leaf, "axis {axis}: {g} ft across the wrap against {stitched} ft stitched");
        }
    }

    let r = stitch::check::check(&built.dir, Some(&mods));
    assert!(r.ok(), "check failed:\n{}", r.fail.join("\n"));
    let w = openmx::load(&built.dir).unwrap();
    let (t, seams, spacing) = w.closed().unwrap();
    assert!(seams > 0);
    assert_eq!(t.holes(), Vec::<[F; 4]>::new(), "openmx's world holes");
    let strip = (game_sim::tiles::generate::SEAM_CELLS * spacing) as f32;
    let (asked, none, step, at) = openmx::across_seams(&t, strip);
    println!("closed by {seams} seam joins {spacing} ft apart: {asked} points across the seams, steepest step {step} ft in half a foot at {at:?}");
    assert_eq!(none, 0, "points across the wrap with no ground");
    assert!(step < 0.5, "a {step} ft step in half a foot at {at:?}");
}
