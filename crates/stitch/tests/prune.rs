//! C7: the candidate pruning (a spatial grid and a radius per tile) changes nothing in what is built.

use std::path::{Path, PathBuf};
use stitch::build::{Params, build};

fn scratch(name: &str) -> PathBuf {
    let d = Path::new(env!("CARGO_TARGET_TMPDIR")).join("stitch-prune").join(name);
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    d
}

/// A generated track mod `elev_prune_<name>`: `n + 1` samples a side at 4.5 ft, gentle hills on `base`, no
/// berm (an MX vs. ATV map's flat edge, so only the shootoff band is cut).
fn tile(root: &Path, name: &str, n: u32, base: f64, surface: u8) -> PathBuf {
    let id = format!("elev_prune_{name}");
    let dir = root.join(&id);
    std::fs::create_dir_all(&dir).unwrap();
    let s = 4.5f32;
    let w = n + 1;
    let k = f64::from(surface);
    let feet: Vec<f32> = (0..w * w)
        .map(|i| {
            let (x, z) = (f64::from(i % w) * f64::from(s), f64::from(i / w) * f64::from(s));
            (base + 5.0 * (x / (190.0 + 9.0 * k)).sin() * (z / 230.0).cos() + 0.003 * z) as f32
        })
        .collect();
    let (mut g, hs) = trnwrite::Grid::from_feet(w, w, &feet, s).unwrap();
    g.surfaces = vec![surface; (w * w) as usize];
    let trn = trnwrite::build(&g, &trnwrite::Options::new(s, hs)).unwrap();
    let (bytes, _) = trnwrite::write(&trn).unwrap();
    std::fs::write(dir.join(format!("{id}.ps2.trn")), bytes).unwrap();
    let mid = (f64::from(n) * f64::from(s) / 2.0) as f32;
    let scene = trnwrite::scene::SceneText::for_terrain(&trn, &id, [mid, base as f32, mid], [0.0, 0.0, 1.0]).to_text();
    std::fs::write(dir.join(format!("{id}.scn")), scene).unwrap();
    std::fs::write(
        dir.join("mod.json"),
        format!(
            r#"{{"standard": 1, "kind": "track", "id": "{id}", "name": "Test {name}",
 "source": {{"game": "Real elevation", "data": "generated by stitch's tests", "date": "2026-10-22"}},
 "version": "1.0.0", "author": "stitch tests", "permission": "public-domain",
 "todo": ["generated test map"]}}"#
        ),
    )
    .unwrap();
    dir
}

/// Every file under a folder with its bytes, by relative path.
fn contents(dir: &Path) -> Vec<(String, Vec<u8>)> {
    stitch::files(dir).unwrap().into_iter().map(|f| (f.clone(), std::fs::read(dir.join(&f)).unwrap())).collect()
}

/// Nine maps in a 3 × 3 grid, one of them 220 ft above the rest (a wide gap on its two sides only):
/// built with every tile a candidate everywhere and again with the pruning, the two worlds are the same
/// to the byte (every join's heights, normals, surfaces and blend, and mod.json), so within the height
/// quantum. And the pruning did prune: the radii differ, and some join hears from fewer than nine tiles.
#[test]
fn the_world_is_the_same_with_and_without_the_pruning() {
    let root = scratch("nine");
    let mods = root.join("mods");
    let bases = [100.0, 104.0, 108.0, 112.0, 116.0, 120.0, 124.0, 128.0, 348.0];
    let dirs: Vec<PathBuf> = bases.iter().enumerate().map(|(i, b)| tile(&mods, &format!("{i}"), 256, *b, i as u8 + 1)).collect();
    let mut p = Params::new("world_prune", "Test world prune");
    p.threads = 8;
    p.chunk = 64;
    let pruned = build(&dirs, &root.join("pruned"), &p).unwrap();
    p.prune = false;
    let all = build(&dirs, &root.join("all"), &p).unwrap();

    let (a, b) = (contents(&pruned.dir), contents(&all.dir));
    assert_eq!(a.len(), b.len());
    let mut joins = 0;
    for ((fa, ba), (fb, bb)) in a.iter().zip(&b) {
        assert_eq!(fa, fb);
        assert!(ba == bb, "{fa} differs with the pruning");
        joins += usize::from(fa.starts_with("joins/"));
    }
    assert!(joins > 20, "{joins} join files");

    let plan = &pruned.plan;
    let (lo, hi) = plan.radii.iter().fold((f64::INFINITY, 0.0f64), |(lo, hi), r| (lo.min(*r), hi.max(*r)));
    assert!(hi > lo * 1.2, "radii {:?}", plan.radii);
    assert_eq!(plan.radius, hi);
    let fewest = plan
        .pieces(p.chunk)
        .iter()
        .map(|s| {
            let r = [s.at[0], s.at[1], s.at[0] + f64::from(s.cells[0]) * s.spacing, s.at[1] + f64::from(s.cells[1]) * s.spacing];
            plan.candidates(r).len()
        })
        .min()
        .unwrap();
    assert!(fewest < bases.len(), "every join hears from all {fewest} tiles");

    let r = stitch::check::check(&pruned.dir, Some(&mods));
    assert!(r.ok(), "check failed:\n{}", r.fail.join("\n"));
}
