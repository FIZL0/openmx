//! C8: a tile whose terrain tree has holes. Its interior is cut inside the cells that are there, so the
//! joins never read a missing cell as 0 ft, and the world passes `stitch check`.

use game_sim::track::Terrain;
use stitch::json::Json;
use std::path::{Path, PathBuf};
use stitch::build::{Params, build};

fn scratch(name: &str) -> PathBuf {
    let d = Path::new(env!("CARGO_TARGET_TMPDIR")).join("stitch-holes").join(name);
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    d
}

/// A generated track mod `elev_holes_<name>`: `w × h` root cells (256 samples each) at 4.5 ft, gentle
/// hills on `base`. `holes` lists the leaves (16 samples, `[x, z]` in leaves) whose child word is then
/// set to 0, as nat04's tree leaves them out. The spawn is at `spawn` (feet, x and z).
fn tile(root: &Path, name: &str, w: u32, h: u32, base: f64, holes: &[[u32; 2]], spawn: [f32; 2]) -> PathBuf {
    let id = format!("elev_holes_{name}");
    let dir = root.join(&id);
    std::fs::create_dir_all(&dir).unwrap();
    let s = 4.5f32;
    let (sw, sh) = (256 * w + 1, 256 * h + 1);
    let feet: Vec<f32> = (0..sw * sh)
        .map(|i| {
            let (x, z) = (f64::from(i % sw) * f64::from(s), f64::from(i / sw) * f64::from(s));
            (base + 5.0 * (x / 190.0).sin() * (z / 230.0).cos() + 0.003 * z) as f32
        })
        .collect();
    let (mut g, hs) = trnwrite::Grid::from_feet(sw, sh, &feet, s).unwrap();
    g.surfaces = vec![1; (sw * sh) as usize];
    let trn = trnwrite::build(&g, &trnwrite::Options::new(s, hs)).unwrap();
    let (mut bytes, _) = trnwrite::write(&trn).unwrap();
    // The tree's offsets are the same in the file and in its openmx view.
    let mut zero = Vec::new();
    {
        let view = trnwrite::openmx_view(&bytes).unwrap().into_owned();
        let t = Terrain::parse(&view).unwrap();
        assert!(holes.is_empty() || t.levels == 2);
        let rootn = t.root().unwrap();
        for &[lx, lz] in holes {
            let cell = t.node(t.child(&rootn, lx / 16, lz / 16).unwrap()).unwrap();
            zero.push(cell.children_at as usize + ((lx % 16) + (lz % 16) * 16) as usize * 4);
        }
    }
    for at in zero {
        bytes[at..at + 4].copy_from_slice(&[0; 4]);
    }
    std::fs::write(dir.join(format!("{id}.ps2.trn")), bytes).unwrap();
    let scene = trnwrite::scene::SceneText::for_terrain(&trn, &id, [spawn[0], base as f32, spawn[1]], [0.0, 0.0, 1.0]).to_text();
    std::fs::write(dir.join(format!("{id}.scn")), scene).unwrap();
    std::fs::write(
        dir.join("mod.json"),
        format!(
            r#"{{"standard": 1, "kind": "track", "id": "{id}", "name": "Test {name}",
 "source": {{"game": "Real elevation", "data": "generated by stitch's tests", "date": "2026-10-22"}},
 "version": "1.0.0", "author": "stitch tests", "permission": "public-domain",
 "todo": ["generated test map"]}}"#
        ),
    )
    .unwrap();
    dir
}

/// Three root cells across, two along. The first root cell column is missing whole, and the last has no
/// leaves past its half (nat04's shape: none past x = 640 of 768). The ground is the rectangle between,
/// the keep stops at both holes (with no shootoff band there, only the berm test), and a world of it and
/// a whole tile builds and passes `stitch check`.
#[test]
fn a_tile_with_missing_cells_is_cut_at_the_hole() {
    let root = scratch("world");
    let mods = root.join("mods");
    let mut holes = Vec::new();
    for lz in 0..32 {
        for lx in 0..16 {
            holes.push([lx, lz]);
        }
        for lx in 40..48 {
            holes.push([lx, lz]);
        }
    }
    let a = tile(&mods, "a", 3, 2, 100.0, &holes, [450.0 * 4.5, 256.0 * 4.5]);
    let b = tile(&mods, "b", 1, 1, 104.0, &[], [128.0 * 4.5, 128.0 * 4.5]);

    let ta = stitch::Tile::load(&a).unwrap();
    assert_eq!(ta.n, (768, 512));
    assert_eq!(ta.ground, [256, 0, 640, 512]);
    // The shootoff band is 34 samples at 4.5 ft from the map's own edges, none at a hole. The hills'
    // fall (up to 5/190 ft a foot) can pass the berm test for a sample or two at a hole's edge.
    let k = ta.find_keep();
    assert!((256..=258).contains(&k[0]) && (638..=640).contains(&k[2]), "keep {k:?}");
    assert_eq!([k[1], k[3]], [34, 478]);
    let tb = stitch::Tile::load(&b).unwrap();
    assert_eq!(tb.ground, [0, 0, 256, 256]);
    assert_eq!(tb.find_keep(), [34, 34, 222, 222]);
    // Every cell of the keep is there.
    let t = ta.terrain();
    for z in k[1]..k[3] {
        for x in k[0]..k[2] {
            assert!(t.cell(x, z, 1).is_some(), "no cell {x},{z} in the keep");
        }
    }

    let mut p = Params::new("world_holes", "Test world holes");
    p.threads = 8;
    p.chunk = 64;
    let built = build(&[a, b], &root.join("out"), &p).unwrap();
    assert!(built.far_slope <= p.max_slope, "join slope {}", built.far_slope);
    let meta = Json::parse(&std::fs::read_to_string(built.dir.join("mod.json")).unwrap()).unwrap();
    let todo: Vec<&str> = meta.get("todo").and_then(Json::arr).unwrap().iter().filter_map(Json::str).collect();
    assert!(
        todo.iter().any(|t| t.starts_with("elev_holes_a: its terrain has no cells outside samples 256..640 × 0..512")),
        "no todo for the hole: {todo:?}"
    );
    assert!(!todo.iter().any(|t| t.starts_with("elev_holes_b:")), "a todo for the whole tile: {todo:?}");

    let r = stitch::check::check(&built.dir, Some(&mods));
    assert!(r.ok(), "check failed:\n{}", r.fail.join("\n"));
}
