//! openmx-mods C12 (ported in MD60b): a world that wraps has ground at every point of its wrap seams, as openmx closes them.
//!
//! openmx closes a wrapped axis itself (MD29): a strip of seam joins past the far edge, running straight
//! from the far edge's ground to the near edge's. stitch's field is the same a world on (`Plan::period`),
//! so the last row and column of tiles meet the first across the wrap as any two lines do and the two
//! edges the strip runs between are the same ground. Generated 2×2 world, four heights 30 ft apart: the
//! snake puts the highest and lowest across the z wrap.

use ps2_float::F;
use std::path::{Path, PathBuf};
use stitch::build::{Params, build};
use stitch::openmx;

fn scratch(name: &str) -> PathBuf {
    let d = Path::new(env!("CARGO_TARGET_TMPDIR")).join("stitch-wrap").join(name);
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    d
}

/// A generated track mod `elev_c12_<name>`: `n + 1` samples a side at 4.5 ft, hills on `base`.
fn tile(root: &Path, name: &str, n: u32, base: f64) -> PathBuf {
    let id = format!("elev_c12_{name}");
    let dir = root.join(&id);
    std::fs::create_dir_all(&dir).unwrap();
    let (w, s) = (n + 1, 4.5f32);
    let feet: Vec<f32> = (0..w * w)
        .map(|i| {
            let (x, z) = (f64::from(i % w) * f64::from(s), f64::from(i / w) * f64::from(s));
            (base + 8.0 * (x / 190.0).sin() * (z / 230.0).cos() + 0.005 * z) as f32
        })
        .collect();
    let (mut g, hs) = trnwrite::Grid::from_feet(w, w, &feet, s).unwrap();
    g.surfaces = vec![1; (w * w) as usize];
    let trn = trnwrite::build(&g, &trnwrite::Options::new(s, hs)).unwrap();
    let (bytes, _) = trnwrite::write(&trn).unwrap();
    std::fs::write(dir.join(format!("{id}.ps2.trn")), bytes).unwrap();
    let mid = (f64::from(n) * f64::from(s) / 2.0) as f32;
    let scene = trnwrite::scene::SceneText::for_terrain(&trn, &id, [mid, base as f32, mid], [0.0, 0.0, 1.0]).to_text();
    std::fs::write(dir.join(format!("{id}.scn")), scene).unwrap();
    std::fs::write(
        dir.join("mod.json"),
        format!(
            r#"{{"standard": 1, "kind": "track", "id": "{id}", "name": "Test {name}",
 "source": {{"game": "Real elevation", "data": "generated by stitch's tests", "date": "2026-10-27"}},
 "version": "1.0.0", "author": "stitch tests", "permission": "public-domain",
 "todo": ["generated test map",
          "{id}.scn: TerrainWidthScale and TerrainBreadthScale print the scale in fewer digits than the terrain's"]}}"#
        ),
    )
    .unwrap();
    dir
}

/// The 2×2 world built wrapped: `stitch check` holds the near edges to the far ones, openmx's closed
/// world has no hole (game-sim's `Tiled::holes`, openmx's `world holes:` line), and every point across
/// both seams has ground with no step. The same tiles built without the wrap and then marked wrapped
/// (as the installed worlds were) have the step across the seam this test is for.
#[test]
fn a_wrapped_world_has_ground_at_every_point_of_its_seams() {
    let root = scratch("world");
    let mods = root.join("mods");
    let dirs: Vec<PathBuf> = [("a", 100.0), ("b", 130.0), ("c", 160.0), ("d", 190.0)].iter().map(|(n, b)| tile(&mods, n, 512, *b)).collect();
    let mut p = Params::new("world_c12", "Test world C12");
    p.threads = 4;
    p.wrap = Some("xz".into());
    let built = build(&dirs, &root.join("out"), &p).unwrap();
    assert!(built.plan.period.iter().all(|v| *v > 0.0), "{:?}", built.plan.period);

    // The field is the same a world on: at every lattice sample of the near edges and the far ones.
    let tiles: Vec<stitch::Tile> = dirs.iter().map(|d| stitch::Tile::load(d).unwrap()).collect();
    let terrains: Vec<_> = tiles.iter().map(stitch::Tile::terrain).collect();
    let plan = &built.plan;
    let field = |x: f64, z: f64| plan.at(&tiles, &terrains, &plan.candidates([x, z, x, z]), x, z).h;
    let [pw, pd] = plan.period;
    let mut worst = 0.0f64;
    for k in 0..=plan.size[1] {
        let z = f64::from(k) * plan.spacing;
        worst = worst.max((field(0.0, z) - field(pw, z)).abs());
    }
    for k in 0..=plan.size[0] {
        let x = f64::from(k) * plan.spacing;
        worst = worst.max((field(x, 0.0) - field(x, pd)).abs());
    }
    assert!(worst < 1e-6, "the field differs by {worst} ft a world on");

    // The maps' relief (MD57) hears them across the wrap too: a band along each far edge reads the
    // same relief from its `relief_cands` as from every source, to the bit.
    let bands = [[pw - 600.0, 0.0, pw, pd], [0.0, pd - 600.0, pw, pd]];
    let mut heard = 0;
    for band in bands {
        let rc = plan.relief_cands(band);
        for k in 0..=200 {
            let f = f64::from(k) / 200.0;
            let (x, z) = (band[0] + f * (band[2] - band[0]), band[1] + (1.0 - f) * (band[3] - band[1]));
            let pt = plan.at(&tiles, &terrains, &plan.candidates([x, z, x, z]), x, z);
            let b = pt.h - pt.relief;
            let (a, all) = (plan.relief_at(Some(&rc), x, z, b), plan.relief_at(None, x, z, b));
            assert_eq!(a.to_bits(), all.to_bits(), "relief at ({x}, {z}): {a} from its candidates, {all} from all");
            heard += usize::from(a != 0.0);
        }
    }
    println!("relief by the far edges: {heard} of 402 points carry some");

    let r = stitch::check::check(&built.dir, Some(&mods));
    for n in &r.note {
        println!("note: {n}");
    }
    assert!(r.ok(), "{:#?}", r.fail);
    assert!(r.wrap_points > 2 * 400, "{} wrap points", r.wrap_points);
    println!("check: {} wrap points, worst {} ft; join slope {}", r.wrap_points, r.wrap_height, r.far_slope);

    let w = openmx::load(&built.dir).unwrap();
    assert_eq!(w.wrap, [true, true]);
    let (t, seams, spacing) = w.closed().unwrap();
    assert!(seams > 0);
    assert_eq!(t.holes(), Vec::<[F; 4]>::new(), "openmx's world holes");
    let strip = (game_sim::tiles::generate::SEAM_CELLS * spacing) as f32;
    let (asked, none, step, at) = openmx::across_seams(&t, strip);
    println!("closed by {seams} seam joins {spacing} ft apart: {asked} points across the seams, {none} with no ground, steepest step {step} ft in half a foot at {at:?}");
    assert_eq!(none, 0, "points across the wrap with no ground");
    assert!(step < 0.5, "a {step} ft step in half a foot at {at:?}");

    // Built with edges and then marked wrapped: the far edge is not the near one.
    let mut p = Params::new("world_c12_edged", "Test world C12, edges");
    p.threads = 4;
    let edged = build(&dirs, &root.join("out"), &p).unwrap();
    let text = std::fs::read_to_string(edged.dir.join("mod.json")).unwrap();
    std::fs::write(edged.dir.join("mod.json"), text.replacen("\"tiles\":", "\"wrap\": \"xz\",\n  \"tiles\":", 1)).unwrap();
    let w = openmx::load(&edged.dir).unwrap();
    assert_eq!(w.wrap, [true, true]);
    let (t, _, spacing) = w.closed().unwrap();
    let (_, _, step, at) = openmx::across_seams(&t, (game_sim::tiles::generate::SEAM_CELLS * spacing) as f32);
    println!("built with edges, then wrapped: steepest step {step} ft in half a foot at {at:?}");
    assert!(step > 2.0, "{step}");
}
