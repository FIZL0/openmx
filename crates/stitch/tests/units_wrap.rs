//! P251: the unit layout (`"layout": "units"`) packs a wrapped world's maps a gap apart, and its join
//! ground is the same either side of the wrap: the blend sees the maps round it as well as beside it, so
//! openmx's seam strip (a cell from the far edge to 0) does not climb between two different maps' heights.

use std::path::{Path, PathBuf};
use stitch::build::{Params, layout};

fn scratch(name: &str) -> PathBuf {
    let d = Path::new(env!("CARGO_TARGET_TMPDIR")).join("stitch-units").join(name);
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    d
}

/// A generated track mod `elev_units_<name>`: `n + 1` samples a side at 4.5 ft, gentle hills on `base`,
/// no berm.
fn tile(root: &Path, name: &str, n: u32, base: f64) -> PathBuf {
    let id = format!("elev_units_{name}");
    let dir = root.join(&id);
    std::fs::create_dir_all(&dir).unwrap();
    let s = 4.5f32;
    let w = n + 1;
    let feet: Vec<f32> = (0..w * w)
        .map(|i| {
            let (x, z) = (f64::from(i % w) * f64::from(s), f64::from(i / w) * f64::from(s));
            (base + 5.0 * (x / 190.0).sin() * (z / 230.0).cos()) as f32
        })
        .collect();
    let (mut g, hs) = trnwrite::Grid::from_feet(w, w, &feet, s).unwrap();
    g.surfaces = vec![1; (w * w) as usize];
    let trn = trnwrite::build(&g, &trnwrite::Options::new(s, hs)).unwrap();
    let (bytes, _) = trnwrite::write(&trn).unwrap();
    std::fs::write(dir.join(format!("{id}.ps2.trn")), bytes).unwrap();
    let mid = (f64::from(n) * f64::from(s) / 2.0) as f32;
    let scene = trnwrite::scene::SceneText::for_terrain(&trn, &id, [mid, base as f32, mid], [0.0, 0.0, 1.0]).to_text();
    std::fs::write(dir.join(format!("{id}.scn")), scene).unwrap();
    std::fs::write(
        dir.join("mod.json"),
        format!(
            r#"{{"standard": 1, "kind": "track", "id": "{id}", "name": "Test {name}",
 "source": {{"game": "Real elevation", "data": "generated by stitch's tests", "date": "2026-11-02"}},
 "version": "1.0.0", "author": "stitch tests", "permission": "public-domain",
 "todo": ["generated test map"]}}"#
        ),
    )
    .unwrap();
    dir
}

/// Six maps, every other one 60 ft higher: wrapped both ways in the unit layout, the ground a hair
/// inside the far edge is the ground at 0 on both axes, and every map side faces another map.
#[test]
fn a_unit_layouts_ground_meets_itself_round_the_wrap() {
    let root = scratch("six");
    let dirs: Vec<PathBuf> = (0..6).map(|i| tile(&root, &format!("{i}"), 256, if i % 2 == 0 { 100.0 } else { 160.0 })).collect();
    let tiles: Vec<stitch::Tile> = dirs.iter().map(|d| stitch::Tile::load(d).unwrap()).collect();
    let terrains: Vec<_> = tiles.iter().map(stitch::Tile::terrain).collect();
    let mut p = Params::new("world_units", "Test world units");
    p.threads = 8;
    p.wrap = Some("xz".into());
    p.units = true;
    let plan = layout(&tiles, &p).unwrap();
    let extent = plan.size.map(|n| f64::from(n) * plan.spacing);
    let field = |x: f64, z: f64| plan.at(&tiles, &terrains, &plan.candidates([x, z, x, z]), x, z).h;
    let mut worst = 0.0f64;
    for i in 0..200 {
        let v = f64::from(i) / 200.0;
        let (z, x) = (v * extent[1], v * extent[0]);
        worst = worst.max((field(extent[0] - 0.01, z) - field(0.0, z)).abs());
        worst = worst.max((field(x, extent[1] - 0.01) - field(x, 0.0)).abs());
    }
    assert!(worst < 0.05, "the ground steps {worst:.3} ft across the wrap ({:.0} × {:.0} ft world)", extent[0], extent[1]);
    for j in plan.join_widths(p.wrap.as_deref()) {
        assert!(j.to.is_some() && j.width < 1500.0, "{}'s side {} is {:.0} ft from {:?}", tiles[j.tile].id, j.side, j.width, j.to);
    }
}
