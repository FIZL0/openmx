//! MD57: join ground far from every map carries the nearest map's own relief, not a smooth plain, and
//! every seam still meets.

use ps2_float::F;
use std::path::{Path, PathBuf};
use stitch::build::{Params, build};

fn scratch(name: &str) -> PathBuf {
    let d = Path::new(env!("CARGO_TARGET_TMPDIR")).join("stitch-relief").join(name);
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    d
}

/// A berm rising 45 ft over the outer 240 ft of every side, on ground at `base` with hills `hill` ft
/// high about 900 ft across.
fn height(x: f64, z: f64, side: f64, base: f64, hill: f64) -> f64 {
    let d = x.min(z).min(side - x).min(side - z);
    let berm = if d < 240.0 { 45.0 * (1.0 - d / 240.0).powi(2) } else { 0.0 };
    base + hill * (x / 150.0).sin() * (z / 170.0).cos() + berm
}

/// A generated track mod `elev_md57_<name>`: 513 samples a side at 4.5 ft.
fn tile(root: &Path, name: &str, base: f64, hill: f64, surface: u8) -> PathBuf {
    let id = format!("elev_md57_{name}");
    let dir = root.join(&id);
    std::fs::create_dir_all(&dir).unwrap();
    let (n, s) = (512u32, 4.5f32);
    let side = f64::from(n) * f64::from(s);
    let w = n + 1;
    let feet: Vec<f32> = (0..w * w)
        .map(|i| height(f64::from(i % w) * f64::from(s), f64::from(i / w) * f64::from(s), side, base, hill) as f32)
        .collect();
    let (mut g, hs) = trnwrite::Grid::from_feet(w, w, &feet, s).unwrap();
    g.surfaces = vec![surface; (w * w) as usize];
    let trn = trnwrite::build(&g, &trnwrite::Options::new(s, hs)).unwrap();
    let (bytes, _) = trnwrite::write(&trn).unwrap();
    std::fs::write(dir.join(format!("{id}.ps2.trn")), bytes).unwrap();
    let mid = (side / 2.0) as f32;
    let scene = trnwrite::scene::SceneText::for_terrain(&trn, &id, [mid, base as f32, mid], [0.0, 0.0, 1.0]).to_text();
    std::fs::write(dir.join(format!("{id}.scn")), scene).unwrap();
    std::fs::write(
        dir.join("mod.json"),
        format!(
            r#"{{"standard": 1, "kind": "track", "id": "{id}", "name": "Test {name}",
 "source": {{"game": "Real elevation", "data": "generated by stitch's tests", "date": "2026-11-01"}},
 "version": "1.0.0", "author": "stitch tests", "permission": "public-domain",
 "todo": ["generated test map"]}}"#
        ),
    )
    .unwrap();
    dir
}

/// The standard deviation of heights on a square grid after the best plane through them is taken off:
/// the ground's relief, whatever it leans.
fn spread(h: &[[f64; 3]]) -> f64 {
    let n = h.len() as f64;
    let m = |f: &dyn Fn(&[f64; 3]) -> f64| h.iter().map(f).sum::<f64>() / n;
    let (mx, mz, my) = (m(&|p| p[0]), m(&|p| p[2]), m(&|p| p[1]));
    let (sxx, szz, sxz) = (m(&|p| (p[0] - mx).powi(2)), m(&|p| (p[2] - mz).powi(2)), m(&|p| (p[0] - mx) * (p[2] - mz)));
    let (sxy, szy) = (m(&|p| (p[0] - mx) * (p[1] - my)), m(&|p| (p[2] - mz) * (p[1] - my)));
    let det = sxx * szz - sxz * sxz;
    let (a, b) = ((sxy * szz - szy * sxz) / det, (szy * sxx - sxy * sxz) / det);
    m(&|p| (p[1] - my - a * (p[0] - mx) - b * (p[2] - mz)).powi(2)).sqrt()
}

/// Two maps with hills of different heights 5000 ft apart: on the join 2000 ft past the hillier one's
/// keep, the ground the world's files hold has that map's relief, within a factor of two of the
/// spread the map has over its own keep, where before MD57 it was a smooth blend. Every seam still
/// meets (`stitch check`), and the near join ground is the blend's.
#[test]
fn a_join_far_from_every_map_has_the_nearest_maps_relief() {
    let root = scratch("far");
    let mods = root.join("mods");
    let dirs = vec![tile(&mods, "a", 100.0, 12.0, 1), tile(&mods, "b", 110.0, 3.0, 3)];
    let mut p = Params::new("world_md57", "Test world MD57");
    p.threads = 4;
    p.min_gap = 5000.0;
    let built = build(&dirs, &root.join("out"), &p).unwrap();
    let r = stitch::check::check(&built.dir, Some(&mods));
    assert!(r.ok(), "check failed:\n{}\nnotes:\n{}", r.fail.join("\n"), r.note.join("\n"));
    assert!(r.far_slope <= 0.5, "{}", r.far_slope);
    let plan = &built.plan;
    assert_eq!(plan.relief_scale, 1.0, "the gentle hills are carried whole");

    let w = stitch::openmx::load(&built.dir).unwrap();
    let tiled = w.tiled().unwrap();
    let ground = |x: f64, z: f64| f64::from(tiled.at(F(x as f32), F(z as f32)).expect("ground").y.0);
    let window = |x0: f64, z0: f64| -> Vec<[f64; 3]> {
        (0..40).flat_map(|j| (0..40).map(move |i| (x0 + 15.0 * f64::from(i), z0 + 15.0 * f64::from(j)))).map(|(x, z)| [x, ground(x, z), z]).collect()
    };
    // The two maps side by side along one axis: the hillier one is the nearer of the gap's ends.
    let (a, b) = (&plan.sources[0], &plan.sources[1]);
    let along = if (a.rect[2] - b.rect[0]).abs() > (a.rect[3] - b.rect[1]).abs() { 0 } else { 1 };
    let (near, far) = if a.rect[along] < b.rect[along] { (a, b) } else { (b, a) };
    assert_eq!(near.tile, 0, "map a is laid out first");
    let mid = |s: &stitch::Source, ax: usize| (s.rect[ax] + s.rect[ax + 2]) / 2.0;
    let mut o = [0.0; 2];
    o[along] = near.rect[along + 2] + 2000.0;
    o[1 - along] = mid(near, 1 - along) - 300.0;
    let join = window(o[0], o[1]);
    for p in &join {
        let d = plan.sources.iter().map(|s| s.distance(p[0], p[2])).fold(f64::INFINITY, f64::min);
        assert!(d >= 1990.0, "({:.0}, {:.0}) is {d:.0} ft from a map", p[0], p[2]);
    }
    let inside = window(mid(near, 0) - 300.0, mid(near, 1) - 300.0);
    let (sj, sm) = (spread(&join), spread(&inside));
    println!("join 2000 ft out: {sj:.2} ft spread; map a's own: {sm:.2} ft; far map {}", far.tile);
    assert!(sj > sm / 2.0 && sj < sm * 2.0, "join {sj:.2} ft against map a's {sm:.2} ft");

    // Without the relief the same ground is the blend: next to no spread at all.
    let tiles: Vec<stitch::Tile> = dirs.iter().map(|d| stitch::Tile::load(d).unwrap()).collect();
    let terrains: Vec<_> = tiles.iter().map(stitch::Tile::terrain).collect();
    let field = |plan: &stitch::build::Plan, x: f64, z: f64| plan.at(&tiles, &terrains, &plan.candidates([x, z, x, z]), x, z);
    for q in join.iter().step_by(97) {
        let h = field(plan, q[0], q[2]).h;
        assert!((h - q[1]).abs() < 0.05, "the file's {:.3} against stitch's {h:.3} at ({:.0}, {:.0})", q[1], q[0], q[2]);
    }
    let mut flat = built.plan;
    flat.relief_scale = 0.0;
    let blend: Vec<[f64; 3]> = join.iter().map(|q| [q[0], field(&flat, q[0], q[2]).h, q[2]]).collect();
    let sb = spread(&blend);
    assert!(sb < sm / 10.0, "the blend alone has {sb:.2} ft of spread there");

    // On the seams and within the gates the ground is the blend's to the bit.
    flat.relief_scale = 1.0;
    let plan = &flat;
    for s in &plan.sources {
        for (x, z) in [(s.rect[2] + 50.0, mid(s, 1)), (s.rect[0] - 50.0, mid(s, 1)), (mid(s, 0), s.rect[1] - 100.0)] {
            let c = plan.candidates([x, z, x, z]);
            let pt = plan.at(&tiles, &terrains, &c, x, z);
            assert_eq!(pt.relief, 0.0, "relief at ({x:.0}, {z:.0}), {:.0} ft out", s.distance(x, z));
        }
    }
}
