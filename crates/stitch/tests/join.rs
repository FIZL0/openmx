//! Generated maps with edge berms, joined by stitch and read back with openmx's readers.

use game_sim::track::Terrain;
use std::path::{Path, PathBuf};
use stitch::build::{Params, build};

/// A scratch folder of this test's own under the target directory.
fn scratch(name: &str) -> PathBuf {
    let d = Path::new(env!("CARGO_TARGET_TMPDIR")).join("stitch").join(name);
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    d
}

/// A berm rising `rise` ft over the outer `band` ft of every side, on ground at `base` with gentle hills.
fn height(x: f64, z: f64, side: f64, base: f64, rise: f64, band: f64) -> f64 {
    let d = x.min(z).min(side - x).min(side - z);
    let berm = if d < band { rise * (1.0 - d / band).powi(2) } else { 0.0 };
    base + 6.0 * (x / 260.0).sin() * (z / 310.0).cos() + 0.004 * x + berm
}

/// Write a generated track mod `elev_<name>` with `n + 1` samples a side at `s` feet, three placements:
/// Model1 in the middle, Model2 and Object1 in the berm band. `ripple` ft of ripples about 25 ft across
/// are added (0: none), for ground with curvature at its edge.
fn tile_rippled(root: &Path, name: &str, n: u32, s: f32, base: f64, surface: u8, ripple: f64) -> PathBuf {
    let id = format!("elev_{name}");
    let dir = root.join(&id);
    std::fs::create_dir_all(&dir).unwrap();
    let side = f64::from(n) * f64::from(s);
    let w = n + 1;
    let feet: Vec<f32> = (0..w * w)
        .map(|i| {
            let (x, z) = (f64::from(i % w) * f64::from(s), f64::from(i / w) * f64::from(s));
            (height(x, z, side, base, 45.0, 240.0) + ripple * (x / 4.1).sin() * (z / 3.7).cos()) as f32
        })
        .collect();
    let (mut g, hs) = trnwrite::Grid::from_feet(w, w, &feet, s).unwrap();
    g.surfaces = (0..w * w).map(|i| if (i % w) < w / 2 { surface } else { surface + 1 }).collect();
    let trn = trnwrite::build(&g, &trnwrite::Options::new(s, hs)).unwrap();
    let (bytes, _) = trnwrite::write(&trn).unwrap();
    std::fs::write(dir.join(format!("{id}.ps2.trn")), bytes).unwrap();
    let mid = (side / 2.0) as f32;
    let mut scene = trnwrite::scene::SceneText::for_terrain(&trn, &id, [mid, base as f32, mid], [0.0, 0.0, 1.0]).to_text();
    scene.push_str(&format!(
        "\r\n[Model1]\r\nSLT=rock\r\nPosition={mid:.2},{base:.2},{mid:.2}\r\n\r\n\
         [Model2]\r\nSLT=rock\r\nPosition=50.00,{base:.2},{mid:.2}\r\n\r\n\
         [Object1]\r\nCOL=fence\r\nPosition={mid:.2},{base:.2},{:.2}\r\n",
        side as f32 - 30.0
    ));
    std::fs::write(dir.join(format!("{id}.scn")), scene).unwrap();
    std::fs::write(
        dir.join("mod.json"),
        format!(
            r#"{{"standard": 1, "kind": "track", "id": "{id}", "name": "Test {name}",
 "source": {{"game": "Real elevation", "data": "generated by stitch's tests", "date": "2026-10-22"}},
 "version": "1.0.0", "author": "stitch tests", "permission": "public-domain",
 "todo": ["generated test map: rock.psg and fence.col are not in the folder"]}}"#
        ),
    )
    .unwrap();
    dir
}

fn world(name: &str, tiles: &[(&str, u32, f32, f64)]) -> (PathBuf, PathBuf, stitch::build::Built) {
    world_rippled(name, tiles, 0.0)
}

fn world_rippled(name: &str, tiles: &[(&str, u32, f32, f64)], ripple: f64) -> (PathBuf, PathBuf, stitch::build::Built) {
    let root = scratch(name);
    let mods = root.join("mods");
    let dirs: Vec<PathBuf> =
        tiles.iter().enumerate().map(|(i, (n, sz, s, b))| tile_rippled(&mods, n, *sz, *s, *b, 2 * i as u8 + 1, ripple)).collect();
    let mut p = Params::new(&format!("world_{name}"), &format!("Test world {name}"));
    p.threads = 4;
    let b = build(&dirs, &root.join("out"), &p).unwrap();
    (mods, b.dir.clone(), b)
}

fn assert_checks(dir: &Path, mods: &Path) -> stitch::check::Report {
    let r = stitch::check::check(dir, Some(mods));
    assert!(r.ok(), "check failed:\n{}\nnotes:\n{}", r.fail.join("\n"), r.note.join("\n"));
    r
}

/// Two maps with berms at the same spacing: continuous height and slope at every seam point, and the
/// tiles unchanged.
#[test]
fn two_bermed_maps_join_with_continuous_height_and_slope() {
    let (mods, dir, b) = world("two", &[("a", 256, 4.5, 100.0), ("b", 256, 4.5, 160.0)]);
    let r = assert_checks(&dir, &mods);
    // Every tile sample on every interior edge is a seam point here (one spacing).
    let per: usize = b.plan.placed.iter().map(|p| 2 * ((p.keep[2] - p.keep[0]) as usize + 1) + 2 * ((p.keep[3] - p.keep[1]) as usize + 1)).sum();
    assert_eq!(r.seam_points, 2 * per, "each point once as a tile sample and once as a lattice point");
    assert_eq!(r.between_points, 0);
    assert!(r.worst_height < 0.01 && r.worst_slope < 0.005, "{} {}", r.worst_height, r.worst_slope);
    assert!(r.far_slope <= 0.5);

    // The berm is cut and no more than the shootoff band and the berm's own slope: 240 ft rising.
    for p in &b.plan.placed {
        let [x0, z0, x1, z1] = p.keep;
        for band in [x0, z0, 256 - x1, 256 - z1] {
            assert!((34..=60).contains(&band), "band {band} samples in {:?}", p.keep);
        }
    }
    // The interior is the tile's own: the terrain bytes and every kept cell, as the tile alone has them.
    for (i, id) in ["elev_a", "elev_b"].iter().enumerate() {
        let src = std::fs::read(mods.join(id).join(format!("{id}.ps2.trn"))).unwrap();
        let copy = std::fs::read(dir.join("tiles").join(id).join(format!("{id}.ps2.trn"))).unwrap();
        assert_eq!(src, copy);
        let (ts, tc) = (Terrain::parse(&src).unwrap(), Terrain::parse(&copy).unwrap());
        let k = b.plan.placed[i].keep;
        for z in k[1]..k[3] {
            for x in k[0]..k[2] {
                assert_eq!(ts.cell(x, z, 1), tc.cell(x, z, 1));
            }
        }
    }
}

/// The berm band's props are dropped and listed, the middle one is kept; the sky and spawn default to
/// the first tile; mod.json says what the joins are.
#[test]
fn props_in_the_cut_band_are_dropped_and_listed() {
    let (_, dir, b) = world("drops", &[("c", 256, 4.5, 90.0), ("d", 256, 4.5, 95.0)]);
    assert_eq!(b.drops, 4);
    let j = stitch::json::Json::parse(&std::fs::read_to_string(dir.join("mod.json")).unwrap()).unwrap();
    let drops: Vec<(String, String)> = j
        .get("drop")
        .and_then(|d| d.arr())
        .unwrap()
        .iter()
        .map(|d| (d.get("tile").unwrap().str().unwrap().to_owned(), d.get("section").unwrap().str().unwrap().to_owned()))
        .collect();
    for t in ["elev_c", "elev_d"] {
        assert!(drops.contains(&(t.into(), "Model2".into())));
        assert!(drops.contains(&(t.into(), "Object1".into())));
        assert!(!drops.contains(&(t.into(), "Model1".into())));
    }
    assert_eq!(j.get("sky").unwrap().str(), Some("elev_c"));
    assert_eq!(j.get("spawn").unwrap().get("tile").unwrap().str(), Some("elev_c"));
    assert_eq!(j.get("kind").unwrap().str(), Some("world"));
}

/// Neighbours 300 ft apart in height: the gap widens until the join ground is under the slope limit.
#[test]
fn a_tall_neighbour_gets_a_wide_enough_gap() {
    let (mods, dir, b) = world("tall", &[("e", 256, 4.5, 80.0), ("f", 256, 4.5, 380.0)]);
    let r = assert_checks(&dir, &mods);
    assert!(r.far_slope <= 0.5 && r.far_slope > 0.1, "{}", r.far_slope);
    let gap = b.plan.sources[1].rect[0].max(b.plan.sources[0].rect[0]) - b.plan.sources[1].rect[2].min(b.plan.sources[0].rect[2]);
    assert!(gap >= 300.0 / 0.5, "gap {gap}");
}

/// A 9 ft map beside 4.5 ft ones: its seams lie on the 4.5 ft lattice and meet it exactly.
#[test]
fn a_coarser_map_meets_the_lattice_at_its_samples() {
    let (mods, dir, b) = world("mixed", &[("g", 256, 4.5, 120.0), ("h", 256, 9.0, 140.0), ("i", 256, 4.5, 130.0)]);
    assert_eq!(b.plan.spacing, 4.5);
    let r = assert_checks(&dir, &mods);
    assert_eq!(r.between_points, 0, "9 ft samples are every other lattice point");
}

/// The look fades: across a gap the first tile's weight runs from 255 down, with no step past the
/// limit (the check), and somewhere in the middle both tiles have a share.
#[test]
fn the_blend_fades_from_one_tile_to_the_other() {
    let (_, dir, _) = world("blend", &[("j", 256, 4.5, 100.0), ("k", 256, 4.5, 110.0)]);
    let j = stitch::json::Json::parse(&std::fs::read_to_string(dir.join("mod.json")).unwrap()).unwrap();
    let mut mixed = 0;
    for jn in j.get("joins").and_then(|v| v.arr()).unwrap() {
        let name = jn.get("join").unwrap().str().unwrap();
        let between = jn.get("between").unwrap().arr().unwrap().len();
        let blend = std::fs::read(dir.join("joins").join(name).join(format!("{name}.blend"))).unwrap();
        mixed += blend.chunks(between).filter(|c| c.iter().filter(|&&b| b > 20).count() >= 2).count();
        assert!(blend.chunks(between).all(|c| c.iter().map(|&b| u32::from(b)).sum::<u32>() == 255));
    }
    assert!(mixed > 1000, "{mixed} samples share the look");
}

/// The check is not a rubber stamp: a join raised by 1% fails at its seams, and so does a tile whose
/// copy differs from its source.
#[test]
fn a_tampered_world_fails_the_check() {
    let (mods, dir, _) = world("tamper", &[("l", 256, 4.5, 100.0), ("m", 256, 4.5, 105.0)]);
    let path = dir.join("joins/j000_000/j000_000.ps2.trn");
    let mut t = trnwrite::read(&std::fs::read(&path).unwrap()).unwrap();
    fn raise(n: &mut trnwrite::Node) {
        n.height_scale = ps2_float::F(n.height_scale.0 * 1.01);
        n.children.iter_mut().flatten().for_each(raise);
    }
    raise(&mut t.root);
    std::fs::write(&path, trnwrite::write(&t).unwrap().0).unwrap();
    let r = stitch::check::check(&dir, Some(&mods));
    assert!(r.fail.iter().any(|f| f.contains("j000_000") && f.contains("edge")), "{:?}", r.fail);

    let (mods, dir, _) = world("tamper2", &[("n", 256, 4.5, 100.0), ("o", 256, 4.5, 105.0)]);
    let scn = dir.join("tiles/elev_n/elev_n.scn");
    let mut text = std::fs::read(&scn).unwrap();
    text.extend_from_slice(b"\r\n[Note]\r\nWho=someone\r\n");
    std::fs::write(&scn, text).unwrap();
    let r = stitch::check::check(&dir, Some(&mods));
    assert!(r.fail.iter().any(|f| f.contains("elev_n.scn: differs")), "{:?}", r.fail);
}

/// A 3.5 ft map beside 4.5 ft ones (C6): the 3.5 ft map's joins are at its own spacing, so every one
/// of its seam samples is a join sample, and where its collar meets the 4.5 ft lattice the two agree.
/// And the other way round: a 4.5 ft map in a 3.5 ft world.
#[test]
fn a_finer_map_gets_joins_at_its_own_spacing() {
    let (mods, dir, b) = world_rippled("mixed35", &[("p", 256, 4.5, 120.0), ("q", 256, 3.5, 140.0), ("r", 256, 4.5, 130.0)], 3.0);
    assert_eq!(b.plan.spacing, 4.5);
    assert_eq!(b.plan.collars.len(), 1, "{:?}", b.plan.uncollared);
    assert_eq!(b.plan.collars[0].tile, 1);
    assert_eq!(b.plan.collars[0].period, 31.5, "9 samples of 3.5 ft are 7 of 4.5");
    let r = assert_checks(&dir, &mods);
    assert_eq!(r.between_points, 0, "every 3.5 ft seam sample is a sample of its collar");
    assert!(r.join_seam_points > 100, "{} points where the collar meets the lattice", r.join_seam_points);
    assert!(r.worst_height < 0.01 && r.worst_slope < 0.005, "{} {}", r.worst_height, r.worst_slope);
    // Each 3.5 ft seam sample is counted twice (as a tile sample and a collar sample), like the 4.5s.
    let per = |p: &stitch::build::Placed| 2 * ((p.keep[2] - p.keep[0]) as usize + 1) + 2 * ((p.keep[3] - p.keep[1]) as usize + 1);
    assert_eq!(r.seam_points, 2 * b.plan.placed.iter().map(per).sum::<usize>());

    let (mods, dir, b) = world("mixed45", &[("s", 256, 3.5, 120.0), ("t", 256, 4.5, 140.0)]);
    assert_eq!(b.plan.spacing, 3.5, "a tie goes to the finer");
    assert_eq!(b.plan.collars.len(), 1, "{:?}", b.plan.uncollared);
    let r = assert_checks(&dir, &mods);
    assert_eq!(r.between_points, 0);
    assert!(r.join_seam_points > 100);
}
