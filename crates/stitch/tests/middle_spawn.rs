//! openmx MD50: a wrapped world's file names its middle tile as `spawn`, so the ride starts as far
//! from the seams as it can; a world with edges keeps the first tile whose start is kept.

use std::path::{Path, PathBuf};
use stitch::build::{Params, build};
use stitch::json::Json;

fn scratch(name: &str) -> PathBuf {
    let d = Path::new(env!("CARGO_TARGET_TMPDIR")).join("stitch-middle").join(name);
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    d
}

/// A generated track mod `elev_middle_<name>`: `n + 1` samples a side at 4.5 ft, gentle hills on `base`, no
/// berm (an MX vs. ATV map's flat edge, so only the shootoff band is cut).
fn tile(root: &Path, name: &str, n: u32, base: f64, surface: u8) -> PathBuf {
    let id = format!("elev_middle_{name}");
    let dir = root.join(&id);
    std::fs::create_dir_all(&dir).unwrap();
    let s = 4.5f32;
    let w = n + 1;
    let k = f64::from(surface);
    let feet: Vec<f32> = (0..w * w)
        .map(|i| {
            let (x, z) = (f64::from(i % w) * f64::from(s), f64::from(i / w) * f64::from(s));
            (base + 5.0 * (x / (190.0 + 9.0 * k)).sin() * (z / 230.0).cos() + 0.003 * z) as f32
        })
        .collect();
    let (mut g, hs) = trnwrite::Grid::from_feet(w, w, &feet, s).unwrap();
    g.surfaces = vec![surface; (w * w) as usize];
    let trn = trnwrite::build(&g, &trnwrite::Options::new(s, hs)).unwrap();
    let (bytes, _) = trnwrite::write(&trn).unwrap();
    std::fs::write(dir.join(format!("{id}.ps2.trn")), bytes).unwrap();
    let mid = (f64::from(n) * f64::from(s) / 2.0) as f32;
    let scene = trnwrite::scene::SceneText::for_terrain(&trn, &id, [mid, base as f32, mid], [0.0, 0.0, 1.0]).to_text();
    std::fs::write(dir.join(format!("{id}.scn")), scene).unwrap();
    std::fs::write(
        dir.join("mod.json"),
        format!(
            r#"{{"standard": 1, "kind": "track", "id": "{id}", "name": "Test {name}",
 "source": {{"game": "Real elevation", "data": "generated by stitch's tests", "date": "2026-10-27"}},
 "version": "1.0.0", "author": "stitch tests", "permission": "public-domain",
 "todo": ["generated test map"]}}"#
        ),
    )
    .unwrap();
    dir
}

/// Of three tiles in a row whose starts are kept, the middle one; a start outside its keep is passed
/// over; a tie goes to the first.
#[test]
fn the_middle_tile_is_the_one_nearest_the_worlds_middle() {
    let t = |x: f64, start: f64| ([x, 0.0], [0, 0, 100, 100], 1.0, [start, 0.0, 50.0]);
    assert_eq!(stitch::middle_tile(&[t(0.0, 50.0), t(100.0, 50.0), t(200.0, 50.0)], [300.0, 100.0]), Some(1));
    assert_eq!(stitch::middle_tile(&[t(0.0, 50.0), t(100.0, 150.0), t(200.0, 50.0)], [300.0, 100.0]), Some(0));
    assert_eq!(stitch::middle_tile(&[t(0.0, 150.0)], [100.0, 100.0]), None);
}

/// Nine maps in a 3 x 3 grid: wrapped, the file's spawn is the tile in the grid's middle cell; with
/// edges, the first tile's.
#[test]
fn a_wrapped_world_spawns_on_its_middle_tile() {
    let root = scratch("nine");
    let mods = root.join("mods");
    let dirs: Vec<PathBuf> = (0..9).map(|i| tile(&mods, &format!("{i}"), 256, 100.0 + 4.0 * f64::from(i), i as u8 + 1)).collect();
    for wrap in [Some("xz"), None] {
        let mut p = Params::new("world_middle", "Test world middle");
        p.threads = 8;
        p.chunk = 64;
        p.wrap = wrap.map(str::to_owned);
        let built = build(&dirs, &root.join(wrap.unwrap_or("edged")), &p).unwrap();
        let meta = Json::parse(&std::fs::read_to_string(built.dir.join("mod.json")).unwrap()).unwrap();
        let spawn = meta.get("spawn").and_then(|s| s.get("tile")).and_then(Json::str).unwrap().to_owned();
        let middle = built.plan.placed.iter().position(|pl| pl.cell == (1, 1)).unwrap();
        let want = if wrap.is_some() { format!("elev_middle_{middle}") } else { "elev_middle_0".to_owned() };
        assert_eq!(spawn, want, "wrap {wrap:?}");
    }
}
