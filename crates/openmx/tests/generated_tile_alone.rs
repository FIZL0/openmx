//! MD33: a generated tile loaded alone as a track, under the scene a world's file gives it.
//!
//! [`game_sim::tiles::generate`] writes one-level terrains of N 16-sample cells, and the tests' world
//! scenes (tiled_world.rs, world_streaming.rs, …) say `TerrainWidth=N`, counting root cells as a world's
//! file does. Read alone, a scene's width is 256-sample units, so the edge sat sixteen times past the
//! ground: the edge test never threw and a bike ridden off the field fell for ever. The field and edge
//! now stop at the tree's own samples ([`game_sim::world::Ground::new`]). Here 12 × 12 cells at 4 feet,
//! 764 feet a side against an edge at 12,288 before: wider than twice the edge test's 150-foot
//! margin, or every spot on it throws. The rides skip without the disc, since the bike and its
//! physics are the disc's.

use game_sim::tiles::generate;
use std::path::{Path, PathBuf};
use std::process::Command;

const SPACING: f32 = 4.0;
const CELLS: u32 = 12;
const SIDE: f32 = (CELLS * 16 - 1) as f32 * SPACING;

/// Gentle rolling ground, as MD8's world has.
fn relief(x: f64, z: f64) -> f64 {
    40.0 + 1.5 * (x / 140.0).sin() * (z / 90.0).cos()
}

fn scene() -> String {
    [
        "[SceneInfo]",
        "SceneName=MD33 tile",
        &format!("DefaultStartPosition={:.2},40.00,{:.2}", SIDE / 2.0, SIDE / 2.0),
        "DefaultStartDirection=1.00,0.00,0.00",
        "[Environment]",
        "TerrainFile=MDT.trn",
        &format!("TerrainWidth={CELLS}"),
        &format!("TerrainBreadth={CELLS}"),
        &format!("TerrainWidthScale={SPACING:.2}"),
        &format!("TerrainBreadthScale={SPACING:.2}"),
        "TerrainBorderWidth=0.00",
        "MinDivisionSize=32.00",
        "[Fog]",
        "ColorRGB=150,151,139",
        "",
    ]
    .join("\r\n")
}

fn write(root: &Path, rel: &str, bytes: impl AsRef<[u8]>) {
    let path = root.join(rel);
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, bytes).unwrap();
}

/// A `mods/` folder holding the one track mod, `md33_tile`; each test writes its own.
fn mods_folder(test: &str) -> PathBuf {
    let mods = Path::new(env!("CARGO_TARGET_TMPDIR")).join("md33").join(test).join("mods");
    let _ = std::fs::remove_dir_all(&mods);
    let dir = mods.join("tracks").join("md33_tile");
    write(
        &dir,
        "mod.json",
        r#"{"standard": 1, "kind": "track", "id": "md33_tile", "name": "MD33 tile", "source": {"game": "Real elevation", "data": "generated by openmx's MD33 test"}, "version": "1.0.0", "author": "crates/openmx/tests/generated_tile_alone.rs", "permission": "public-domain", "todo": []}"#,
    );
    write(&dir, "Env/MDT/MDT.scn", scene());
    let sp = f64::from(SPACING);
    let trn = generate::terrain("mdt", (CELLS, CELLS), SPACING, |x, z| relief(f64::from(x) * sp, f64::from(z) * sp), |_, _| 1);
    write(&dir, "Env/MDT/MDT.ps2.trn", trn);
    mods
}

/// One traced tick: where the bike is, and whether it is down.
struct Tick {
    frame: usize,
    x: f32,
    y: f32,
    z: f32,
    wreck: bool,
}

/// `--trace-feel` on the gas from `x,z` facing `degrees`, on through every wreck.
fn ride(test: &str, x: f32, z: f32, degrees: f32, frames: usize) -> Option<Vec<Tick>> {
    if let Err(e) = game_render::disc::Disc::open_configured() {
        eprintln!("skipped: {e}");
        return None;
    }
    let mods = mods_folder(test);
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let (at, n) = (format!("{x},{z},{degrees}"), frames.to_string());
    let out = Command::new(env!("CARGO_BIN_EXE_openmx"))
        .current_dir(&root)
        .args(["--headless", "--track", "md33_tile", "--mods", mods.to_str().unwrap()])
        .args(["--trace", &n, "--trace-gas", "--trace-feel", "--trace-at", &at])
        .output()
        .expect("the shell runs");
    let said = format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr));
    assert!(out.status.success(), "the shell failed:\n{said}");
    let mut ticks = Vec::new();
    for l in said.lines() {
        let w: Vec<&str> = l.split_whitespace().collect();
        let Some(frame) = w.first().and_then(|f| f.parse::<usize>().ok()) else { continue };
        if w.len() != 12 {
            continue;
        }
        let f = |i: usize| w[i].parse::<f32>().unwrap();
        ticks.push(Tick { frame, x: f(5), y: f(6), z: f(7), wreck: w[11] == "1" });
    }
    assert!(!ticks.is_empty(), "no trace rows:\n{said}");
    Some(ticks)
}

/// Ridden off each side, the bike is thrown at the edge and put back on the field: every tick is
/// within a few feet of it and above the relief's lowest point. Before MD33 the bike rode off the
/// 764-foot field towards an edge at 12,288 feet and fell under
/// the map.
#[test]
fn a_generated_tile_alone_throws_at_its_own_edge() {
    let mut throws = 0;
    for degrees in [270.0, 0.0, 90.0, 180.0] {
        let Some(ticks) = ride(&format!("edge_{degrees}"), SIDE / 2.0, SIDE / 2.0, degrees, 1200) else { return };
        assert_eq!(ticks.len(), 1200, "{degrees}°: the trace stopped at {}", ticks.len());
        let mut down = false;
        for t in &ticks {
            let near = |v: f32| (-20.0..SIDE + 20.0).contains(&v);
            assert!(near(t.x) && near(t.z), "{degrees}°, tick {}: off the map at ({}, {}, {})", t.frame, t.x, t.y, t.z);
            assert!(t.y > 30.0, "{degrees}°, tick {}: at y {} under the map at ({}, {})", t.frame, t.y, t.x, t.z);
            throws += usize::from(t.wreck && !down);
            down = t.wreck;
        }
    }
    println!("{throws} throws");
    assert!(throws >= 4, "{throws} throws");
}
