//! MD29: a world mod whose world file says `"wrap": "x"`, ridden round through the shell's own
//! binary, as `tests/tiled_world.rs` rides its world.
//!
//! Two track mods at 9 feet a sample in a row along `x`, over ground that does not come round, and
//! the seam join the shell makes past the far one ([`game_sim::tiles::generate::seam_joins`]) to close
//! it. Every terrain is written by the test, so nothing is off a disc; the rides skip without the
//! disc, since the bike and its physics are the disc's.
//!
//! What is proved: the world loads wrapped, one strip wider, and says so; a ride east along it goes
//! over the made join and through the seam onto the first tile, on the ground all the way, and is
//! never shot back; and the world file without the switch is the world with its edge, which throws.

use game_sim::tiles::generate;
use game_sim::track::TerrainLayout;
use ps2_float::F;
use std::path::{Path, PathBuf};
use std::process::Command;

/// Rolling ground that climbs to the east, so the seam join has a step to close.
fn relief(x: f64, z: f64) -> f64 {
    40.0 + 8.0 * x / 1134.0 + 1.5 * (x / 140.0).sin() * (z / 90.0).cos()
}

/// The tiles: `a` at the origin, `b` beside it, each 63 cells of 9 feet.
const TILES: [(&str, &str, u32); 2] = [("a", "MWA", 0), ("b", "MWB", 567)];

/// The world before its seam join, and the join's width: 15 cells of the tiles' 9 feet.
const OPEN: f32 = 1134.0;
const STRIP: f32 = 135.0;
const WIDTH: f32 = OPEN + STRIP;
const DEPTH: f32 = 567.0;

fn terrain(at: u32) -> Vec<u8> {
    generate::terrain("t", (4, 4), 9.0, |x, z| relief(f64::from(at) + f64::from(x) * 9.0, f64::from(z) * 9.0), |_, _| 1)
}

/// A tile's scene: its terrain, its size, and a start line 200 feet in, facing `+x`.
fn scene(name: &str, stem: &str) -> String {
    let layout = TerrainLayout { width: 4, breadth: 4, width_scale: F(9.0), breadth_scale: F(9.0), ..TerrainLayout::default() };
    [
        "[SceneInfo]",
        &format!("SceneName=MD29 {name}"),
        "DefaultStartPosition=200.00,40.00,283.00",
        "DefaultStartDirection=1.00,0.00,0.00",
        "[Environment]",
        &format!("TerrainFile={stem}.trn"),
        &format!("TerrainWidth={}", layout.width),
        &format!("TerrainBreadth={}", layout.breadth),
        &format!("TerrainWidthScale={:.2}", layout.width_scale.0),
        &format!("TerrainBreadthScale={:.2}", layout.breadth_scale.0),
        "TerrainBorderWidth=0.00",
        "MinDivisionSize=96.00",
        "[Fog]",
        "ColorRGB=150,151,139",
        "",
    ]
    .join("\r\n")
}

fn track_json(id: &str) -> String {
    format!(
        r#"{{
  "standard": 1, "kind": "track", "id": "{id}", "name": "MD29 {id}",
  "source": {{"game": "Real elevation", "data": "generated by openmx's MD29 test", "date": "2026-10-27"}},
  "version": "1.0.0", "author": "crates/openmx/tests/wrapped_world.rs", "permission": "public-domain", "todo": []
}}"#
    )
}

/// The world's file, with `wrap` as its switch's JSON (none at all for `None`).
fn world_json(id: &str, wrap: Option<&str>) -> String {
    let tiles: Vec<String> = TILES.iter().map(|(name, _, at)| format!(r#"{{"tile": "{name}", "at": [{at}.0, 0.0], "keep": [0, 0, 63, 63]}}"#)).collect();
    let wrap = wrap.map(|w| format!(r#""wrap": {w}, "#)).unwrap_or_default();
    format!(
        r#"{{
  "standard": 1, "kind": "world", "id": "{id}", "name": "MD29 round",
  "source": {{"game": "Combined", "games": ["Real elevation"]}},
  "version": "1.0.0", "author": "crates/openmx/tests/wrapped_world.rs", "permission": "public-domain",
  "tiles": [{}],
  "joins": [],
  {wrap}"drop": [], "sky": "a", "spawn": {{"tile": "a"}}, "todo": []
}}"#,
        tiles.join(", ")
    )
}

fn write(root: &Path, rel: &str, bytes: impl AsRef<[u8]>) {
    let path = root.join(rel);
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, bytes).unwrap();
}

/// A `mods/` folder holding the world wrapped, `md29_round`, and the same world with no switch,
/// `md29_edged`. Each test writes its own, so they run side by side.
fn mods_folder(test: &str) -> PathBuf {
    let mods = Path::new(env!("CARGO_TARGET_TMPDIR")).join("md29").join(test).join("mods");
    let _ = std::fs::remove_dir_all(&mods);
    for (id, wrap) in [("md29_round", Some(r#""x""#)), ("md29_edged", None)] {
        let world = mods.join("tracks").join(id);
        write(&world, "mod.json", world_json(id, wrap));
        for (name, stem, at) in TILES {
            let dir = world.join("tiles").join(name);
            write(&dir, "mod.json", track_json(&format!("md29_{name}")));
            write(&dir, &format!("Env/{stem}/{stem}.scn"), scene(name, stem));
            write(&dir, &format!("Env/{stem}/{stem}.ps2.trn"), terrain(at));
        }
    }
    mods
}

fn shell(test: &str, track: &str, args: &[&str]) -> Option<String> {
    if let Err(e) = game_render::disc::Disc::open_configured() {
        eprintln!("skipped: {e}");
        return None;
    }
    let mods = mods_folder(test);
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let out = Command::new(env!("CARGO_BIN_EXE_openmx"))
        .current_dir(&root)
        .args(["--headless", "--track", track, "--mods", mods.to_str().unwrap()])
        .args(args)
        .output()
        .expect("the shell runs");
    let said = format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr));
    assert!(out.status.success(), "the shell failed:\n{said}");
    Some(said)
}

fn line<'a>(said: &'a str, prefix: &str) -> &'a str {
    said.lines().find(|l| l.starts_with(prefix)).unwrap_or_else(|| panic!("no `{prefix}` line:\n{said}"))
}

/// One traced tick: where the bike is, and whether the rider is down.
struct Tick {
    frame: usize,
    x: f32,
    y: f32,
    z: f32,
    wreck: bool,
}

/// `--trace-feel` on the gas from `x,z` facing `degrees` for `frames` ticks, through every wreck.
fn ride(test: &str, track: &str, x: f32, z: f32, degrees: f32, frames: usize) -> Option<Vec<Tick>> {
    let at = format!("{x},{z},{degrees}");
    let n = frames.to_string();
    let said = shell(test, track, &["--trace", &n, "--trace-gas", "--trace-feel", "--trace-at", &at])?;
    let mut out = Vec::new();
    for l in said.lines() {
        let w: Vec<&str> = l.split_whitespace().collect();
        let Some(frame) = w.first().and_then(|f| f.parse::<usize>().ok()) else { continue };
        if w.len() != 12 {
            continue;
        }
        let f = |i: usize| w[i].parse::<f32>().unwrap();
        out.push(Tick { frame, x: f(5), y: f(6), z: f(7), wreck: w[11] == "1" });
    }
    assert!(!out.is_empty(), "no trace rows:\n{said}");
    Some(out)
}

/// The ground the made join should have under `x`, `z`: the tiles' own, and across the strip a
/// straight run from the far edge's height to the near edge's.
fn ground(x: f32, z: f32) -> f32 {
    let (x, z) = (f64::from(x), f64::from(z));
    let open = f64::from(OPEN);
    if x < open {
        return relief(x, z) as f32;
    }
    let t = (x - open) / f64::from(STRIP);
    (relief(open, z) + (relief(0.0, z) - relief(open, z)) * t) as f32
}

#[test]
fn a_wrapped_world_loads_one_strip_wider_and_says_it_wraps() {
    let Some(said) = shell("loads", "md29_round", &["--frames", "2"]) else { return };
    assert_eq!(line(&said, "world: md29_round"), format!("world: md29_round (MD29 round), 2 tiles and 1 joins, {WIDTH:.0} x {DEPTH:.0} feet, lit by a"));
    assert_eq!(line(&said, "world wraps: "), format!("world wraps: x every {WIDTH:.0} feet, closed by 1 seam joins"));
}

/// On the gas along `+x` from tile `a`: across `b`, over the made join, through the seam onto `a`
/// again, on the ground all the way, and never shot back.
#[test]
fn a_ride_east_goes_round_the_world_on_the_ground() {
    let Some(ticks) = ride("round", "md29_round", 200.0, 283.0, 90.0, 1200) else { return };
    let mut laps = 0;
    for pair in ticks.windows(2) {
        let (a, b) = (&pair[0], &pair[1]);
        assert!(!b.wreck, "tick {}: down at ({}, {})", b.frame, b.x, b.z);
        if a.x - b.x > WIDTH / 2.0 {
            assert!(a.x > WIDTH - 60.0 && b.x < 60.0, "tick {}: through the seam from {} to {}", b.frame, a.x, b.x);
            laps += 1;
        }
        assert!(b.x >= 0.0 && b.x < WIDTH, "tick {}: at x {}, outside the world", b.frame, b.x);
        let under = ground(b.x, b.z);
        assert!((b.y - under).abs() < 6.0, "tick {}: at y {} over ground {under} at ({}, {})", b.frame, b.y, b.x, b.z);
    }
    let on_join = ticks.iter().filter(|t| t.x > OPEN && t.x < WIDTH).count();
    assert!(laps >= 1 && on_join > 3, "{laps} laps, {on_join} ticks on the join; last at {}", ticks.last().unwrap().x);
}

/// The same world with no `wrap` in its file is the world with its edge: the same ride is shot back
/// before the far side.
#[test]
fn without_the_switch_the_edge_throws() {
    let Some(said) = shell("edged_loads", "md29_edged", &["--frames", "2"]) else { return };
    assert_eq!(line(&said, "world: md29_edged"), format!("world: md29_edged (MD29 round), 2 tiles and 0 joins, {OPEN:.0} x {DEPTH:.0} feet, lit by a"));
    assert!(!said.contains("world wraps:"), "{said}");
    let Some(ticks) = ride("edged", "md29_edged", 200.0, 283.0, 90.0, 900) else { return };
    let thrown = ticks.iter().find(|t| t.wreck).expect("never shot back");
    assert!((thrown.x - (OPEN - 150.0)).abs() < 12.0, "thrown at ({}, {})", thrown.x, thrown.z);
}
