//! MD3: a freeride map the size of MX vs. ATV's — 80×80 leaves, two levels, five root cells a side
//! (`TerrainWidth=5`) at 4.5 feet a sample, 5,760 feet a side — against MX Unleashed's 48×48 leaves
//! at nine feet. Nothing in the shell may take a free track's size as given: the ground is the
//! terrain's and the scene's, the map edge and its shootoff (S59) are the scene's numbers, and so is
//! the radar's world.
//!
//! The terrain is written by the test, as `tests/track_mods.rs`'s is (no byte of it off a disc): flat
//! at height 0, every leaf one shared block, every root cell one shared node. The rides go through the
//! shell's own binary headless and skip without the disc, since the bike and its physics are the
//! disc's.

use std::path::{Path, PathBuf};
use std::process::Command;

/// Root cells a side, and feet a sample: MX vs. ATV's freeride maps (`MC01`'s scene says so).
const CELLS: u32 = 5;
const SPACING: f32 = 4.5;
/// The map's side as the edge test measures it: cells × 256 samples × the spacing.
const SIDE: f32 = CELLS as f32 * 256.0 * SPACING;
/// The shootoff's margin, `game_sim::off_map::MARGIN`.
const MARGIN: f32 = 150.0;
/// MX Unleashed's free tracks: 768 samples a side. A ground or an edge sized by them on this map
/// would end here, at this map's spacing.
const MXU_SAMPLES: f32 = 768.0;

fn word(out: &mut Vec<u8>, w: u32) {
    out.extend_from_slice(&w.to_le_bytes());
}

fn single(out: &mut Vec<u8>, f: f32) {
    word(out, f.to_bits());
}

/// A terrain node: full relief, half a unit a raw height, the block and the children's table.
fn node(out: &mut Vec<u8>, block: u16, children_at: u32) {
    for f in [1.0, 0.5, 0.0, 0.0] {
        single(out, f);
    }
    out.extend_from_slice(&0u16.to_le_bytes());
    out.extend_from_slice(&block.to_le_bytes());
    out.extend_from_slice(&[0; 4 + 64 + 4]);
    out.push(1);
    word(out, children_at);
}

/// The flat two-level terrain: a root whose `CELLS`×`CELLS` cells are one node, whose 16×16 leaves
/// are one leaf, on one block.
fn big_terrain() -> Vec<u8> {
    let mut out = Vec::new();
    out.extend_from_slice(b"PLN\0");
    out.push(b'7');
    out.extend_from_slice(b"ps2\0");
    let mut name = [0u8; 32];
    name[..5].copy_from_slice(b"mdbig");
    out.extend_from_slice(&name);
    word(&mut out, 0); // no palette
    single(&mut out, SPACING);
    word(&mut out, 2); // two levels
    let tree_slot = out.len();
    word(&mut out, 0);
    word(&mut out, 1); // the words in front of the blocks
    word(&mut out, 1); // blocks
    word(&mut out, 0);
    word(&mut out, 0); // no texture table
    word(&mut out, 0); // and no pages
    word(&mut out, 0); // the block's base
    out.extend(std::iter::repeat_n(0u8, 17 * 20 * 2));
    for _ in 0..289 {
        out.extend_from_slice(&[0, 127, 0]);
    }
    out.extend(std::iter::repeat_n(0u8, 289));
    out.extend(std::iter::repeat_n(0x81u8, 289));
    let tree_at = out.len() as u32;
    out[tree_slot..tree_slot + 4].copy_from_slice(&tree_at.to_le_bytes());
    let root_children = tree_at + 97;
    let cell_at = root_children + 256 * 4;
    let cell_children = cell_at + 97;
    let leaf_at = cell_children + 256 * 4;
    node(&mut out, 0, root_children);
    for cz in 0..16 {
        for cx in 0..16 {
            word(&mut out, if cx < CELLS && cz < CELLS { cell_at } else { 0 });
        }
    }
    node(&mut out, 0, cell_children);
    for _ in 0..256 {
        word(&mut out, leaf_at);
    }
    node(&mut out, 0, 0);
    out
}

fn scene() -> String {
    [
        "[SceneInfo]",
        "SceneName=MD3 Big",
        "DefaultStartPosition=2880.00,5.00,2880.00",
        "DefaultStartDirection=0.00,0.00,1.00",
        "[Environment]",
        "TerrainFile=MDBIG.trn",
        &format!("TerrainWidth={CELLS}"),
        &format!("TerrainBreadth={CELLS}"),
        &format!("TerrainWidthScale={SPACING:.2}"),
        &format!("TerrainBreadthScale={SPACING:.2}"),
        "TerrainBorderWidth=0.00",
        "MinDivisionSize=96.00",
        "[Fog]",
        "ColorRGB=150,151,139",
        "",
    ]
    .join("\r\n")
}

fn mod_json(id: &str) -> String {
    format!(
        r#"{{
  "standard": 1,
  "kind": "track",
  "id": "{id}",
  "name": "MD3 Big",
  "source": {{"game": "Real elevation", "data": "generated by openmx's MD3 test", "date": "2026-10-22"}},
  "version": "1.0.0",
  "author": "crates/openmx/tests/big_terrain.rs",
  "permission": "public-domain",
  "todo": []
}}"#
    )
}

fn write(root: &Path, rel: &str, bytes: impl AsRef<[u8]>) {
    let path = root.join(rel);
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, bytes).unwrap();
}

/// A `mods/` folder holding the one big map, `md3_big`.
fn mods_folder() -> PathBuf {
    let mods = Path::new(env!("CARGO_TARGET_TMPDIR")).join("md3").join("mods");
    let _ = std::fs::remove_dir_all(&mods);
    let dir = mods.join("tracks").join("md3_big");
    write(&dir, "mod.json", mod_json("md3_big"));
    write(&dir, "Env/MDBIG/MDBIG.scn", scene());
    write(&dir, "Env/MDBIG/MDBIG.ps2.trn", big_terrain());
    mods
}

/// Ride the shell headless on the big map with these arguments, or `None` with no disc to ride.
fn shell(args: &[&str]) -> Option<String> {
    if let Err(e) = game_render::disc::Disc::open_configured() {
        eprintln!("skipped: {e}");
        return None;
    }
    let mods = mods_folder();
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let out = Command::new(env!("CARGO_BIN_EXE_openmx"))
        .current_dir(&root)
        .args(["--headless", "--track", "md3_big", "--mods", mods.to_str().unwrap()])
        .args(args)
        .output()
        .expect("the shell runs");
    let said = format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr));
    assert!(out.status.success(), "the shell failed:\n{said}");
    Some(said)
}

fn line<'a>(said: &'a str, prefix: &str) -> &'a str {
    said.lines().find(|l| l.starts_with(prefix)).unwrap_or_else(|| panic!("no `{prefix}` line:\n{said}"))
}

/// One traced tick: where the bike is (`x`, `z`), whether it is on the ground, and whether the tick
/// wrecked it.
struct Tick {
    frame: usize,
    x: f32,
    y: f32,
    z: f32,
    wreck: bool,
}

/// `--trace-feel` on the gas from `x,z` facing `degrees`, up to the first wreck.
fn ride(x: f32, z: f32, degrees: f32, frames: usize) -> Option<Vec<Tick>> {
    let at = format!("{x},{z},{degrees}");
    let n = frames.to_string();
    let said = shell(&["--trace", &n, "--trace-gas", "--trace-feel", "--trace-at", &at])?;
    let mut out = Vec::new();
    for l in said.lines() {
        let w: Vec<&str> = l.split_whitespace().collect();
        let Some(frame) = w.first().and_then(|f| f.parse::<usize>().ok()) else { continue };
        if w.len() != 12 {
            continue;
        }
        let f = |i: usize| w[i].parse::<f32>().unwrap();
        let tick = Tick { frame, x: f(5), y: f(6), z: f(7), wreck: w[11] == "1" };
        let wrecked = tick.wreck;
        out.push(tick);
        if wrecked {
            break;
        }
    }
    assert!(!out.is_empty(), "no trace rows:\n{said}");
    Some(out)
}

/// The ground, the edge and the radar are the big map's own numbers.
#[test]
fn the_big_map_is_sized_by_its_terrain_and_scene() {
    let Some(said) = shell(&["--frames", "2"]) else { return };
    let side = (CELLS * 256 - 1) as f32 * SPACING;
    let ground = format!("ground {side:.0} x {side:.0} feet in 1280 x 1280 samples");
    assert!(line(&said, "MD3 Big: ").contains(&ground), "\n{said}");
    // The edge 5,760 feet a side, and the radar over the larger of the scene's two scales × 192
    // (the original's), 864 feet.
    assert_eq!(
        line(&said, "map: "),
        format!("map: {SIDE:.0} x {SIDE:.0} feet to its edge, shot back from {MARGIN:.0} feet short of it; radar 864 feet across")
    );
}

/// Corner to corner: on the gas from 300 feet inside the near corner along the diagonal, the bike
/// crosses where a 768-sample map would have ended and is shot back only where this one's edge is.
#[test]
fn a_big_map_rides_corner_to_corner_and_shoots_off_at_its_own_edge() {
    let Some(ticks) = ride(300.0, 300.0, 45.0, 6000) else { return };
    let last = ticks.last().unwrap();
    assert!(last.wreck, "never shot back: rode to ({}, {}) in {} ticks", last.x, last.z, last.frame);
    let (riding, thrown) = ticks.split_at(ticks.len() - 1);
    // Every tick before it inside the margin and on the ground (y 0, the flat map), and past where the
    // MX Unleashed-sized ground would have ended.
    let far = riding.iter().map(|t| t.x.min(t.z)).fold(0.0, f32::max);
    assert!(far > MXU_SAMPLES * SPACING + 1000.0, "only reached {far}");
    for t in riding {
        assert!(t.x.min(t.z) > MARGIN && t.x.max(t.z) < SIDE - MARGIN, "tick {}: ({}, {})", t.frame, t.x, t.z);
        assert!(t.y.abs() < 5.0, "tick {}: off the ground at y {}", t.frame, t.y);
    }
    // And the throw is at this map's far edge, within a tick's ride and the rider's lean of it.
    let edge = thrown[0].x.max(thrown[0].z);
    assert!((edge - (SIDE - MARGIN)).abs() < 12.0, "thrown at ({}, {})", thrown[0].x, thrown[0].z);
    println!("thrown on tick {} at ({:.1}, {:.1})", thrown[0].frame, thrown[0].x, thrown[0].z);
}

/// And at the near edge too: from the middle of the low-`x` side, facing `-x`, the shootoff comes at
/// `x` = 150.
#[test]
fn a_big_map_shoots_off_at_its_near_edge() {
    let Some(ticks) = ride(600.0, SIDE / 2.0, 270.0, 1500) else { return };
    let last = ticks.last().unwrap();
    assert!(last.wreck, "never shot back: rode to ({}, {})", last.x, last.z);
    assert!((last.x - MARGIN).abs() < 12.0, "thrown at ({}, {})", last.x, last.z);
}
