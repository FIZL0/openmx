//! MD9: a combined world looks like one place. Two generated track mods side by side — tile `a`
//! painted red-brown, tile `b` green, each from its terrain's own texture page — with a join terrain
//! between them, ridden through the shell's own binary.
//!
//! What is proved: from above, the ground's colour runs from `a`'s to `b`'s across the join with no
//! step anywhere (the GPU's frame and the CPU's [`WorldPaint`] both), each tile keeping its own
//! colour inside its cells; and under World Sky Global the light is the sky tile's wherever the
//! camera is, while under Per Map a camera over `b` gets `b`'s sun, ambient and fog, mixed with `a`'s
//! only over the join. The rides skip without the disc, since the bike is the disc's.

use game_render::terrain::{BLEND_REACH, PaintTile, Pages, Regions, WorldPaint};
use game_sim::tiles::generate;
use game_sim::track::Terrain;
use std::path::{Path, PathBuf};
use std::process::Command;

/// Flat ground, so the light on it is the same everywhere and only the paint changes.
const HEIGHT: f64 = 40.0;
const RED: [u8; 3] = [200, 70, 40];
const GREEN: [u8; 3] = [50, 170, 60];

struct Spec {
    name: &'static str,
    stem: &'static str,
    at: [u32; 2],
    keep: Option<[u32; 4]>,
    cells: (u32, u32),
    page: Option<[u8; 3]>,
    /// The scene's fog colour, sun colour and ambient.
    fog: [u8; 3],
    sun: [u8; 3],
    ambient: [u8; 3],
}

const SPACING: f32 = 9.0;

/// Tile `a` at the origin owns `x` 0..504, the join from 432 shows from 504 to its last cell's start
/// at 711 (a terrain's last sample row has no cell after it), and tile `b` from 648 owns 711..1215: a
/// 207-foot join.
const SPECS: [Spec; 3] = [
    Spec { name: "a", stem: "MDA", at: [0, 0], keep: Some([0, 0, 56, 63]), cells: (4, 4), page: Some(RED), fog: [150, 151, 139], sun: [255, 240, 220], ambient: [90, 90, 90] },
    Spec { name: "b", stem: "MDB", at: [648, 0], keep: Some([7, 0, 63, 63]), cells: (4, 4), page: Some(GREEN), fog: [60, 80, 160], sun: [140, 150, 255], ambient: [40, 40, 70] },
    Spec { name: "ab", stem: "ab", at: [432, 0], keep: None, cells: (2, 4), page: None, fog: [0; 3], sun: [0; 3], ambient: [0; 3] },
];

fn terrain(s: &Spec) -> Vec<u8> {
    let colour = s.page;
    let page = move |_: u32, _: u32| colour.unwrap();
    let page: Option<&dyn Fn(u32, u32) -> [u8; 3]> = if colour.is_some() { Some(&page) } else { None };
    generate::terrain_painted(s.name, s.cells, SPACING, |_, _| HEIGHT, |_, _| 1, page)
}

/// A tile's scene: its terrain, a start line 200 feet in, its lights and a fog that never closes in.
fn scene(s: &Spec) -> String {
    let rgb = |c: [u8; 3]| format!("{},{},{}", c[0], c[1], c[2]);
    [
        "[SceneInfo]".to_string(),
        format!("SceneName=MD9 {}", s.name),
        "DefaultStartPosition=200.00,40.00,200.00".into(),
        "DefaultStartDirection=1.00,0.00,0.00".into(),
        "[Environment]".into(),
        format!("TerrainFile={}.trn", s.stem),
        format!("TerrainWidth={}", s.cells.0),
        format!("TerrainBreadth={}", s.cells.1),
        format!("TerrainWidthScale={SPACING:.2}"),
        format!("TerrainBreadthScale={SPACING:.2}"),
        "TerrainBorderWidth=0.00".into(),
        "MinDivisionSize=96.00".into(),
        "[Light0]".into(),
        "Type=Directional".into(),
        format!("ColorRGB={}", rgb(s.sun)),
        "Position=0.00,100.00,0.00".into(),
        "TargetPosition=20.00,0.00,10.00".into(),
        "[Light1]".into(),
        "Type=Ambient".into(),
        format!("ColorRGB={}", rgb(s.ambient)),
        "[Fog]".into(),
        format!("ColorRGB={}", rgb(s.fog)),
        "MinimumFogDistance=10.00".into(),
        "MaximumFogDistance=30000.00".into(),
        "Visibility=1.00".into(),
        "Haziness=0.00".into(),
        String::new(),
    ]
    .join("\r\n")
}

fn track_json(id: &str) -> String {
    format!(
        r#"{{
  "standard": 1, "kind": "track", "id": "{id}", "name": "MD9 {id}",
  "source": {{"game": "Real elevation", "data": "generated by openmx's MD9 test", "date": "2026-10-23"}},
  "version": "1.0.0", "author": "crates/openmx/tests/world_look.rs", "permission": "public-domain", "todo": []
}}"#
    )
}

fn world_json() -> String {
    let tile = |s: &Spec| format!(r#"{{"tile": "{}", "at": [{}.0, {}.0], "keep": {:?}}}"#, s.name, s.at[0], s.at[1], s.keep.unwrap());
    format!(
        r#"{{
  "standard": 1, "kind": "world", "id": "md9_world", "name": "MD9 two tiles",
  "source": {{"game": "Combined", "games": ["Real elevation"]}},
  "version": "1.0.0", "author": "crates/openmx/tests/world_look.rs", "permission": "public-domain",
  "tiles": [{}, {}],
  "joins": [{{"join": "ab", "at": [432.0, 0.0], "between": ["a", "b"]}}],
  "drop": [], "sky": "a", "spawn": {{"tile": "a"}}, "todo": []
}}"#,
        tile(&SPECS[0]),
        tile(&SPECS[1])
    )
}

fn write(root: &Path, rel: &str, bytes: impl AsRef<[u8]>) {
    let path = root.join(rel);
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, bytes).unwrap();
}

/// A `mods/` folder holding the world, `md9_world`. Each test writes its own.
fn mods_folder(test: &str) -> PathBuf {
    let mods = Path::new(env!("CARGO_TARGET_TMPDIR")).join("md9").join(test).join("mods");
    let _ = std::fs::remove_dir_all(&mods);
    let world = mods.join("tracks").join("md9_world");
    write(&world, "mod.json", world_json());
    for s in &SPECS[..2] {
        let dir = world.join("tiles").join(s.name);
        write(&dir, "mod.json", track_json(&format!("md9_{}", s.name)));
        write(&dir, &format!("Env/{0}/{0}.scn", s.stem), scene(s));
        write(&dir, &format!("Env/{0}/{0}.ps2.trn", s.stem), terrain(s));
    }
    write(&world, "joins/ab/ab.ps2.trn", terrain(&SPECS[2]));
    mods
}

/// The shell on the world, headless at 640x448 with no overlay: what it said.
fn shell(test: &str, args: &[&str]) -> Option<String> {
    if let Err(e) = game_render::disc::Disc::open_configured() {
        eprintln!("skipped: {e}");
        return None;
    }
    let mods = mods_folder(test);
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let out = Command::new(env!("CARGO_BIN_EXE_openmx"))
        .current_dir(&root)
        .args(["--headless", "--track", "md9_world", "--mods", mods.to_str().unwrap(), "--size", "640x448", "--overlay", "none"])
        .args(args)
        .output()
        .expect("the shell runs");
    let said = format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr));
    assert!(out.status.success(), "the shell failed:\n{said}");
    Some(said)
}

fn scratch(test: &str, name: &str) -> PathBuf {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join("md9").join(test);
    std::fs::create_dir_all(&dir).expect("a scratch directory");
    dir.join(name)
}

/// A PNG the shell wrote, back to its RGB pixels: its rows are filter 0 in zlib stored blocks.
fn read_png(path: &Path) -> (usize, usize, Vec<u8>) {
    let png = std::fs::read(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let be = |at: usize| u32::from_be_bytes(png[at..at + 4].try_into().unwrap()) as usize;
    let (mut at, mut size, mut idat) = (8, (0, 0), Vec::new());
    while at + 8 <= png.len() {
        let (len, tag) = (be(at), &png[at + 4..at + 8]);
        let data = &png[at + 8..at + 8 + len];
        match tag {
            b"IHDR" => size = (be(at + 8), be(at + 12)),
            b"IDAT" => idat.extend_from_slice(data),
            _ => {}
        }
        at += 12 + len;
    }
    let mut raw = Vec::new();
    let mut i = 2;
    loop {
        let last = idat[i] & 1 != 0;
        let n = u16::from_le_bytes([idat[i + 1], idat[i + 2]]) as usize;
        raw.extend_from_slice(&idat[i + 5..i + 5 + n]);
        i += 5 + n;
        if last {
            break;
        }
    }
    let (w, h) = size;
    let rgb = (0..h).flat_map(|y| raw[y * (1 + 3 * w) + 1..(y + 1) * (1 + 3 * w)].to_vec()).collect();
    (w, h, rgb)
}

/// The world's paint as the shell builds it, from the generated tiles' own pages.
fn paint() -> WorldPaint {
    let owned = SPECS[..2]
        .iter()
        .map(|s| {
            let k = s.keep.unwrap().map(|k| k as f32 * SPACING);
            [s.at[0] as f32 + k[0], s.at[1] as f32 + k[1], s.at[0] as f32 + k[2], s.at[1] as f32 + k[3]]
        })
        .collect();
    let tiles = SPECS[..2]
        .iter()
        .map(|s| {
            let bytes = terrain(s);
            let t = Terrain::parse(&bytes).expect("the generated terrain reads");
            let pages = Pages::of(&t, SPACING, (s.cells.0, s.cells.1)).expect("it has a page");
            PaintTile { at: [s.at[0] as f32, s.at[1] as f32], pages: Some(pages) }
        })
        .collect();
    WorldPaint { regions: Regions { owned }, tiles, dirt: [150.0, 118.0, 86.0] }
}

/// The CPU's paint along `z` 288 from inside `a` to inside `b`: each tile its own colour in its
/// cells, and across the join a run from one to the other with no step bigger than a tenth of a
/// foot's worth of the whole change.
#[test]
fn the_paint_blends_across_the_join_with_no_step() {
    let w = paint();
    let at = |x: f32| w.paint(x, 288.0);
    let (red, green) = (RED.map(f32::from), GREEN.map(f32::from));
    let near = |a: [f32; 3], b: [f32; 3]| (0..3).all(|k| (a[k] - b[k]).abs() < 1.5);
    for x in [10.0, 300.0, 503.9] {
        assert!(near(at(x), red), "{x}: {:?}, a's own is {red:?}", at(x));
    }
    for x in [711.0, 900.0, 1210.0] {
        assert!(near(at(x), green), "{x}: {:?}, b's own is {green:?}", at(x));
    }
    let (mut worst, mut x) = (0.0f32, 400.0f32);
    let mut last = at(x);
    while x < 800.0 {
        x += 0.25;
        let c = at(x);
        let step = (0..3).map(|k| (c[k] - last[k]).abs()).fold(0.0, f32::max);
        worst = worst.max(step);
        last = c;
    }
    // 150 levels of red over 207 feet: a seam would be the whole 150 in one step.
    assert!(worst < 1.0, "a step of {worst} levels in a quarter of a foot");
    let middle = at(612.0);
    assert!(middle[1] > 90.0 && middle[1] < 140.0 && middle[0] > 90.0 && middle[0] < 160.0, "the join's middle is {middle:?}");
    assert!(BLEND_REACH > 207.0);
}

/// The shell's GPU frame looking straight down on the join: red at one end of the middle row,
/// green at the other, and from pixel to pixel no step a seam would make.
#[test]
fn the_ground_runs_from_one_map_to_the_next_with_no_seam() {
    let path = scratch("seam", "join.png");
    let _ = std::fs::remove_file(&path);
    // Over the join's middle, 340 feet up, looking down with `+z` up the picture: the row across the
    // middle runs along `x` from about 330 to 890, `a`'s last 170 feet, the join, `b`'s first 180.
    let pose = "608,340,288,0,-89.9,60";
    let Some(said) = shell("seam", &["--frames", "2", "--shot", path.to_str().unwrap(), "--shot-pose", pose]) else { return };
    if !said.contains("renderer: gpu") {
        eprintln!("skipped: no GPU\n{said}");
        return;
    }
    assert!(said.contains("world look: 2 of 2 tiles painted from their pages"), "{said}");
    let (w, h, rgb) = read_png(&path);
    let px = |x: usize| {
        let i = 3 * ((h / 2) * w + x);
        [rgb[i] as i32, rgb[i + 1] as i32, rgb[i + 2] as i32]
    };
    let (left, right) = (px(4), px(w - 5));
    let reddish = |c: [i32; 3]| c[0] > c[1] + 40;
    let greenish = |c: [i32; 3]| c[1] > c[0] + 40;
    assert!(
        (reddish(left) && greenish(right)) || (greenish(left) && reddish(right)),
        "the row's ends are {left:?} and {right:?}, not a's red and b's green"
    );
    let mut worst = 0;
    for x in 1..w {
        let (a, b) = (px(x - 1), px(x));
        worst = worst.max((0..3).map(|k| (a[k] - b[k]).abs()).max().unwrap());
    }
    let change = (0..3).map(|k| (left[k] - right[k]).abs()).max().unwrap();
    assert!(change > 60, "the two maps are only {change} levels apart");
    assert!(worst <= 6, "a step of {worst} levels between neighbouring pixels across a change of {change}");
}

/// One `world sky:` line's numbers after `over <tile> at x,z:`: the fog colour.
fn fog_of(line: &str) -> [u8; 3] {
    let fog = line.split(" fog ").nth(1).unwrap_or_else(|| panic!("no fog in {line}"));
    let rgb: Vec<u8> = fog.split(' ').next().unwrap().split(',').map(|n| n.parse().unwrap()).collect();
    [rgb[0], rgb[1], rgb[2]]
}

fn sky_line(said: &str) -> &str {
    said.lines().find(|l| l.starts_with("world sky: over")).unwrap_or_else(|| panic!("no `world sky: over` line:\n{said}"))
}

/// Global lights the whole world with the sky tile's light, even over `b`; Per Map gives `b`'s own
/// over `b` and `a`'s own over `a`.
#[test]
fn global_keeps_one_sky_and_per_map_takes_the_tile_below() {
    let over_b = "1000,200,288,90,-30,60";
    let over_a = "200,200,288,90,-30,60";
    let Some(global) = shell("global", &["--frames", "2", "--shot-pose", over_b]) else { return };
    let line = sky_line(&global);
    assert!(line.contains("over the whole world"), "{line}");
    assert_eq!(fog_of(line), SPECS[0].fog, "{line}");
    let Some(per_map) = shell("per-map-b", &["--frames", "2", "--shot-pose", over_b, "--world-sky", "per-map"]) else { return };
    let line = sky_line(&per_map);
    assert!(line.contains("over b at 1000,288"), "{line}");
    assert_eq!(fog_of(line), SPECS[1].fog, "{line}");
    assert!(line.contains("ambient 0.157,0.157,0.275"), "b's ambient (40,40,70 of 255): {line}");
    let Some(per_map) = shell("per-map-a", &["--frames", "2", "--shot-pose", over_a, "--world-sky", "per-map"]) else { return };
    let line = sky_line(&per_map);
    assert!(line.contains("over a at 200,288"), "{line}");
    assert_eq!(fog_of(line), SPECS[0].fog, "{line}");
}

/// Per Map's light across the join: `a`'s exactly at `a`'s edge, `b`'s at `b`'s, and between them a
/// mix that moves a little at a time.
#[test]
fn per_map_light_is_mixed_across_the_join() {
    use game_render::scene::Looks;
    use game_render::v3;
    use game_render::world::Lighting;
    let lit = |s: &Spec| Lighting {
        sun: v3(0.6, -0.8, 0.0),
        sun_color: s.sun.map(|c| f32::from(c) / 255.0),
        ambient: s.ambient.map(|c| f32::from(c) / 255.0),
        fog_color: s.fog,
        fog_near: 100.0,
        fog_far: 1000.0,
    };
    let looks = Looks { regions: paint().regions, lights: vec![lit(&SPECS[0]), lit(&SPECS[1])] };
    let (a, sky) = looks.at(503.0, 288.0).unwrap();
    assert_eq!((a, sky), (lit(&SPECS[0]), 0));
    let (b, sky) = looks.at(711.0, 288.0).unwrap();
    assert_eq!((b, sky), (lit(&SPECS[1]), 1));
    let mut last = looks.at(504.0, 288.0).unwrap().0;
    let mut x = 504.0;
    while x < 711.0 {
        x += 0.5;
        let (l, _) = looks.at(x, 288.0).unwrap();
        let step = (0..3).map(|k| (l.ambient[k] - last.ambient[k]).abs()).fold(0.0, f32::max);
        assert!(step < 0.01, "the ambient jumps {step} at x {x}");
        last = l;
    }
    let (_, sky) = looks.at(560.0, 288.0).unwrap();
    assert_eq!(sky, 0, "a's sky while nearer a");
    let (_, sky) = looks.at(680.0, 288.0).unwrap();
    assert_eq!(sky, 1, "b's sky while nearer b");
}
