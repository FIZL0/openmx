//! MD51: two maps that meet across a wrapped world's seam blend like two maps across a join. On
//! world_mxu_free Dallas (mxu_free06) and Norfolk (mxu_free07) are the row's two ends, so they meet
//! only over the `x` wrap: the ground between them is join ground running up to the seam and on past
//! it. Its height was C12's (openmx-mods: stitch's field is a torus, so the far edge's ground is the
//! near edge's), but its paint was each map's by its distance in the world unwrapped, so Norfolk's
//! paint ran up to the seam and Dallas's began on it, one straight line across the world. A map is
//! now as near as its nearest copy a side over ([`game_render::terrain::Regions::period`]).
//!
//! A generated world of two flat maps, `a` red and `b` green, wrapped on `x`, through the shell's
//! own binary: the shell's `--seams` reads the ground and the paint across the join between them and
//! across the wrap from `b` round to `a`, and the wrap's change no faster than the join's; and the
//! GPU's frame looking down on the wrap runs from green to red with no step bigger than the join's.
//! Both skip without the disc, as the shell needs it. The same on world_mxu_free as openmx-mods'
//! stitch built it is ignored: it reads `$OPENMX_WORLDS/tracks/world_mxu_free` (a `mods/` folder).

use game_sim::tiles::generate;
use std::path::{Path, PathBuf};
use std::process::Command;

const HEIGHT: f64 = 40.0;
const RED: [u8; 3] = [200, 70, 40];
const GREEN: [u8; 3] = [50, 170, 60];
const SPACING: f32 = 9.0;

struct Spec {
    name: &'static str,
    stem: &'static str,
    at: [u32; 2],
    keep: Option<[u32; 4]>,
    cells: (u32, u32),
    page: Option<[u8; 3]>,
}

/// `a` owns `x` 72..504 and `b` 711..1143, with the join `ab` (432..711) between them; past `b` the
/// join `ba` runs to 1359, the world's last ground, and the seam strip the shell adds (15 cells of 9
/// feet) to 1494, the world's width; `start` lies under `a` from 0, so from `b` round to `a` is 423
/// feet of join ground, twice the 207 between them the other way.
const SPECS: [Spec; 5] = [
    Spec { name: "a", stem: "MWA", at: [0, 0], keep: Some([8, 0, 56, 63]), cells: (4, 4), page: Some(RED) },
    Spec { name: "b", stem: "MWB", at: [648, 0], keep: Some([7, 0, 55, 63]), cells: (4, 4), page: Some(GREEN) },
    Spec { name: "ab", stem: "ab", at: [432, 0], keep: None, cells: (2, 4), page: None },
    Spec { name: "ba", stem: "ba", at: [1080, 0], keep: None, cells: (2, 4), page: None },
    Spec { name: "start", stem: "start", at: [0, 0], keep: None, cells: (2, 4), page: None },
];

/// The world's width: `ba`'s last sample and the seam strip.
const WIDTH: f32 = 1359.0 + 135.0;

fn terrain(s: &Spec) -> Vec<u8> {
    let colour = s.page;
    let page = move |_: u32, _: u32| colour.unwrap();
    let page: Option<&dyn Fn(u32, u32) -> [u8; 3]> = if colour.is_some() { Some(&page) } else { None };
    generate::terrain_painted(s.name, s.cells, SPACING, |_, _| HEIGHT, |_, _| 1, page)
}

/// A map's scene: its terrain, a start line 200 feet in, one light for both, and a fog that never
/// closes in.
fn scene(s: &Spec) -> String {
    [
        "[SceneInfo]".to_string(),
        format!("SceneName=MD51 {}", s.name),
        "DefaultStartPosition=200.00,40.00,200.00".into(),
        "DefaultStartDirection=1.00,0.00,0.00".into(),
        "[Environment]".into(),
        format!("TerrainFile={}.trn", s.stem),
        format!("TerrainWidth={}", s.cells.0),
        format!("TerrainBreadth={}", s.cells.1),
        format!("TerrainWidthScale={SPACING:.2}"),
        format!("TerrainBreadthScale={SPACING:.2}"),
        "TerrainBorderWidth=0.00".into(),
        "MinDivisionSize=96.00".into(),
        "[Light0]".into(),
        "Type=Directional".into(),
        "ColorRGB=255,240,220".into(),
        "Position=0.00,100.00,0.00".into(),
        "TargetPosition=20.00,0.00,10.00".into(),
        "[Light1]".into(),
        "Type=Ambient".into(),
        "ColorRGB=90,90,90".into(),
        "[Fog]".into(),
        "ColorRGB=150,151,139".into(),
        "MinimumFogDistance=10.00".into(),
        "MaximumFogDistance=30000.00".into(),
        "Visibility=1.00".into(),
        "Haziness=0.00".into(),
        String::new(),
    ]
    .join("\r\n")
}

fn track_json(id: &str) -> String {
    format!(
        r#"{{
  "standard": 1, "kind": "track", "id": "{id}", "name": "MD51 {id}",
  "source": {{"game": "Real elevation", "data": "generated by openmx's MD51 test", "date": "2026-10-27"}},
  "version": "1.0.0", "author": "crates/openmx/tests/wrap_seam_look.rs", "permission": "public-domain", "todo": []
}}"#
    )
}

fn world_json() -> String {
    let tile = |s: &Spec| format!(r#"{{"tile": "{}", "at": [{}.0, {}.0], "keep": {:?}}}"#, s.name, s.at[0], s.at[1], s.keep.unwrap());
    let join = |s: &Spec, between: &str| format!(r#"{{"join": "{}", "at": [{}.0, {}.0], "between": {between}}}"#, s.name, s.at[0], s.at[1]);
    format!(
        r#"{{
  "standard": 1, "kind": "world", "id": "md51_world", "name": "MD51 two maps round a seam",
  "source": {{"game": "Combined", "games": ["Real elevation"]}},
  "version": "1.0.0", "author": "crates/openmx/tests/wrap_seam_look.rs", "permission": "public-domain",
  "tiles": [{}, {}],
  "joins": [{}, {}, {}],
  "drop": [], "sky": "a", "spawn": {{"tile": "a"}}, "wrap": "x", "todo": []
}}"#,
        tile(&SPECS[0]),
        tile(&SPECS[1]),
        join(&SPECS[2], r#"["a", "b"]"#),
        join(&SPECS[3], r#"["b", "a"]"#),
        join(&SPECS[4], r#"["b", "a"]"#),
    )
}

fn write(root: &Path, rel: &str, bytes: impl AsRef<[u8]>) {
    let path = root.join(rel);
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, bytes).unwrap();
}

fn scratch(test: &str, name: &str) -> PathBuf {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join("md51").join(test);
    std::fs::create_dir_all(&dir).expect("a scratch directory");
    dir.join(name)
}

/// A `mods/` folder holding the world, `md51_world`. Each test writes its own.
fn mods_folder(test: &str) -> PathBuf {
    let mods = scratch(test, "mods");
    let _ = std::fs::remove_dir_all(&mods);
    let world = mods.join("tracks").join("md51_world");
    write(&world, "mod.json", world_json());
    for s in &SPECS[..2] {
        let dir = world.join("tiles").join(s.name);
        write(&dir, "mod.json", track_json(&format!("md51_{}", s.name)));
        write(&dir, &format!("Env/{0}/{0}.scn", s.stem), scene(s));
        write(&dir, &format!("Env/{0}/{0}.ps2.trn", s.stem), terrain(s));
    }
    for s in &SPECS[2..] {
        write(&world, &format!("joins/{0}/{0}.ps2.trn", s.name), terrain(s));
    }
    mods
}

/// The shell on a world in `mods`, headless at 640x448 with no overlay: what it said, or `None`
/// without the disc.
fn shell(mods: &Path, track: &str, args: &[&str]) -> Option<String> {
    if let Err(e) = game_render::disc::Disc::open_configured() {
        eprintln!("skipped: {e}");
        return None;
    }
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let out = Command::new(env!("CARGO_BIN_EXE_openmx"))
        .current_dir(&root)
        .args(["--headless", "--no-sound", "--track", track, "--mods", mods.to_str().unwrap(), "--size", "640x448", "--overlay", "none"])
        .args(args)
        .output()
        .expect("the shell runs");
    let said = format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr));
    assert!(out.status.success(), "the shell failed:\n{said}");
    Some(said)
}

/// One `world crossing:` line's numbers: the join's width, the slope, and the blend and paint
/// changes, each a foot.
#[derive(Debug, Clone, Copy)]
struct Crossing {
    gap: f32,
    slope: f32,
    blend: f32,
    paint: f32,
}

/// The `world crossing:` line from `from` to `to` on `axis`, across the seam or not.
fn crossing(said: &str, axis: &str, from: &str, to: &str, seam: bool) -> Crossing {
    let head = format!("world crossing: {axis} {from} > {to}{}, ", if seam { " across the seam" } else { "" });
    let line = said.lines().find(|l| l.starts_with(&head)).unwrap_or_else(|| panic!("no `{head}` line:\n{said}"));
    parse(line)
}

fn parse(line: &str) -> Crossing {
    let after = |word: &str| -> f32 {
        let at = line.find(word).unwrap_or_else(|| panic!("no `{word}` in {line}")) + word.len();
        line[at..].split([' ', ',']).find(|w| !w.is_empty()).unwrap().parse().unwrap_or_else(|_| panic!("{word} in {line}"))
    };
    let gap = line.split(", ").nth(1).and_then(|w| w.split(' ').next()).and_then(|w| w.parse().ok()).unwrap_or_else(|| panic!("{line}"));
    Crossing { gap, slope: after("slope "), blend: after("blend "), paint: after("paint ") }
}

/// A PNG the shell wrote, back to its RGB pixels: its rows are filter 0 in zlib stored blocks.
fn read_png(path: &Path) -> (usize, usize, Vec<u8>) {
    let png = std::fs::read(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let be = |at: usize| u32::from_be_bytes(png[at..at + 4].try_into().unwrap()) as usize;
    let (mut at, mut size, mut idat) = (8, (0, 0), Vec::new());
    while at + 8 <= png.len() {
        let (len, tag) = (be(at), &png[at + 4..at + 8]);
        let data = &png[at + 8..at + 8 + len];
        match tag {
            b"IHDR" => size = (be(at + 8), be(at + 12)),
            b"IDAT" => idat.extend_from_slice(data),
            _ => {}
        }
        at += 12 + len;
    }
    let mut raw = Vec::new();
    let mut i = 2;
    loop {
        let last = idat[i] & 1 != 0;
        let n = u16::from_le_bytes([idat[i + 1], idat[i + 2]]) as usize;
        raw.extend_from_slice(&idat[i + 5..i + 5 + n]);
        i += 5 + n;
        if last {
            break;
        }
    }
    let (w, h) = size;
    let rgb = (0..h).flat_map(|y| raw[y * (1 + 3 * w) + 1..(y + 1) * (1 + 3 * w)].to_vec()).collect();
    (w, h, rgb)
}

/// From `b` round the seam to `a` the ground and its paint change no faster than across the join
/// between them: the same flat ground, and a blend half as steep over twice the join.
#[test]
fn across_the_wrap_the_maps_blend_like_across_a_join() {
    let mods = mods_folder("crossings");
    let Some(said) = shell(&mods, "md51_world", &["--frames", "1", "--seams"]) else { return };
    assert!(said.contains(&format!("world wraps: x every {WIDTH:.0} feet")), "{said}");
    let join = crossing(&said, "x", "a", "b", false);
    let wrap = crossing(&said, "x", "b", "a", true);
    println!("join {join:?}\nwrap {wrap:?}");
    assert!((join.gap - 207.0).abs() < 1.0 && (wrap.gap - 423.0).abs() < 1.0, "{join:?} {wrap:?}");
    assert!(wrap.slope <= join.slope + 1e-3, "the ground across the wrap is steeper: {wrap:?} against {join:?}");
    // 150 levels of red over 423 feet against 207: before MD51 the wrap was one step at the seam,
    // the whole 150 in four and a half feet, 33 a foot.
    assert!(wrap.blend > 0.0 && wrap.blend <= join.blend, "the maps blend faster across the wrap: {wrap:?} against {join:?}");
    assert!(wrap.paint <= join.paint, "the paint changes faster across the wrap: {wrap:?} against {join:?}");
}

/// The GPU's frame looking down on the wrap, `b`'s end to `a`'s start, against one looking down on
/// the join: green to red, and from pixel to pixel no step bigger than the join's.
#[test]
fn the_gpu_paints_the_wrap_like_a_join() {
    let mods = mods_folder("gpu");
    // 340 feet up with `+z` up the picture, so the middle row runs along `x`, about 560 feet: over
    // the join's middle (607), and over the wrap's (1354.5: `b`'s last 70 feet, the 423 between,
    // `a`'s first 70, drawn on the world's copy one width over).
    let mut rows = Vec::new();
    for (name, x) in [("join", 607.5), ("wrap", 1354.5)] {
        let path = scratch("gpu", &format!("{name}.png"));
        let _ = std::fs::remove_file(&path);
        let pose = format!("{x},340,288,0,-89.9,60");
        let Some(said) = shell(&mods, "md51_world", &["--frames", "2", "--shot", path.to_str().unwrap(), "--shot-pose", &pose]) else { return };
        if !said.contains("renderer: gpu") {
            eprintln!("skipped: no GPU\n{said}");
            return;
        }
        let (w, h, rgb) = read_png(&path);
        let px = |x: usize| {
            let i = 3 * ((h / 2) * w + x);
            [rgb[i] as i32, rgb[i + 1] as i32, rgb[i + 2] as i32]
        };
        let row: Vec<[i32; 3]> = (0..w).map(px).collect();
        rows.push((name, row));
    }
    let reddish = |c: [i32; 3]| c[0] > c[1] + 40;
    let greenish = |c: [i32; 3]| c[1] > c[0] + 40;
    let worst = |row: &[[i32; 3]]| row.windows(2).map(|p| (0..3).map(|k| (p[0][k] - p[1][k]).abs()).max().unwrap()).max().unwrap();
    let (join, wrap) = (&rows[0].1, &rows[1].1);
    let (left, right) = (wrap[4], wrap[wrap.len() - 5]);
    assert!(greenish(left) && reddish(right), "the wrap's row runs from {left:?} to {right:?}, not b's green to a's red");
    let (j, w) = (worst(join), worst(wrap));
    println!("the steepest step from pixel to pixel: {j} levels over the join, {w} over the wrap");
    assert!(w <= j, "a step of {w} levels across the wrap, {j} across the join");
}

/// world_mxu_free as openmx-mods' stitch builds it off the user's disc (C12 or later): Norfolk to
/// Dallas over the `x` wrap against every join stitch made between two of its maps. Not in this
/// repository, so ignored; the journal entry has its run.
#[test]
#[ignore = "needs world_mxu_free from openmx-mods' stitch (C12 or later) in $OPENMX_WORLDS/tracks, and the disc"]
fn dallas_and_norfolk_meet_like_two_stitched_neighbours() {
    let mods = PathBuf::from(std::env::var_os("OPENMX_WORLDS").expect("OPENMX_WORLDS: a mods/ folder with tracks/world_mxu_free"));
    let said = shell(&mods, "world_mxu_free", &["--frames", "1", "--seams"]).expect("the disc");
    let wrap = crossing(&said, "x", "mxu_free07", "mxu_free06", true);
    let joins: Vec<Crossing> = said.lines().filter(|l| l.starts_with("world crossing: ") && !l.contains(" across the seam")).map(parse).collect();
    println!("Norfolk to Dallas {wrap:?}");
    for l in said.lines().filter(|l| l.starts_with("world crossing: ")) {
        println!("{l}");
    }
    assert!(!joins.is_empty(), "no joins between two maps:\n{said}");
    let most = |f: fn(&Crossing) -> f32| joins.iter().map(f).fold(0.0, f32::max);
    assert!(wrap.slope <= most(|c| c.slope) + 1e-3, "the ground: {wrap:?}, the joins' steepest {}", most(|c| c.slope));
    assert!(wrap.blend <= most(|c| c.blend), "the maps' blend: {wrap:?}, the joins' steepest {}", most(|c| c.blend));
    // Dallas's own join, to its neighbour mxu_free10 the other way.
    let dallas = crossing(&said, "x", "mxu_free06", "mxu_free10", false);
    assert!(wrap.blend <= dallas.blend, "the maps' blend: {wrap:?}, Dallas to mxu_free10 {dallas:?}");
}
