//! MD8: a world mod — three track mods at three spacings (9, 4.5 and 6 feet a sample) laid in a row
//! along `x`, with a join terrain between each two — ridden through the shell's own binary.
//!
//! Every terrain is written by the test from one rolling height function in world feet
//! ([`game_sim::tiles::generate`]), so the ground runs on across the joins and nothing is off a disc.
//! The rides skip without the disc, since the bike and its physics are the disc's.
//!
//! What is proved: the world rides end to end across both joins on the ground, and is shot back only
//! at its outer edge; the first tile, at the world's origin, rides tick for tick to the bit as it does
//! alone; and every tile's ground as the world reads it from the mod's files is that tile's alone.

use game_sim::contact_search;
use game_sim::tiles::{generate, Piece, Reach, Source, Tile, Tiled};
use game_sim::track::{Terrain, TerrainLayout};
use game_sim::world::Ground;
use ps2_float::{F, Vf};
use std::path::{Path, PathBuf};
use std::process::Command;

/// The shootoff's margin, `game_sim::off_map::MARGIN`.
const MARGIN: f32 = 150.0;

/// Gentle rolling ground: a bike rides it on the gas without leaving it for long.
fn relief(x: f64, z: f64) -> f64 {
    40.0 + 1.5 * (x / 140.0).sin() * (z / 90.0).cos()
}

struct Spec {
    name: &'static str,
    /// The scene's stem, upper case.
    stem: &'static str,
    at: [u32; 2],
    spacing: f32,
    cells: (u32, u32),
    keep: Option<[u32; 4]>,
}

/// Tile `a` at the origin (9 ft), join `ab`, tile `b` (4.5 ft), join `bc`, tile `c` (6 ft): `a` keeps
/// to `x` 504, the join to 711 under `b` from 684, `b` to 1188, the second join to 1431 under `c` from
/// 1368, and `c` to 1722, the world's outer edge.
const SPECS: [Spec; 5] = [
    Spec { name: "a", stem: "MDA", at: [0, 0], spacing: 9.0, cells: (4, 4), keep: Some([0, 0, 56, 63]) },
    Spec { name: "b", stem: "MDB", at: [648, 0], spacing: 4.5, cells: (8, 8), keep: Some([8, 0, 120, 127]) },
    Spec { name: "c", stem: "MDC", at: [1344, 0], spacing: 6.0, cells: (4, 4), keep: Some([4, 0, 63, 63]) },
    Spec { name: "ab", stem: "ab", at: [432, 0], spacing: 9.0, cells: (2, 4), keep: None },
    Spec { name: "bc", stem: "bc", at: [1152, 0], spacing: 9.0, cells: (2, 4), keep: None },
];

/// The world's far corner: `c`'s last kept sample, and `b`'s.
const WIDTH: f32 = 1344.0 + 63.0 * 6.0;
const DEPTH: f32 = 127.0 * 4.5;

fn terrain(s: &Spec) -> Vec<u8> {
    let sp = f64::from(s.spacing);
    let (ox, oz) = (f64::from(s.at[0]), f64::from(s.at[1]));
    generate::terrain(s.name, s.cells, s.spacing, |x, z| relief(ox + f64::from(x) * sp, oz + f64::from(z) * sp), |_, _| 1)
}

fn layout(s: &Spec) -> TerrainLayout {
    TerrainLayout {
        width: s.cells.0,
        breadth: s.cells.1,
        width_scale: F(s.spacing),
        breadth_scale: F(s.spacing),
        ..TerrainLayout::default()
    }
}

/// A tile's scene: its terrain, its size, and a start line 200 feet in, facing `+x`.
fn scene(s: &Spec) -> String {
    [
        "[SceneInfo]",
        &format!("SceneName=MD8 {}", s.name),
        "DefaultStartPosition=200.00,40.00,200.00",
        "DefaultStartDirection=1.00,0.00,0.00",
        "[Environment]",
        &format!("TerrainFile={}.trn", s.stem),
        &format!("TerrainWidth={}", s.cells.0),
        &format!("TerrainBreadth={}", s.cells.1),
        &format!("TerrainWidthScale={:.2}", s.spacing),
        &format!("TerrainBreadthScale={:.2}", s.spacing),
        "TerrainBorderWidth=0.00",
        "MinDivisionSize=96.00",
        "[Fog]",
        "ColorRGB=150,151,139",
        "",
    ]
    .join("\r\n")
}

fn track_json(id: &str) -> String {
    format!(
        r#"{{
  "standard": 1, "kind": "track", "id": "{id}", "name": "MD8 {id}",
  "source": {{"game": "Real elevation", "data": "generated by openmx's MD8 test", "date": "2026-10-22"}},
  "version": "1.0.0", "author": "crates/openmx/tests/tiled_world.rs", "permission": "public-domain", "todo": []
}}"#
    )
}

fn world_json() -> String {
    let tiles: Vec<String> = SPECS[..3]
        .iter()
        .map(|s| format!(r#"{{"tile": "{}", "at": [{}.0, {}.0], "keep": {:?}}}"#, s.name, s.at[0], s.at[1], s.keep.unwrap()))
        .collect();
    let joins: Vec<String> = SPECS[3..]
        .iter()
        .map(|s| {
            let between: Vec<String> = s.name.chars().map(|c| format!("\"{c}\"")).collect();
            format!(r#"{{"join": "{}", "at": [{}.0, {}.0], "between": [{}]}}"#, s.name, s.at[0], s.at[1], between.join(", "))
        })
        .collect();
    format!(
        r#"{{
  "standard": 1, "kind": "world", "id": "md8_world", "name": "MD8 three tiles",
  "source": {{"game": "Combined", "games": ["Real elevation"]}},
  "version": "1.0.0", "author": "crates/openmx/tests/tiled_world.rs", "permission": "public-domain",
  "tiles": [{}],
  "joins": [{}],
  "drop": [], "sky": "a", "spawn": {{"tile": "a"}}, "todo": []
}}"#,
        tiles.join(", "),
        joins.join(", ")
    )
}

fn write(root: &Path, rel: &str, bytes: impl AsRef<[u8]>) {
    let path = root.join(rel);
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, bytes).unwrap();
}

/// A track mod's files in `dir`.
fn track_files(dir: &Path, s: &Spec, id: &str) {
    write(dir, "mod.json", track_json(id));
    write(dir, &format!("Env/{0}/{0}.scn", s.stem), scene(s));
    write(dir, &format!("Env/{0}/{0}.ps2.trn", s.stem), terrain(s));
}

/// A `mods/` folder holding the world, `md8_world`, and each tile alone as its own track mod,
/// `md8_a`, `md8_b` and `md8_c`. Each test writes its own, so they run side by side.
fn mods_folder(test: &str) -> PathBuf {
    let mods = Path::new(env!("CARGO_TARGET_TMPDIR")).join("md8").join(test).join("mods");
    let _ = std::fs::remove_dir_all(&mods);
    let world = mods.join("tracks").join("md8_world");
    write(&world, "mod.json", world_json());
    for s in &SPECS[..3] {
        track_files(&world.join("tiles").join(s.name), s, &format!("md8_{}", s.name));
        track_files(&mods.join("tracks").join(format!("md8_{}", s.name)), s, &format!("md8_{}", s.name));
    }
    for s in &SPECS[3..] {
        write(&world, &format!("joins/{0}/{0}.ps2.trn", s.name), terrain(s));
    }
    mods
}

fn shell(test: &str, track: &str, args: &[&str]) -> Option<String> {
    if let Err(e) = game_render::disc::Disc::open_configured() {
        eprintln!("skipped: {e}");
        return None;
    }
    let mods = mods_folder(test);
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let out = Command::new(env!("CARGO_BIN_EXE_openmx"))
        .current_dir(&root)
        .args(["--headless", "--track", track, "--mods", mods.to_str().unwrap()])
        .args(args)
        .output()
        .expect("the shell runs");
    let said = format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr));
    assert!(out.status.success(), "the shell failed:\n{said}");
    Some(said)
}

fn line<'a>(said: &'a str, prefix: &str) -> &'a str {
    said.lines().find(|l| l.starts_with(prefix)).unwrap_or_else(|| panic!("no `{prefix}` line:\n{said}"))
}

/// One traced tick, its numbers as printed, and where the bike is.
struct Tick {
    frame: usize,
    text: String,
    x: f32,
    y: f32,
    z: f32,
    wreck: bool,
}

/// `--trace-feel` on the gas from `x,z` facing `degrees`, up to the first wreck.
fn ride(test: &str, track: &str, x: f32, z: f32, degrees: f32, frames: usize) -> Option<Vec<Tick>> {
    let at = format!("{x},{z},{degrees}");
    let n = frames.to_string();
    let said = shell(test, track, &["--trace", &n, "--trace-gas", "--trace-feel", "--trace-at", &at])?;
    let mut out = Vec::new();
    for l in said.lines() {
        let w: Vec<&str> = l.split_whitespace().collect();
        let Some(frame) = w.first().and_then(|f| f.parse::<usize>().ok()) else { continue };
        if w.len() != 12 {
            continue;
        }
        let f = |i: usize| w[i].parse::<f32>().unwrap();
        let tick = Tick { frame, text: w[1..].join(" "), x: f(5), y: f(6), z: f(7), wreck: w[11] == "1" };
        let wrecked = tick.wreck;
        out.push(tick);
        if wrecked {
            break;
        }
    }
    assert!(!out.is_empty(), "no trace rows:\n{said}");
    Some(out)
}

/// The world loads as one ride: its line, its edge over the whole and the spawn tile's start.
#[test]
fn a_world_loads_as_one_ride() {
    let Some(said) = shell("loads", "md8_world", &["--frames", "2"]) else { return };
    assert_eq!(
        line(&said, "world: md8_world"),
        format!("world: md8_world (MD8 three tiles), 3 tiles and 2 joins, {WIDTH:.0} x {DEPTH:.0} feet, lit by a")
    );
    let map = line(&said, "map: ");
    assert!(map.starts_with(&format!("map: {WIDTH:.0} x {DEPTH:.0} feet to its edge, shot back from 150 feet")), "{map}");
}

/// On the gas along `+x` from tile `a`: across the first join onto `b`, across the second onto `c`,
/// on the ground all the way, and shot back only at the world's far edge.
#[test]
fn a_world_rides_across_both_joins_and_shoots_off_at_its_outer_edge() {
    let Some(ticks) = ride("across", "md8_world", 200.0, 220.0, 90.0, 600) else { return };
    let last = ticks.last().unwrap();
    assert!(last.wreck, "never shot back: rode to ({}, {}) in {} ticks", last.x, last.z, last.frame);
    let (riding, thrown) = ticks.split_at(ticks.len() - 1);
    for (piece, from, to) in [("ab", 504.0, 684.0), ("b", 684.0, 1188.0), ("bc", 1188.0, 1368.0), ("c", 1368.0, 1500.0)] {
        let on = riding.iter().filter(|t| t.x > from && t.x < to).count();
        assert!(on > 3, "only {on} ticks on {piece}");
    }
    for t in riding {
        let ground = relief(f64::from(t.x), f64::from(t.z)) as f32;
        assert!((t.y - ground).abs() < 6.0, "tick {}: at y {} over ground {ground} at ({}, {})", t.frame, t.y, t.x, t.z);
        assert!(t.x < WIDTH - MARGIN && t.z > MARGIN && t.z < DEPTH - MARGIN, "tick {}: ({}, {})", t.frame, t.x, t.z);
    }
    assert!((thrown[0].x - (WIDTH - MARGIN)).abs() < 12.0, "thrown at ({}, {})", thrown[0].x, thrown[0].z);
    println!("thrown on tick {} at ({:.1}, {:.1})", thrown[0].frame, thrown[0].x, thrown[0].z);
}

/// Tile `a` is at the world's origin, so a ride on it is the same floats as on `a` alone: tick for
/// tick to the bit, up to where the world's join begins.
#[test]
fn the_tile_at_the_origin_rides_as_it_does_alone() {
    let Some(world) = ride("origin_world", "md8_world", 160.0, 200.0, 90.0, 240) else { return };
    let Some(alone) = ride("origin_alone", "md8_a", 160.0, 200.0, 90.0, 240) else { return };
    let mut compared = 0;
    for (w, a) in world.iter().zip(&alone) {
        if w.x > 480.0 {
            break;
        }
        assert_eq!(w.text, a.text, "tick {}", w.frame);
        compared += 1;
    }
    assert!(compared > 60, "only {compared} ticks before the join");
}

/// The same ride on tile `b`, 648 feet out in the world and at its own origin alone: the ground is
/// the same, the sums are not. How long they stay together, for the journal.
#[test]
fn a_tile_away_from_the_origin_parts_from_itself_alone() {
    let Some(world) = ride("far_world", "md8_world", 648.0 + 200.0, 200.0, 90.0, 200) else { return };
    let Some(alone) = ride("far_alone", "md8_b", 200.0, 200.0, 90.0, 200) else { return };
    let mut first = None;
    let mut worst = 0.0f32;
    for (w, a) in world.iter().zip(&alone) {
        if w.x > 1150.0 {
            break;
        }
        let dx = (w.x - 648.0 - a.x).abs().max((w.y - a.y).abs()).max((w.z - a.z).abs());
        if dx > 0.0 && first.is_none() {
            first = Some(w.frame);
        }
        worst = worst.max(dx);
    }
    println!("b in the world against b alone: first apart on tick {first:?}, at most {worst} ft apart");
    let rows = |t: &[Tick]| t.iter().take(4).map(|t| format!("{} {}", t.frame, t.text)).collect::<Vec<_>>().join("\n");
    assert!(worst < 0.5, "{worst} ft apart\n{}\n--\n{}", rows(&world), rows(&alone));
}

/// The world reads each piece from the mod's own files: under every piece, at every point it owns,
/// the ground is that piece's terrain alone, to the bit.
#[test]
fn every_tiles_ground_from_the_mods_files_is_its_own() {
    let mods = mods_folder("files");
    let world = mods.join("tracks").join("md8_world");
    let path = |s: &Spec| match s.keep {
        Some(_) => world.join("tiles").join(s.name).join(format!("Env/{0}/{0}.ps2.trn", s.stem)),
        None => world.join("joins").join(s.name).join(format!("{}.ps2.trn", s.name)),
    };
    struct Files(Vec<PathBuf>);
    impl Source for Files {
        fn load(&mut self, i: usize) -> Result<Piece, String> {
            Ok(Piece { terrain: std::fs::read(&self.0[i]).map_err(|e| e.to_string())?, shapes: Vec::new() })
        }
    }
    let tiles = SPECS
        .iter()
        .map(|s| {
            let mut t = Tile {
                name: s.name.into(),
                at: s.at.map(|a| F(a as f32)),
                layout: layout(s),
                spacing: F(s.spacing),
                levels: 1,
                keep: [0; 4],
                first_owner: 0,
            };
            t.keep = s.keep.unwrap_or_else(|| t.every_cell());
            t
        })
        .collect();
    let tiled = Tiled::new(tiles, Box::new(Files(SPECS.iter().map(path).collect())), Reach::DESKTOP).unwrap();
    let files: Vec<Vec<u8>> = SPECS.iter().map(|s| std::fs::read(path(s)).unwrap()).collect();
    let mut per = [0usize; 5];
    for i in 0..1800 {
        for j in 0..60 {
            let (x, z) = (i as f32 * 0.9573 + 0.01, j as f32 * 9.531 + 0.3);
            let Some((owner, lx, lz)) = tiled.owner(F(x), F(z)) else { continue };
            let s = &SPECS[owner];
            let terrain = Terrain::parse(&files[owner]).unwrap();
            let alone = Ground::new(&terrain, &layout(s));
            let (got, want) = (tiled.at(F(x), F(z)).unwrap(), alone.at(lx, lz).unwrap());
            assert_eq!((got.y.0.to_bits(), got.surface), (want.y.0.to_bits(), want.surface), "({x}, {z})");
            assert_eq!(got.normal.0.map(f32::to_bits), want.normal.0.map(f32::to_bits));
            let g = contact_search::ground(&tiled.field(), Vf::new(x, 500.0, z, 1.0));
            let a = contact_search::ground(&alone.field(), Vf::new(lx.0, 500.0, lz.0, 1.0));
            assert_eq!(g.point.y().to_bits(), a.point.y().to_bits(), "({x}, {z})");
            assert_eq!(g.normal.0.map(f32::to_bits), a.normal.0.map(f32::to_bits));
            per[owner] += 1;
        }
    }
    assert!(per.iter().all(|&n| n > 500), "{per:?}");
}
