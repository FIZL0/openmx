//! MD29/MD44: the biplane flown over a wrapped world's seam is drawn going straight on, and so is its
//! camera — "when flying biplane across the wrap i can see it teleport me a bit".
//!
//! The world is `tests/wrapped_world.rs`' two generated tiles, wrapped on both axes (1269 x 702
//! feet). The shell flies the plane east off the start line on full throttle, headless, drawn at
//! 60 pictures a second, and `--trace-picture` says where each picture drew the plane and the eye.
//! Brought round by the world's width, the plane and the eye move on as they move everywhere else.
//! Before the fix the crossing tick cut the picture (the plane stepped two frames' way and stood a
//! frame), and the plane's camera was carried over the seam as a jump — the width and the tick's
//! flight too — so the eye leapt 7.4 feet in a frame, 3.4 feet onto the plane, and eased back. The
//! bike ridden round the same world is held to the same.

use game_sim::tiles::generate;
use game_sim::track::TerrainLayout;
use ps2_float::F;
use std::path::{Path, PathBuf};
use std::process::Command;

/// Rolling ground that climbs to the east, so the seam join has a step to close.
fn relief(x: f64, z: f64) -> f64 {
    40.0 + 8.0 * x / 1134.0 + 1.5 * (x / 140.0).sin() * (z / 90.0).cos()
}

/// The tiles: `a` at the origin, `b` beside it, each 63 cells of 9 feet.
const TILES: [(&str, &str, u32); 2] = [("a", "MWA", 0), ("b", "MWB", 567)];

/// The world before its seam join, and the join's width: 15 cells of the tiles' 9 feet.
const OPEN: f32 = 1134.0;
const STRIP: f32 = 135.0;
const WIDTH: f32 = OPEN + STRIP;

fn terrain(at: u32) -> Vec<u8> {
    generate::terrain("t", (4, 4), 9.0, |x, z| relief(f64::from(at) + f64::from(x) * 9.0, f64::from(z) * 9.0), |_, _| 1)
}

/// A tile's scene: its terrain, its size, and a start line 200 feet in, facing `+x`.
fn scene(name: &str, stem: &str) -> String {
    let layout = TerrainLayout { width: 4, breadth: 4, width_scale: F(9.0), breadth_scale: F(9.0), ..TerrainLayout::default() };
    [
        "[SceneInfo]",
        &format!("SceneName=MD29 {name}"),
        "DefaultStartPosition=200.00,40.00,283.00",
        "DefaultStartDirection=1.00,0.00,0.00",
        "[Environment]",
        &format!("TerrainFile={stem}.trn"),
        &format!("TerrainWidth={}", layout.width),
        &format!("TerrainBreadth={}", layout.breadth),
        &format!("TerrainWidthScale={:.2}", layout.width_scale.0),
        &format!("TerrainBreadthScale={:.2}", layout.breadth_scale.0),
        "TerrainBorderWidth=0.00",
        "MinDivisionSize=96.00",
        "[Fog]",
        "ColorRGB=150,151,139",
        "",
    ]
    .join("\r\n")
}

fn track_json(id: &str) -> String {
    format!(
        r#"{{
  "standard": 1, "kind": "track", "id": "{id}", "name": "MD29 {id}",
  "source": {{"game": "Real elevation", "data": "generated by openmx's MD29 test", "date": "2026-10-27"}},
  "version": "1.0.0", "author": "crates/openmx/tests/wrapped_world.rs", "permission": "public-domain", "todo": []
}}"#
    )
}

/// The world's file, with `wrap` as its switch's JSON (none at all for `None`).
fn world_json(id: &str, wrap: Option<&str>) -> String {
    let tiles: Vec<String> = TILES.iter().map(|(name, _, at)| format!(r#"{{"tile": "{name}", "at": [{at}.0, 0.0], "keep": [0, 0, 63, 63]}}"#)).collect();
    let wrap = wrap.map(|w| format!(r#""wrap": {w}, "#)).unwrap_or_default();
    format!(
        r#"{{
  "standard": 1, "kind": "world", "id": "{id}", "name": "MD29 flown",
  "source": {{"game": "Combined", "games": ["Real elevation"]}},
  "version": "1.0.0", "author": "crates/openmx/tests/wrapped_world.rs", "permission": "public-domain",
  "tiles": [{}],
  "joins": [],
  {wrap}"drop": [], "sky": "a", "spawn": {{"tile": "a"}}, "todo": []
}}"#,
        tiles.join(", ")
    )
}

fn write(root: &Path, rel: &str, bytes: impl AsRef<[u8]>) {
    let path = root.join(rel);
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, bytes).unwrap();
}

/// A `mods/` folder holding the world wrapped on both axes, `md29f_round`. Each test writes its own,
/// so they run side by side.
fn mods_folder(test: &str) -> PathBuf {
    let mods = Path::new(env!("CARGO_TARGET_TMPDIR")).join("md29f").join(test).join("mods");
    let _ = std::fs::remove_dir_all(&mods);
    for (id, wrap) in [("md29f_round", Some(r#""xz""#))] {
        let world = mods.join("tracks").join(id);
        write(&world, "mod.json", world_json(id, wrap));
        for (name, stem, at) in TILES {
            let dir = world.join("tiles").join(name);
            write(&dir, "mod.json", track_json(&format!("md29f_{name}")));
            write(&dir, &format!("Env/{stem}/{stem}.scn"), scene(name, stem));
            write(&dir, &format!("Env/{stem}/{stem}.ps2.trn"), terrain(at));
        }
    }
    mods
}


/// Full throttle and nothing else, at the 30 Hz cap: Cross down, at full pressure — the bike's gas
/// and the plane's throttle alike.
fn throttle_tape(frames: usize) -> String {
    let mut text = format!("# game-sim pad tape: {frames} frames\nformat 1\ntape full throttle\n");
    let report = format!("0079ff{:02x}7f7f7f7f000000000000{:02x}{}", 0xbf, 0xff, "00".repeat(17));
    for _ in 0..frames {
        text += &format!("frame 0x3d088889 0x{report} -\n");
    }
    text
}

/// The shell on the world from its start line east, on the throttle tape for `ticks` ticks, drawn at
/// 60 a second, in the plane when `vehicle` says so: what it said, or `None` with no disc to ride.
fn ride(test: &str, vehicle: &[&str], ticks: usize) -> Option<String> {
    if let Err(e) = game_render::disc::Disc::open_configured() {
        eprintln!("skipped: {e}");
        return None;
    }
    let mods = mods_folder(test);
    let tape = mods.parent().unwrap().join("throttle.tape");
    std::fs::write(&tape, throttle_tape(ticks + 30)).expect("the tape is written");
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let out = Command::new(env!("CARGO_BIN_EXE_openmx"))
        .current_dir(&root)
        .args(["--headless", "--no-sound", "--track", "md29f_round", "--mods", mods.to_str().unwrap()])
        .args(vehicle)
        .args(["--trace-at", "200,283,90", "--trace-picture", "--draw-fps", "60", "--frames", &ticks.to_string()])
        .args(["--play", tape.to_str().unwrap()])
        .output()
        .expect("the shell runs");
    let said = format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr));
    assert!(out.status.success(), "the shell failed:\n{said}");
    Some(said)
}

/// One drawn frame: its tick, whether it cut, the machine's spot at the tick before and at its own,
/// where it was drawn, and the camera's eye.
#[derive(Debug, Clone, Copy)]
struct Frame {
    tick: u64,
    cut: bool,
    from: [f32; 3],
    to: [f32; 3],
    drawn: [f32; 3],
    eye: [f32; 3],
}

/// The plane's `picture plane:` lines, or the bike's `picture:` lines.
fn frames(said: &str, plane: bool) -> Vec<Frame> {
    let prefix = if plane { "picture plane: " } else { "picture: " };
    said.lines()
        .filter_map(|l| l.strip_prefix(prefix))
        .map(|l| {
            let w: Vec<&str> = l.split_whitespace().collect();
            let n = |i: usize| -> f32 { w[i].parse().unwrap_or_else(|_| panic!("word {i} of {l}")) };
            let p = |i: usize| -> [f32; 3] { [n(i), n(i + 1), n(i + 2)] };
            // The bike's line has `down N bike` before its `from`.
            let o = if plane { 0 } else { 3 };
            assert_eq!((w[0], w[4], w[6 + o], w[10 + o], w[14 + o], w[18 + o]), ("tick", "cut", "from", "to", "drawn", "eye"), "{l}");
            Frame { tick: n(1) as u64, cut: w[5] == "1", from: p(7 + o), to: p(11 + o), drawn: p(15 + o), eye: p(19 + o) }
        })
        .collect()
}

/// `x` brought within half a width of `near` (the world wraps every [`WIDTH`] feet along x).
fn unwrap(x: f32, near: f32) -> f32 {
    x - ((x - near) / WIDTH).round() * WIDTH
}

/// Every frame after the first takes off: the machine and the eye go on along x by no more than the
/// tick's own move, never back, with the gap between them all but unchanged — brought round the
/// world's width over the seam, which the machine crosses at least once, on a tick that does not
/// cut. `moving` is the least a tick's move along x must be for the frame to be held to it.
fn goes_straight_over(shown: &[Frame], what: &str, moving: f32) {
    let mut crossings = 0;
    let mut checked = 0;
    let (mut worst_eye, mut worst_gap) = (0f32, 0f32);
    for (a, b) in shown.iter().zip(&shown[1..]) {
        let tick = b.to[0] - unwrap(b.from[0], b.to[0]);
        if tick < moving || a.tick + 1 < b.tick {
            continue;
        }
        // The first frame of the tick that took the machine over: its spot a width from the last.
        let crossed = (b.to[0] - a.to[0]).abs() > WIDTH / 2.0;
        if crossed {
            crossings += 1;
            assert!(!b.cut, "{what}: the tick over the seam cut the picture: {a:?} then {b:?}");
        }
        let drawn = b.drawn[0] - unwrap(a.drawn[0], b.drawn[0]);
        let eye = b.eye[0] - unwrap(a.eye[0], b.eye[0]);
        let gap = (b.drawn[0] - unwrap(b.eye[0], b.drawn[0])) - (a.drawn[0] - unwrap(a.eye[0], a.drawn[0]));
        assert!(drawn > -1e-3 && drawn < tick + 0.05, "{what}: drawn {drawn:.3} ft on in a frame of a {tick:.3} ft tick: {a:?} then {b:?}");
        assert!(eye > -1e-3 && eye < tick + 0.5, "{what}: the eye {eye:.3} ft on in a frame of a {tick:.3} ft tick: {a:?} then {b:?}");
        assert!(gap.abs() < 1.0, "{what}: the camera came {gap:.3} ft nearer or further in a frame: {a:?} then {b:?}");
        (worst_eye, worst_gap) = (worst_eye.max(eye - tick), worst_gap.max(gap.abs()));
        checked += 1;
    }
    assert!(crossings >= 1, "{what}: never over the seam in {} frames ({checked} checked)", shown.len());
    println!("{what}: {checked} frames checked, {crossings} over the seam; the eye at most {worst_eye:.3} ft past a tick's move, the gap {worst_gap:.3} ft");
}

#[test]
fn a_plane_flown_over_the_seam_is_drawn_straight_on() {
    let Some(said) = ride("plane", &["--vehicle", "biplane"], 900) else { return };
    let shown = frames(&said, true);
    assert!(!shown.is_empty(), "no `picture plane:` lines:\n{said}");
    goes_straight_over(&shown, "plane", 2.0);
}

#[test]
fn a_bike_ridden_over_the_seam_is_drawn_straight_on() {
    let Some(said) = ride("bike", &[], 1300) else { return };
    let shown = frames(&said, false);
    assert!(!shown.is_empty(), "no `picture:` lines:\n{said}");
    goes_straight_over(&shown, "bike", 1.0);
}
