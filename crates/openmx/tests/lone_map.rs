//! MD22: one generated terrain smaller than a throw's arc, ridden alone through the shell's own binary.
//!
//! The map is a track mod the test writes ([`game_sim::tiles::generate`]): 16 × 16 cells of 16 samples
//! at 2 feet, 510 feet a side, under a scene's `TerrainWidth=1` as a one-level tree's is. An edge throw
//! flies a bike much further than that, and a wreck can come down off the field, where a lone
//! terrain's ground query answers no ground. Before MD22 the put-back record kept such a spot and the
//! bike was put back at `y` −10⁶. The rides skip without the disc, since the bike and its physics are
//! the disc's.

use game_sim::tiles::generate;
use std::path::{Path, PathBuf};
use std::process::Command;

const SPACING: f32 = 2.0;
const SIDE: f32 = 255.0 * SPACING;

/// Gentle rolling ground, as MD8's world has.
fn relief(x: f64, z: f64) -> f64 {
    40.0 + 1.5 * (x / 140.0).sin() * (z / 90.0).cos()
}

fn scene() -> String {
    [
        "[SceneInfo]",
        "SceneName=MD22 lone",
        "DefaultStartPosition=255.00,40.00,255.00",
        "DefaultStartDirection=1.00,0.00,0.00",
        "[Environment]",
        "TerrainFile=MDL.trn",
        "TerrainWidth=1",
        "TerrainBreadth=1",
        &format!("TerrainWidthScale={SPACING:.2}"),
        &format!("TerrainBreadthScale={SPACING:.2}"),
        "TerrainBorderWidth=0.00",
        "MinDivisionSize=32.00",
        "[Fog]",
        "ColorRGB=150,151,139",
        "",
    ]
    .join("\r\n")
}

fn write(root: &Path, rel: &str, bytes: impl AsRef<[u8]>) {
    let path = root.join(rel);
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, bytes).unwrap();
}

/// A `mods/` folder holding the one track mod, `md22_lone`; each test writes its own.
fn mods_folder(test: &str) -> PathBuf {
    let mods = Path::new(env!("CARGO_TARGET_TMPDIR")).join("md22").join(test).join("mods");
    let _ = std::fs::remove_dir_all(&mods);
    let dir = mods.join("tracks").join("md22_lone");
    write(
        &dir,
        "mod.json",
        r#"{"standard": 1, "kind": "track", "id": "md22_lone", "name": "MD22 lone", "source": {"game": "Real elevation", "data": "generated by openmx's MD22 test"}, "version": "1.0.0", "author": "crates/openmx/tests/lone_map.rs", "permission": "public-domain", "todo": []}"#,
    );
    write(&dir, "Env/MDL/MDL.scn", scene());
    let sp = f64::from(SPACING);
    let trn = generate::terrain("mdl", (16, 16), SPACING, |x, z| relief(f64::from(x) * sp, f64::from(z) * sp), |_, _| 1);
    write(&dir, "Env/MDL/MDL.ps2.trn", trn);
    mods
}

/// One traced tick: where the bike is, and whether it is down.
struct Tick {
    frame: usize,
    x: f32,
    y: f32,
    z: f32,
    wreck: bool,
}

/// `--trace-feel` on the gas from `x,z` facing `degrees`, on through every wreck.
fn ride(test: &str, x: f32, z: f32, degrees: f32, frames: usize) -> Option<Vec<Tick>> {
    if let Err(e) = game_render::disc::Disc::open_configured() {
        eprintln!("skipped: {e}");
        return None;
    }
    let mods = mods_folder(test);
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let (at, n) = (format!("{x},{z},{degrees}"), frames.to_string());
    let out = Command::new(env!("CARGO_BIN_EXE_openmx"))
        .current_dir(&root)
        .args(["--headless", "--track", "md22_lone", "--mods", mods.to_str().unwrap()])
        .args(["--trace", &n, "--trace-gas", "--trace-feel", "--trace-at", &at])
        .output()
        .expect("the shell runs");
    let said = format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr));
    assert!(out.status.success(), "the shell failed:\n{said}");
    let mut ticks = Vec::new();
    for l in said.lines() {
        let w: Vec<&str> = l.split_whitespace().collect();
        let Some(frame) = w.first().and_then(|f| f.parse::<usize>().ok()) else { continue };
        if w.len() != 12 {
            continue;
        }
        let f = |i: usize| w[i].parse::<f32>().unwrap();
        ticks.push(Tick { frame, x: f(5), y: f(6), z: f(7), wreck: w[11] == "1" });
    }
    assert!(!ticks.is_empty(), "no trace rows:\n{said}");
    Some(ticks)
}

/// Ridden off each side through throw after throw, the bike is never under the map or away from it:
/// every tick is within a few feet of the field (a put-back by the `x = 0` or `z = 0` edge can sit a
/// foot or two short of it, where the ground query clamps onto the field) and above the relief's
/// lowest point. Before MD22 the 270° ride was put back at `y` −10⁶ past the far edge, `x` 512, on its
/// second throw and sat there for 316 ticks.
#[test]
fn a_lone_terrain_smaller_than_a_throw_never_puts_the_bike_on_no_ground() {
    let mut throws = 0;
    for degrees in [270.0, 0.0, 90.0, 180.0, 45.0, 315.0] {
        let Some(ticks) = ride(&format!("throws_{degrees}"), SIDE / 2.0, SIDE / 2.0, degrees, 3000) else { return };
        assert_eq!(ticks.len(), 3000, "{degrees}°: the trace stopped at {}", ticks.len());
        let mut down = false;
        for t in &ticks {
            let near = |v: f32| (-20.0..SIDE + 20.0).contains(&v);
            assert!(near(t.x) && near(t.z), "{degrees}°, tick {}: off the map at ({}, {}, {})", t.frame, t.x, t.y, t.z);
            assert!(t.y > 30.0, "{degrees}°, tick {}: at y {} under the map at ({}, {})", t.frame, t.y, t.x, t.z);
            throws += usize::from(t.wreck && !down);
            down = t.wreck;
        }
    }
    println!("{throws} throws");
    assert!(throws >= 20, "{throws} throws");
}
