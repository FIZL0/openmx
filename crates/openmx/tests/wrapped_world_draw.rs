//! MD43: a wrapped world drawn across its seam, through the shell's own binary. The world is
//! `tests/wrapped_world.rs`'s (MD29): two generated track mods in a row along `x` and the seam join
//! past the far one, with `"wrap": "x"`, and the same world without the switch.
//!
//! What is proved: a `--shot` from 30 feet short of the far seam, looking east across it, shows the
//! ground of the world's near side over the seam on the GPU and in software alike, where the same
//! shot at the edge of the world without the switch shows sky; and the radar's dot of a rider just
//! over the seam sits by the radar's middle, not on its rim (`hud::radar_near`), and the label east
//! names the map over the seam (`MapNames::around_in`) — those two are `hud.rs`'s own tests, the
//! HUD not being in the library.

use game_sim::tiles::generate;
use game_sim::track::TerrainLayout;
use ps2_float::F;
use std::path::{Path, PathBuf};
use std::process::Command;

/// Rolling ground that climbs to the east, so the seam join has a step to close.
fn relief(x: f64, z: f64) -> f64 {
    40.0 + 8.0 * x / 1134.0 + 1.5 * (x / 140.0).sin() * (z / 90.0).cos()
}

/// The tiles: `a` at the origin, `b` beside it, each 63 cells of 9 feet.
const TILES: [(&str, &str, u32); 2] = [("a", "MWA", 0), ("b", "MWB", 567)];

/// The world before its seam join, and the join's width: 15 cells of the tiles' 9 feet.
const OPEN: f32 = 1134.0;
const STRIP: f32 = 135.0;
const WIDTH: f32 = OPEN + STRIP;
const DEPTH: f32 = 567.0;

fn terrain(at: u32) -> Vec<u8> {
    generate::terrain("t", (4, 4), 9.0, |x, z| relief(f64::from(at) + f64::from(x) * 9.0, f64::from(z) * 9.0), |_, _| 1)
}

/// A tile's scene: its terrain, its size, and a start line 200 feet in, facing `+x`.
fn scene(name: &str, stem: &str) -> String {
    let layout = TerrainLayout { width: 4, breadth: 4, width_scale: F(9.0), breadth_scale: F(9.0), ..TerrainLayout::default() };
    [
        "[SceneInfo]",
        &format!("SceneName=MD29 {name}"),
        "DefaultStartPosition=200.00,40.00,283.00",
        "DefaultStartDirection=1.00,0.00,0.00",
        "[Environment]",
        &format!("TerrainFile={stem}.trn"),
        &format!("TerrainWidth={}", layout.width),
        &format!("TerrainBreadth={}", layout.breadth),
        &format!("TerrainWidthScale={:.2}", layout.width_scale.0),
        &format!("TerrainBreadthScale={:.2}", layout.breadth_scale.0),
        "TerrainBorderWidth=0.00",
        "MinDivisionSize=96.00",
        "[Fog]",
        "ColorRGB=150,151,139",
        "",
    ]
    .join("\r\n")
}

fn track_json(id: &str) -> String {
    format!(
        r#"{{
  "standard": 1, "kind": "track", "id": "{id}", "name": "MD29 {id}",
  "source": {{"game": "Real elevation", "data": "generated by openmx's MD29 test", "date": "2026-10-27"}},
  "version": "1.0.0", "author": "crates/openmx/tests/wrapped_world.rs", "permission": "public-domain", "todo": []
}}"#
    )
}

/// The world's file, with `wrap` as its switch's JSON (none at all for `None`). The start is `a`'s
/// own in world feet: a tile spawn on a wrapped world moves to the middle tile (MD50), here `b`, and
/// the software renderer's ground follows the rider, so the seam's far side would be out of its reach.
fn world_json(id: &str, wrap: Option<&str>) -> String {
    let tiles: Vec<String> = TILES.iter().map(|(name, _, at)| format!(r#"{{"tile": "{name}", "at": [{at}.0, 0.0], "keep": [0, 0, 63, 63]}}"#)).collect();
    let wrap = wrap.map(|w| format!(r#""wrap": {w}, "#)).unwrap_or_default();
    format!(
        r#"{{
  "standard": 1, "kind": "world", "id": "{id}", "name": "MD29 round",
  "source": {{"game": "Combined", "games": ["Real elevation"]}},
  "version": "1.0.0", "author": "crates/openmx/tests/wrapped_world.rs", "permission": "public-domain",
  "tiles": [{}],
  "joins": [],
  {wrap}"drop": [], "sky": "a", "spawn": {{"position": [200, 40, 283], "direction": [1, 0, 0]}}, "todo": []
}}"#,
        tiles.join(", ")
    )
}

fn write(root: &Path, rel: &str, bytes: impl AsRef<[u8]>) {
    let path = root.join(rel);
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, bytes).unwrap();
}

/// A `mods/` folder holding the world wrapped, `md29_round`, and the same world with no switch,
/// `md29_edged`. Each test writes its own, so they run side by side.
fn mods_folder(test: &str) -> PathBuf {
    let mods = Path::new(env!("CARGO_TARGET_TMPDIR")).join("md43").join(test).join("mods");
    let _ = std::fs::remove_dir_all(&mods);
    for (id, wrap) in [("md29_round", Some(r#""x""#)), ("md29_edged", None)] {
        let world = mods.join("tracks").join(id);
        write(&world, "mod.json", world_json(id, wrap));
        for (name, stem, at) in TILES {
            let dir = world.join("tiles").join(name);
            write(&dir, "mod.json", track_json(&format!("md29_{name}")));
            write(&dir, &format!("Env/{stem}/{stem}.scn"), scene(name, stem));
            write(&dir, &format!("Env/{stem}/{stem}.ps2.trn"), terrain(at));
        }
    }
    mods
}

/// A PNG the shell wrote, back to its RGB pixels: its rows are filter 0 in zlib stored blocks.
fn read_png(path: &Path) -> (usize, usize, Vec<u8>) {
    let png = std::fs::read(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let be = |at: usize| u32::from_be_bytes(png[at..at + 4].try_into().unwrap()) as usize;
    let (mut at, mut size, mut idat) = (8, (0, 0), Vec::new());
    while at + 8 <= png.len() {
        let (len, tag) = (be(at), &png[at + 4..at + 8]);
        let data = &png[at + 8..at + 8 + len];
        match tag {
            b"IHDR" => size = (be(at + 8), be(at + 12)),
            b"IDAT" => idat.extend_from_slice(data),
            _ => {}
        }
        at += 12 + len;
    }
    let mut raw = Vec::new();
    let mut i = 2;
    loop {
        let last = idat[i] & 1 != 0;
        let n = u16::from_le_bytes([idat[i + 1], idat[i + 2]]) as usize;
        raw.extend_from_slice(&idat[i + 5..i + 5 + n]);
        i += 5 + n;
        if last {
            break;
        }
    }
    let (w, h) = size;
    let rgb = (0..h).flat_map(|y| raw[y * (1 + 3 * w) + 1..(y + 1) * (1 + 3 * w)].to_vec()).collect();
    (w, h, rgb)
}

/// A `--shot` of `track` from `pose` with `renderer`, at 320x224 with no overlay: the renderer the
/// shell drew with, and the picture. `None` without the disc.
fn shot(test: &str, track: &str, renderer: &str, pose: &str) -> Option<(String, Vec<u8>)> {
    if let Err(e) = game_render::disc::Disc::open_configured() {
        eprintln!("skipped: {e}");
        return None;
    }
    let mods = mods_folder(test);
    let png = mods.parent().unwrap().join(format!("{track}-{renderer}.png"));
    let _ = std::fs::remove_file(&png);
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let out = Command::new(env!("CARGO_BIN_EXE_openmx"))
        .current_dir(&root)
        .args(["--headless", "--track", track, "--mods", mods.to_str().unwrap(), "--size", "320x224", "--overlay", "none"])
        .args(["--renderer", renderer, "--graphics", "original", "--shot-pose", pose, "--shot", png.to_str().unwrap(), "--frames", "3"])
        .output()
        .expect("the shell runs");
    let said = format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr));
    assert!(out.status.success(), "the shell failed:\n{said}");
    let drew = said.lines().find_map(|l| l.strip_prefix("renderer: ")).unwrap_or("?").to_string();
    let (w, h, rgb) = read_png(&png);
    assert_eq!((w, h), (320, 224));
    Some((drew, rgb))
}

/// The share of the box between the horizon and the middle of the picture — the ground 45 feet and
/// more ahead, past the seam — that is not the colour of the sky straight above it at the top.
fn ground_share(rgb: &[u8]) -> f32 {
    let px = |x: usize, y: usize| -> [u8; 3] { std::array::from_fn(|k| rgb[3 * (y * 320 + x) + k]) };
    let (mut ground, mut all) = (0, 0);
    for y in 75..108 {
        for x in (80..240).step_by(2) {
            let sky = px(x, 2);
            all += 1;
            if px(x, y).iter().zip(sky).any(|(a, b)| a.abs_diff(b) > 24) {
                ground += 1;
            }
        }
    }
    ground as f32 / all as f32
}

/// A pose `back` feet short of `edge` along `x`, over the ground (40 to 50 feet up there), looking
/// east and 15 degrees down.
fn pose(edge: f32, back: f32) -> String {
    format!("{},62,283,90,-15,85", edge - back)
}

#[test]
fn a_shot_across_the_seam_shows_the_far_sides_ground() {
    for renderer in ["gpu", "software"] {
        // The wrapped world, 30 feet short of its seam: the join's ground under the eye.
        let Some((drew, round)) = shot("shot", "md29_round", renderer, &pose(WIDTH, 30.0)) else { return };
        // The world without the switch, as far short of its edge.
        let Some((_, edged)) = shot("shot", "md29_edged", renderer, &pose(OPEN, 30.0)) else { return };
        let (over, off) = (ground_share(&round), ground_share(&edged));
        eprintln!("{renderer} ({drew}): across the seam {over}, past the edge {off}");
        assert!(off < 0.1, "{drew}: past the edge of the world without the switch is sky, but {off} of it is not");
        assert!(over > 0.9, "{drew}: across the seam is ground, but only {over} of it");
    }
}
