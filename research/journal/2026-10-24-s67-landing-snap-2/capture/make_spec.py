"""S67: write landings.toml, the capture spec for animandpump's landings.

usage: python3 -B make_spec.py > landings.toml   (run from this folder)

S109's animandpump.toml front (the counter, dt, the rng and the pad, which the port's tape is read
from) followed by watch/s64-wheels.toml's whole bike — chassis integrator, both wheels' spin-step
state, the drivetrain, the balance — moved onto this state's chains (the rider one `next` hop down
the list, the vehicle six), and the air state and the rider's sticks beside it.
"""

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
G = '@game_manager -> 0x34 -> 0x34'
OLD_BIKE = G + ' -> 0x8' * 8 + ' -> 0x0'
OLD_RIDER = G + ' -> 0x8 -> 0x8 -> 0x0'
BIKE = G + ' -> 0x8' * 6 + ' -> 0x0'
RIDER = G + ' -> 0x8 -> 0x0'

s109 = (ROOT / 'research/journal/2026-10-23-s109-animandpump/capture/animandpump.toml').read_text()
front = s109[s109.index('[watch]'):s109.index('[[field]]\nname = "rider_ctl_src"')]
front = front.replace('name        = "s109-animandpump"', 'name        = "s67-landings"')
front = re.sub(r'description = ".*"', 'description = "animandpump played back: the whole bike through its landings"', front)
front = re.sub(r'frames      = \d+', 'frames      = 1600', front)

s64 = (ROOT / 'watch/s64-wheels.toml').read_text()
blocks = s64.split('\n[[field]]')[1:]
body = []
for b in blocks:
    name = re.search(r'name = "([^"]+)"', b).group(1)
    if name in ('frame_counter', 'dt'):
        continue
    b = b.replace(OLD_BIKE, '@@BIKE@@').replace(OLD_RIDER, RIDER).replace('@@BIKE@@', BIKE)
    # s64's run ends on a null rider; here the chain is null for a frame while Play loads the state.
    b = b.replace('required = true\n', '')
    body.append('\n[[field]]' + b.rstrip('\n') + '\n')


def field(name, off, kind):
    return f'\n[[field]]\nname = "{name}"\naddr = "{RIDER} -> {off:#x}"\ntype = "{kind}"\n'


extra = [field(n, o, k) for n, o, k in [
    ('on_ground', 0x574, 'u32'), ('both_wheels', 0x578, 'u32'), ('airborne', 0x57c, 'u32'),
    ('was_airborne', 0x580, 'u32'), ('hang_time', 0x4f0, 'f32'), ('contact_vel', 0x430, 'f32x4'),
    ('crossup', 0x600, 'f32'), ('stick_y', 0x62c, 'f32'), ('stick_v', 0x630, 'f32'),
    ('lean_x', 0x670, 'f32'), ('lean_y', 0x674, 'f32'),
    ('balance_inertia', 0xa4c, 'f32'), ('balance_noise_time', 0xa6c, 'f32'),
    ('pitch_integral', 0x724, 'f32'), ('stoppie', 0x728, 'u32'),
]]
sys.stdout.write('# landings.toml: generated by make_spec.py beside it. Do not edit.\n\n'
                 + front.rstrip('\n') + '\n' + ''.join(body) + ''.join(extra))
