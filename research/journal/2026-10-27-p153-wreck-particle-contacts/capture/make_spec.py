"""P153: write p153.toml, the capture spec for the wreck's contact emitters over animandpump.

usage: python3 -B make_spec.py > p153.toml   (run from this folder)

The human's bike particle manager is P74's (its make_spec.py). This one reads the five entries the
wreck runs — 0 Vehicle Dust, 1 Vehicle Chunks (CollisionModel), 2 Rider Dust, 3 Rider Chunks, 4 Foot
Dust (ParticleCollisionConstraint) — and what they read:

* each entry's flag byte, and its emitter's switch byte (+0x240), carry (+0x3b0), point (+0x40) and
  the point it last came from (+0x60), its zone (+0x214) and its view-cull rate scale (+0x254);
* the crash body both CollisionModel entries read (entry +0x28 -> -> body): its ground and object
  words (+0x48, +0x4c), its velocity (+0x1e0), its contact count (+0x100) and the first CONTACTS of
  its contact list (+0x108, 0x80 apart: the point at +0x40, the zone index at +0x70);
* the rider's collision spheres the constraint entries walk (entry -> +0x30 -> list at +0x14, count
  at +0x10): each one's ground and object words (+0x18, +0x1c), zone byte (+0x3c), point (+0x40)
  and its bone's velocity (+0x80 -> +0x70).
"""

G = '@game_manager -> 0x34 -> 0x34'
RIDER = G + ' -> 0x8 -> 0x0'
BIKE = G + ' -> 0x8' * 6 + ' -> 0x0'
CONTACTS = 12
SPHERES = 9


def field(name, addr, kind):
    return f'\n[[field]]\nname = "{name}"\naddr = "{addr}"\ntype = "{kind}"\n'


def entry(i):
    return f'{RIDER} -> 0x1490 -> 0x3c -> {4 * i:#x}'


out = ['''# p153.toml: generated by make_spec.py beside it. Do not edit.

[watch]
name        = "p153-wreck-contacts"
description = "animandpump played back: the wreck's crash-body and ragdoll contacts and the five entries that emit off them"
every       = 1
frames      = 400

[setup]
warmup = 0
''']
out.append(field('frame_counter', '@frame_counter', 'u32'))
out.append(field('dt', '@frame_dt', 'f32'))
out.append(field('rider_type', f'{RIDER} -> 0x0', 'u32'))
out.append(field('wreck_reason', f'{RIDER} -> 0x748', 'u32'))
out.append(field('s868', f'{RIDER} -> 0x868', 'u32'))
out.append(field('bike_xform', f'{BIKE} -> 0x180', 'mat4'))
for i in range(5):
    e = entry(i)
    out.append(field(f'e{i}_flag', f'{e} -> 0x8', 'u8'))
    out.append(field(f'e{i}_on', f'{e} -> 0x14 -> 0x240', 'u8'))
    out.append(field(f'e{i}_carry', f'{e} -> 0x14 -> 0x3b0', 'f32'))
    out.append(field(f'e{i}_at', f'{e} -> 0x14 -> 0x40', 'f32x4'))
    out.append(field(f'e{i}_from', f'{e} -> 0x14 -> 0x60', 'f32x4'))
    out.append(field(f'e{i}_zone', f'{e} -> 0x14 -> 0x214', 'u32'))
    out.append(field(f'e{i}_scale', f'{e} -> 0x14 -> 0x254', 'f32'))
body = f'{entry(0)} -> 0x28 -> 0x0'
out.append(field('body_ground', f'{body} -> 0x48', 'u32'))
out.append(field('body_object', f'{body} -> 0x4c', 'u32'))
out.append(field('body_vel', f'{body} -> 0x1e0', 'f32x4'))
out.append(field('body_n', f'{body} -> 0x100', 'u32'))
for c in range(CONTACTS):
    out.append(field(f'c{c}_at', f'{body} -> 0x108 -> {0x80 * c + 0x40:#x}', 'f32x4'))
    out.append(field(f'c{c}_zone', f'{body} -> 0x108 -> {0x80 * c + 0x70:#x}', 'u32'))
spheres = f'{entry(2)} -> 0x0 -> 0x30'
out.append(field('spheres_n', f'{spheres} -> 0x10', 'u32'))
for s in range(SPHERES):
    p = f'{spheres} -> 0x14 -> {4 * s:#x}'
    out.append(field(f'r{s}_ground', f'{p} -> 0x18', 'u32'))
    out.append(field(f'r{s}_object', f'{p} -> 0x1c', 'u32'))
    out.append(field(f'r{s}_zone', f'{p} -> 0x3c', 'u8'))
    out.append(field(f'r{s}_at', f'{p} -> 0x40', 'f32x4'))
    out.append(field(f'r{s}_vel', f'{p} -> 0x80 -> 0x70', 'f32x4'))
print(''.join(out))
