"""P74: write p74.toml, the capture spec for the bike's particle manager over animandpump.

usage: python3 -B make_spec.py > p74.toml   (run from this folder)

The human's rider record in animandpump's state is the actor list's second node (S109). Off it: the
words the bike hands its particle manager (the stunt-state snapshot at +0x860..+0x948, which the
manager reads through the pointers at +0xf60), the live words they are copied from (the throttle and
clutch, the chassis' speed, each wheel's contact, spin, compression, side force and surface), the
manager's two tire records' flags, and for each of the manager's 15 entries its flag byte, its
emitter's switch byte and carry, and the sprays' fade clock and side velocity. The order of the
entries is the file's (walk_state.py lists them off the state).
"""

G = '@game_manager -> 0x34 -> 0x34'
RIDER = G + ' -> 0x8 -> 0x0'
BIKE = G + ' -> 0x8' * 6 + ' -> 0x0'
ENTRIES = 15
SPRAYS = range(8, 13)


def field(name, addr, kind):
    return f'\n[[field]]\nname = "{name}"\naddr = "{addr}"\ntype = "{kind}"\n'


out = ['''# p74.toml: generated by make_spec.py beside it. Do not edit.

[watch]
name        = "p74-bike-particles"
description = "animandpump played back: the bike's particle manager, its entries and what feeds them"
every       = 1
frames      = 2410

[setup]
warmup = 0
''']
out.append(field('frame_counter', '@frame_counter', 'u32'))
out.append(field('dt', '@frame_dt', 'f32'))
out.append(field('rider_type', f'{RIDER} -> 0x0', 'u32'))
out.append(field('wreck_reason', f'{RIDER} -> 0x748', 'u32'))
out.append(field('on_ground', f'{RIDER} -> 0x574', 'u32'))
out.append(field('airborne', f'{RIDER} -> 0x57c', 'u32'))
out.append(field('bike_xform', f'{BIKE} -> 0x180', 'mat4'))
out.append(field('bike_vel', f'{BIKE} -> 0x130', 'f32x4'))
# The snapshot the manager reads.
for off, kind in [(0x860, 'f32'), (0x868, 'u32'), (0x86c, 'f32'), (0x870, 'f32'), (0x87c, 'f32'),
                  (0x880, 'f32'), (0x888, 'f32'), (0x88c, 'f32'), (0x910, 'u8'), (0x911, 'u8'),
                  (0x914, 'u32'), (0x918, 'u32'), (0x91c, 'u32'), (0x920, 'u32'), (0x924, 'u32'),
                  (0x928, 'u32'), (0x92c, 'u32'), (0x930, 'u32'), (0x934, 'u32'), (0x938, 'u32')]:
    out.append(field(f's{off:x}', f'{RIDER} -> {off:#x}', kind))
# What it is copied from.
out.append(field('throttle', f'{RIDER} -> 0x658', 'f32'))
out.append(field('clutch', f'{RIDER} -> 0x65c', 'f32'))
out.append(field('speed', f'{RIDER} -> 0x7a4 -> 0x34', 'f32'))
for side, ptr in [('f', 0x7b0), ('r', 0x7b4)]:
    for name, off, kind in [('ground', 0xd0, 'u32'), ('object', 0xd4, 'u32'), ('spin', 0xe0, 'u32'),
                            ('lock', 0xe4, 'u32'), ('slide', 0xe8, 'u32'), ('comp', 0xf0, 'f32'),
                            ('surface', 0x110, 'u8'), ('side', 0x234, 'f32')]:
        out.append(field(f'{side}_{name}', f'{RIDER} -> {ptr:#x} -> {off:#x}', kind))
for t, base in [(0, 0), (1, 0x2c)]:
    out.append(field(f't{t}_flags', f'{RIDER} -> 0xf64 -> {base + 0x28:#x}', 'u8'))
    out.append(field(f't{t}_zone', f'{RIDER} -> 0xf64 -> {base + 0x29:#x}', 'u8'))
for i in range(ENTRIES):
    e = f'{RIDER} -> 0x1490 -> 0x3c -> {4 * i:#x}'
    out.append(field(f'e{i}_flag', f'{e} -> 0x8', 'u8'))
    out.append(field(f'e{i}_on', f'{e} -> 0x14 -> 0x240', 'u8'))
    out.append(field(f'e{i}_carry', f'{e} -> 0x14 -> 0x3b0', 'f32'))
    out.append(field(f'e{i}_at', f'{e} -> 0x14 -> 0x40', 'f32x4'))
    if i in SPRAYS:
        out.append(field(f'e{i}_clock', f'{e} -> 0x28', 'f32'))
        out.append(field(f'e{i}_vx', f'{e} -> 0x14 -> 0x80', 'f32'))
        out.append(field(f'e{i}_rate', f'{e} -> 0x14 -> 0x340', 'f32'))
        out.append(field(f'e{i}_noise_hi', f'{e} -> 0x14 -> 0x370', 'f32x4'))
    if i in (5, 6):
        out.append(field(f'e{i}_vy', f'{e} -> 0x14 -> 0x84', 'f32'))
print(''.join(out))
