"""S109: write animandpump.toml, the capture spec for the user's animandpump recording.

usage: python3 -B make_spec.py > animandpump.toml   (run from this folder)

It is watch/s56-ragdoll.toml (every ragdoll bone's body, the body actor's flags, the holds, the riding
request, the skeleton's rests) with its pointer chains moved to this state's actor list, its
recording2-only heap words dropped, and S109's own columns added: the preload meter's movie variable
(V53), the rider's lean pair and the pose it is shown at, the rider body's animation machine, the
bike's two struts and their ground normals, and the trick clocks.

In animandpump's state the human's rider record is the list's *second* node (one `next` hop, not
recording2's two) and the human's vehicle the seventh (six hops, not eight); the speedometer's
preload variable hangs off 0x016b649c, its latch is 0x016b64a0 (V53's were 0x01b0a30c/0x01b0a310).
All read off the state's RAM image (context/capture/s109/start.ee.bin), see the journal.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
G = '@game_manager -> 0x34 -> 0x34'
OLD_BIKE = G + ' -> 0x8' * 8 + ' -> 0x0'
OLD_RIDER = G + ' -> 0x8 -> 0x8 -> 0x0'
BIKE = G + ' -> 0x8' * 6 + ' -> 0x0'
RIDER = G + ' -> 0x8 -> 0x0'

src = (ROOT / 'watch/s56-ragdoll.toml').read_text()
body = src[src.index('[watch]'):]
body = body.replace(OLD_BIKE, '@@BIKE@@').replace(OLD_RIDER, RIDER).replace('@@BIKE@@', BIKE)
body = body.replace('name        = "s56-ragdoll"', 'name        = "s109-animandpump"')
body = re.sub(r'description = ".*"', 'description = "animandpump played back: the riding ragdoll, the meter, the lean, the struts"', body)
body = re.sub(r'frames      = \d+', 'frames      = 1210', body)
# The recording2 heap words S62 laid in: another state's addresses, nothing here.
blocks = body.split('\n[[')
keep = [b for b in blocks if not re.search(r'^field\]\]\nname = "w[0-9a-f]{7}"', b)]
body = '\n[['.join(keep)


def field(name, addr, kind):
    return f'\n[[field]]\nname = "{name}"\naddr = "{addr}"\ntype = "{kind}"\n'


extra = []
# rider_type first among the new ones: the start trigger reads it.
extra.append(field('rider_type', f'{RIDER} -> 0x0', 'u32'))
extra.append(field('meter_var', '0x016b649c -> 0xc', 'u32'))
extra.append(field('meter_latch', '0x016b64a0', 'u32'))
for name, off, kind in [
    ('avail', 0x4a0, 'u32'), ('firing', 0x4a4, 'u32'), ('armed', 0x4a8, 'u32'), ('timer', 0x4b0, 'f32'),
    ('force', 0x494, 'f32'), ('max', 0x4c4, 'f32'), ('hide', 0x868, 'u32'),
    ('stick_y', 0x62c, 'f32'), ('stick_v', 0x630, 'f32'),
    ('lean_x', 0x670, 'f32'), ('lean_y', 0x674, 'f32'), ('shown_pose', 0x9e8, 'f32'), ('shown_fore_aft', 0x9ec, 'f32'),
    ('on_ground', 0x574, 'u32'), ('both_wheels', 0x578, 'u32'), ('airborne', 0x57c, 'u32'),
    ('g_peak', 0x550, 'f32x4'),
    ('flip_on', 0x4fc, 'u32'), ('trick_running', 0xa0c, 'u32'), ('trick_elapsed', 0xa1c, 'f32'),
    ('trick_id', 0xa78, 'u32'), ('trick_req', 0xa7c, 'u32'),
]:
    extra.append(field(name, f'{RIDER} -> {off:#x}', kind))
for side, ptr in [('f', 0x7b0), ('r', 0x7b4)]:
    for name, off, kind in [('comp', 0xf0, 'f32'), ('force', 0xf8, 'f32'), ('hit', 0xd0, 'u32'), ('normal', 0x200, 'f32x4'),
                            ('load_point', 0x140, 'f32x4')]:
        extra.append(field(f'{side}_{name}', f'{RIDER} -> {ptr:#x} -> {off:#x}', kind))
extra.append(field('ch_ang_vel', f'{RIDER} -> 0x7a4 -> 0x280', 'f32x4'))
# The rider body's animation machine (rider-joints.toml's offsets, on the body actor = vehicle - 0x400).
extra.append(field('d_flags', f'{BIKE} -> 0x680 - 0x400', 'bytes:40'))
extra.append(field('d_cross', f'{BIKE} -> 0x8dc - 0x400', 'bytes:36'))
extra.append(field('m_clock', f'{BIKE} -> 0x48 - 0x400', 'bytes:80'))
extra.append(field('d_lags', f'{BIKE} -> 0x630 - 0x400', 'bytes:8'))

head, arrays = body.split('\n[[array]]\nname   = "col"', 1)
out = head.rstrip('\n') + '\n' + ''.join(extra) + '\n[[array]]\nname   = "col"' + arrays
# The joints' blended translations beside their quaternions: the pose the riding spring pulls to.
out = out.rstrip('\n') + '\n\n[[array.field]]\nname = "pos"\noff  = 0x40\ntype = "f32x4"\n'
sys.stdout.write('# animandpump.toml: generated by make_spec.py beside it, from watch/s56-ragdoll.toml. Do not edit.\n\n' + out)
