"""C18: write the capture spec for a car's particle manager over an S149a car drive.

usage: python3 -B make_spec.py CAR MGR ENTRIES > spec.toml

CAR is the car (0x00605270 in every S149a free07 state), MGR the car's word holding its particle
manager (+0xf00 the buggy's and baja's, +0xff0 the truck's), ENTRIES the manager's entry count (22, 22,
21 with the four tire tracks). Off the car: the wreck reason (+0x2c4) and its lift flag (+0x2c8), the
loader's wreck word (+0x754) and the feed's pointer to it (+0xa94), the throttle, clutch and ground speed
the feed points at, each tire's words the four records point at, each record's flag and zone bytes, and
for each entry its flag byte, its emitter's switch byte, carry, rate and point, and a spray's fade clock
and side velocity. Body place and velocity for the frame count.
"""
import sys

CAR, MGR, ENTRIES = int(sys.argv[1], 0), int(sys.argv[2], 0), int(sys.argv[3])
C = f'{CAR:#010x}'


def field(name, addr, kind):
    return f'\n[[field]]\nname = "{name}"\naddr = "{addr}"\ntype = "{kind}"\n'


out = ['''# generated by make_spec.py (C18). Do not edit.

[watch]
name        = "c18-car-particles"
description = "an S149a car drive: the car's particle manager and the words it reads"
every       = 1
frames      = 660

[setup]
warmup = 0
''']
out.append(field('frame_counter', '@frame_counter', 'u32'))
out.append(field('dt', '@frame_dt', 'f32'))
out.append(field('car_kind', f'{C} + 0xd50', 'u32'))
out.append(field('wreck_reason', f'{C} + 0x2c4', 'u32'))
out.append(field('wreck_lifted', f'{C} + 0x2c8', 'u32'))
out.append(field('w754', f'{C} + 0x754', 'u32'))
out.append(field('feed_wreck', f'{C} + 0xa94', 'u32'))
out.append(field('throttle', f'{C} + 0x3ec', 'f32'))
out.append(field('clutch', f'{C} + 0x3f0', 'f32'))
out.append(field('speed', f'{C} + 0x55c', 'f32'))
out.append(field('body_pos', f'{C} + 0x160 -> 0x60', 'f32x4'))
out.append(field('body_vel', f'{C} + 0x160 -> 0x70', 'f32x4'))
for t, ptr in enumerate([0x548, 0x54c, 0x550, 0x554]):
    for name, off, kind in [('solid', 0xb4, 'u32'), ('sorted', 0xb8, 'u32'), ('comp', 0xdc, 'f32'),
                            ('slip', 0x1e4, 'u32'), ('lock', 0x1ec, 'u32'), ('side', 0x2b0, 'f32'),
                            ('surface', 0x100, 'u8')]:
        out.append(field(f't{t}_{name}', f'{C} + {ptr:#x} -> {off:#x}', kind))
    out.append(field(f'r{t}_flags', f'{C} + 0xa74 -> {0x2c * t + 0x28:#x}', 'u8'))
    out.append(field(f'r{t}_zone', f'{C} + 0xa74 -> {0x2c * t + 0x29:#x}', 'u8'))
for i in range(ENTRIES):
    e = f'{C} + {MGR:#x} -> 0x3c -> {4 * i:#x}'
    out.append(field(f'e{i}_flag', f'{e} -> 0x8', 'u8'))
    out.append(field(f'e{i}_on', f'{e} -> 0x14 -> 0x240', 'u8'))
    out.append(field(f'e{i}_carry', f'{e} -> 0x14 -> 0x3b0', 'f32'))
    out.append(field(f'e{i}_rate', f'{e} -> 0x14 -> 0x340', 'f32'))
    out.append(field(f'e{i}_at', f'{e} -> 0x14 -> 0x40', 'f32x4'))
    out.append(field(f'e{i}_clock', f'{e} -> 0x28', 'f32'))
    out.append(field(f'e{i}_vx', f'{e} -> 0x14 -> 0x80', 'f32'))
print(''.join(out))
