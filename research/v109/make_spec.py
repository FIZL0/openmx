"""V109's spec: the 2p tape's P1 reverse runs and P2's air entries (frames 139950..140420), with the
pose a fade starts from. Per rider, beside C11's machine words and the 22 posed joints (the blend
buffer: joint record +0x40 translation, +0x50 quaternion):

  * the joint record's transform node (+0x34), its local matrix's four rows (+0x40..+0x70) -- what
    anim_rewind reads (anim_joint_rotation / anim_joint_translation);
  * the motion object's snapshot buffers: +0x248 one quaternion per joint, +0x24c one translation;
  * the ragdoll's flags and its 18 parts' positions (s56-ragdoll.toml), to see who wrote the nodes.

The rider body is the bike actor - 0x400, as in watch/2p.toml; the fields it shares are copied out of
that file by name.

    python3 -B research/v109/make_spec.py > research/v109/snap.toml
"""
import re

SRC = 'watch/2p.toml'
KEEP = ['type', 'joint_count', 'mode', 'rag_flags', 'settled', 'm_clock', 'd_flags', 'd_cross',
        'd_reverse', 'lag_mix', 'lag_phase', 'req_placing', 'req_axes', 'airborne']

text = open(SRC).read()
blocks = re.split(r'\n(?=\[\[)', text)
fields = {}
for b in blocks:
    m = re.search(r'name\s*=\s*"([^"]+)"', b)
    if m and b.startswith('[[field]]'):
        fields[m.group(1)] = b.strip()

print('''# V109: generated by research/v109/make_spec.py (edit that, not this). Played by
# research/c10/play_capture.sh with SPEC=research/v109/snap.toml, FIRST 139950, N 471.

[watch]
name        = "v109-snap"
description = "the 2p tape's reverse and air fades: posed joints, their nodes and the snapshot"
every       = 1
frames      = 471

[setup]
warmup = 0

[[field]]
name = "frame_counter"
addr = "@frame_counter"
type = "u32"

[[field]]
name = "dt"
addr = "@frame_dt"
type = "f32"
''')
for p in ('p1', 'p2'):
    chain = fields[p + '_joint_count'].split('addr = "')[1].split(' -> 0x230')[0]
    for k in KEEP:
        print(fields[p + '_' + k] + '\n')
    print(f'''[[array]]
name   = "{p}_j"  # the 22 posed joints and their transform nodes' local matrices
addr   = "{chain} -> 0x234 - 0x400 -> 0x0"
count  = 22
stride = 0x60
''')
    for f, off in [('t', '0x40'), ('q', '0x50'), ('n0', '0x34 -> 0x40'), ('n1', '0x34 -> 0x50'),
                   ('n2', '0x34 -> 0x60'), ('n3', '0x34 -> 0x70')]:
        print(f'''[[array.field]]
name = "{f}"
off  = {off if '->' not in off else '"' + off + '"'}
type = "f32x4"
''')
    for name, off in [('sq', '0x248'), ('st', '0x24c')]:
        print(f'''[[array]]
name   = "{p}_{name}"  # the snapshot buffer at motion +{off}
addr   = "{chain} -> {off} - 0x400 -> 0x0"
count  = 22
stride = 0x10

[[array.field]]
name = "v"
off  = 0x0
type = "f32x4"
''')
    print(f'''[[array]]
name   = "{p}_bone"  # the 18 ragdoll parts' rigid bodies
addr   = "{chain} -> 0x2f4 - 0x400 -> 0x0"
count  = 18
stride = 0xb0

[[array.field]]
name = "pos"
off  = "0xa4 -> 0x60"
type = "f32x3"
''')
