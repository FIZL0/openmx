"""The event tables of crates/game-sim/tests/two_p.rs, from research/c10/events.json (C10).

    python3 -B research/c10/index.py 2p --json > /dev/null && python3 -B research/c10/consts.py

Prints the Rust consts the test pastes between its `// generated` markers: every indexed event of the
capture of record, by rider and frame. Research, not product.
"""
import json

NEAR = ['fore-aft g (front)', 'fore-aft g (back)', 'side g', 'vertical g (flat)', 'ground pitch down (deg)',
        'ground pitch up (deg)', 'touch pitch down (deg)', 'touch pitch up (deg)', 'touch |roll| (deg)']
ANIMS = ['foot down (turn_stop/turn_still)', 'reverse', 'backflip clip', 'no-handed lander', 'wreck flail',
         'hold (after a wreck)', 'put-back (mode 0)']

ev = json.load(open('research/c10/events.json'))


def table(name, ty, doc, items):
    print('/// %s' % doc)
    print('const %s: &[%s] = &[' % (name, ty))
    line = '   '
    for it in items:
        s = ' %s,' % it
        if len(line) + len(s) > 110:
            print(line)
            line = '   '
        line += s
    if line.strip():
        print(line)
    print('];')


print('// generated by research/c10/consts.py from the index of the capture of record')
print('const ROWS: usize = %d;' % ev['rows'])
print('const FIRST: u32 = %d;' % ev['first'])
table('WRECKS', '(u32, u32, u32)', '(rider, frame, reason): the row the wreck reason turns non-zero.',
      ['(%d, %d, %d)' % (e['p'], e['frame'], e['reason']) for e in ev['wrecks']])
table('RAGDOLLS', '(u32, u32, u32)', '(rider, first, last frame) of each body-mode-2 stretch.',
      ['(%d, %d, %d)' % (e['p'], e['from'], e['to']) for e in ev['ragdoll']])
table('CONTACTS', '(u32, u32)', '(rider, frame): a record entry on scenery starts.',
      ['(%d, %d)' % (e['p'], e['frame']) for e in ev['contacts']])
table('NEAR', '(u32, u32, usize, f32)', '(rider, frame, clause in `NEAR_CLAUSES`, value): ridden out at half its limit or more.',
      ['(%d, %d, %d, %r)' % (e['p'], e['frame'], NEAR.index(e['clause']), e['value']) for e in ev['near']])
table('TRICKS', '(u32, u32, u32, u32)', '(rider, first, last frame, trick id) of each trick_running stretch.',
      ['(%d, %d, %d, %d)' % (e['p'], e['from'], e['to'], e['id']) for e in ev['tricks']])
table('FLIPS', '(u32, u32, u32)', '(rider, first, last frame) of each flip_on stretch.',
      ['(%d, %d, %d)' % (e['p'], e['from'], e['to']) for e in ev['flips']])
table('ANIMS', '(u32, usize, u32, u32)', '(rider, group in `ANIM_GROUPS`, first, last frame) of each stretch.',
      ['(%d, %d, %d, %d)' % (e['p'], ANIMS.index(e['what']), e['from'], e['to']) for e in ev['anims']
       if e['what'] in ANIMS])
table('LEANS', '(u32, u32, f32)', '(rider, frame, roll in radians): the three deepest leans each way, riding on the ground.',
      ['(%d, %d, %r)' % (e['p'], e['from'], e['roll']) for e in ev['anims'] if e['what'].startswith('lean')])
print('// end generated')
